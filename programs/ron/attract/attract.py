"""
ATTRACT - build hook (runs before synthesis; pure Python, no PIL/numpy).

  1. loads the text-grid art (assets/*.txt) into the shared pattern ROM
  2. assembles the game program (tools/game.py) for the game CPU
  3. writes the generated VHDL:
       attract_patrom.vhd   pattern ROM entity (font in logic, then 1 EBR per 32 patterns)
       attract_coderom.vhd  program ROM entity
       attract_pkg.vhd      3-3-2 -> YUV tables
  4. prints how full each ROM is (graphics vs code trade 1 EBR for 1 EBR)

Contact sheets and emulator previews: python3 tools/preview.py [sheet|run].
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, 'tools'))

import assets   # noqa: E402
import game     # noqa: E402

HDR = """-- Copyright (C) 2026 czartroniks
-- SPDX-License-Identifier: GPL-3.0-only
--
-- GENERATED by attract.py -- do not edit.
"""


def write(name, text):
    p = os.path.join(HERE, name)
    old = open(p).read() if os.path.exists(p) else None
    if old != text:
        with open(p, 'w') as f:
            f.write(text)


def gen_patrom(pats):
    """Patterns 0-63 are the font: one colour, so it is stored 1 bit per
    pixel as LOGIC (eight 512-bit vectors indexed by the address -- a vector
    index is a mux, not a memory, so yosys cannot put it back in an EBR).
    Patterns 64.. go to EBR chunks of 32 patterns."""
    font = []
    for p in pats[:64]:
        for w in p:
            row = 0
            for i in range(8):
                px = (w >> (14 - 2 * i)) & 3
                assert px in (0, 1), 'font glyphs must use colour 1 only'
                row |= px << (7 - i)
            font.append(row)
    words = []
    for p in pats[64:]:
        words.extend(p)
    nchunk = (len(words) + 255) // 256
    words += [0] * (nchunk * 256 - len(words))
    L = [HDR, """-- Shared pattern ROM: %d patterns of 8x8 2bpp (8 rows x 16 bits).
-- addr = pattern(8:0) & row(2:0).  q is valid 2 clocks after addr.
--   patterns 0-63 (the font): 1bpp logic ROM, pixels expanded to colour 1
--   patterns 64-%d: %d EBR chunks of 256 words (32 patterns), chunk c at
--   addr(11:8) = c + 2

library ieee;
use ieee.std_logic_1164.all;
use ieee.numeric_std.all;

entity attract_patrom is
    port (
        clk  : in  std_logic;
        addr : in  unsigned(11 downto 0);
        q    : out std_logic_vector(15 downto 0)
    );
end entity;

architecture rtl of attract_patrom is
    type t_chunk is array (0 to 255) of std_logic_vector(15 downto 0);
""" % (len(pats), len(pats) - 1, nchunk)]
    for b in range(8):
        bits = ''.join(str((r >> b) & 1) for r in font)
        L.append('    constant C_F%d : std_logic_vector(0 to 511) :=\n' % b)
        L.append('        ' + ' &\n        '.join('"%s"' % bits[i:i + 64] for i in range(0, 512, 64)) + ';\n')
    for c in range(nchunk):
        L.append('    constant C_P%d : t_chunk := (\n' % c)
        ch = words[c * 256:(c + 1) * 256]
        rows = []
        for i in range(0, 256, 8):
            rows.append('        ' + ', '.join('x"%04X"' % w for w in ch[i:i + 8]))
        L.append(',\n'.join(rows) + ');\n')
    for c in range(nchunk):
        L.append("    signal r%d : std_logic_vector(15 downto 0) := (others => '0');\n" % c)
    L.append("    signal s_fa  : unsigned(8 downto 0) := (others => '0');\n")
    L.append("    signal s_sel : unsigned(3 downto 0) := (others => '0');\n")
    L.append("    signal s_q : std_logic_vector(15 downto 0) := (others => '0');\nbegin\n")
    for c in range(nchunk):
        L.append("""    p_r%d : process(clk)
    begin
        if rising_edge(clk) then
            r%d <= C_P%d(to_integer(addr(7 downto 0)));
        end if;
    end process;
""" % (c, c, c))
    L.append("""    p_mux : process(clk)
        variable v_f : std_logic_vector(15 downto 0);
    begin
        if rising_edge(clk) then
            s_sel <= addr(11 downto 8);
            s_fa  <= addr(8 downto 0);
            v_f := (others => '0');
""")
    for b in range(8):
        L.append('            v_f(%d) := C_F%d(to_integer(s_fa));\n' % (2 * b, b))
    L.append("""            case to_integer(s_sel) is
                when 0 | 1 => s_q <= v_f;
""")
    for c in range(nchunk):
        L.append('                when %d => s_q <= r%d;\n' % (c + 2, c))
    L.append("""                when others => s_q <= (others => '0');
            end case;
        end if;
    end process;
    q <= s_q;
end architecture;
""")
    write('attract_patrom.vhd', ''.join(L))
    return nchunk


def code_chunks(n):
    """Power-of-2 chunk sizes (>= 256) covering n words, largest first."""
    sizes, base = [], 0
    for sz in (2048, 1024, 512, 256):
        while n - base >= sz or (sz == 256 and base < n):
            sizes.append(sz)
            base += sz
            if base >= n:
                break
        if base >= n:
            break
    return sizes


def gen_coderom(rom):
    sizes = code_chunks(len(rom))
    total = sum(sizes)
    words = list(rom) + [0] * (total - len(rom))
    L = [HDR, """-- Game CPU program ROM: %d of %d words used, chunks %s (16 bits = 1 EBR
-- per 256 words).  q valid 1 clock after addr (EBR register; the chunk
-- select is a small mux on the registered address).

library ieee;
use ieee.std_logic_1164.all;
use ieee.numeric_std.all;

entity attract_coderom is
    port (
        clk  : in  std_logic;
        addr : in  unsigned(11 downto 0);
        q    : out std_logic_vector(15 downto 0)
    );
end entity;

architecture rtl of attract_coderom is
""" % (len(rom), total, '+'.join(str(x) for x in sizes))]
    base = 0
    for i, sz in enumerate(sizes):
        L.append('    type t_c%d is array (0 to %d) of std_logic_vector(15 downto 0);\n' % (i, sz - 1))
        L.append('    constant C_C%d : t_c%d := (\n' % (i, i))
        ch = words[base:base + sz]
        rows = []
        for j in range(0, sz, 8):
            rows.append('        ' + ', '.join('x"%04X"' % w for w in ch[j:j + 8]))
        L.append(',\n'.join(rows) + ');\n')
        L.append("    signal r%d : std_logic_vector(15 downto 0) := (others => '0');\n" % i)
        base += sz
    L.append("    signal s_a : unsigned(11 downto 0) := (others => '0');\n")
    L.append("    signal s_q : std_logic_vector(15 downto 0) := (others => '0');\nbegin\n")
    base = 0
    for i, sz in enumerate(sizes):
        ab = sz.bit_length() - 1
        L.append("""    p_c%d : process(clk)
    begin
        if rising_edge(clk) then
            r%d <= C_C%d(to_integer(addr(%d downto 0)));
        end if;
    end process;
""" % (i, i, i, ab - 1))
    L.append("""    p_mux : process(clk)
    begin
        if rising_edge(clk) then
            s_a <= addr;
        end if;
    end process;
    p_sel : process(s_a""" + ''.join(', r%d' % i for i in range(len(sizes))) + """)
    begin
        s_q <= (others => '0');
""")
    # chunks are aligned powers of two: select on the top address bits
    # (never compare s_a with the integer end address: 4096 wraps to 0 in a
    # 12-bit unsigned compare and the last chunk silently disappears)
    base = 0
    for i, sz in enumerate(sizes):
        ab = sz.bit_length() - 1
        L.append('        if s_a(11 downto %d) = "%s" then s_q <= r%d; end if;\n'
                 % (ab, format(base >> ab, '0%db' % (12 - ab)), i))
        base += sz
    L.append("""    end process;
    q <= s_q;
end architecture;
""")
    write('attract_coderom.vhd', ''.join(L))
    return total


def yuv_tables():
    """3-3-2 -> 10-bit YUV contributions (BT.601, studio range, luma capped
    at 768).  Y = YR+YG+YB, U = UR+UG+UB, V = VR+VG+VB; offsets live in the
    R tables so black (0,0,0) is exactly 64/512/512."""
    ky, kc = 704.0, 896.0
    t = {}
    t['YR'] = [64 + round(ky * 0.299 * r / 7) for r in range(8)]
    t['YG'] = [round(ky * 0.587 * g / 7) for g in range(8)]
    t['YB'] = [round(ky * 0.114 * b / 3) for b in range(4)]
    t['UR'] = [512 + round(kc * 0.564 * -0.299 * r / 7) for r in range(8)]
    t['UG'] = [round(kc * 0.564 * -0.587 * g / 7) for g in range(8)]
    t['UB'] = [round(kc * 0.564 * 0.886 * b / 3) for b in range(4)]
    t['VR'] = [512 + round(kc * 0.713 * 0.701 * r / 7) for r in range(8)]
    t['VG'] = [round(kc * 0.713 * -0.587 * g / 7) for g in range(8)]
    t['VB'] = [round(kc * 0.713 * -0.114 * b / 3) for b in range(4)]
    # range check over all 256 colours
    for c in range(256):
        r, g, b = c >> 5, (c >> 2) & 7, c & 3
        y = t['YR'][r] + t['YG'][g] + t['YB'][b]
        u = t['UR'][r] + t['UG'][g] + t['UB'][b]
        v = t['VR'][r] + t['VG'][g] + t['VB'][b]
        assert 64 <= y <= 768 and 0 <= u <= 1023 and 0 <= v <= 1023, (c, y, u, v)
    return t


def gen_pkg():
    t = yuv_tables()
    L = [HDR, """-- 3-3-2 -> YUV (BT.601, studio range, white = 768).  Unswapped; the
-- output stage swaps U/V for the hardware.

package attract_pkg is
    type t_i8 is array (0 to 7) of integer;
    type t_i4 is array (0 to 3) of integer;
"""]
    for k in ('YR', 'YG', 'UR', 'UG', 'VR', 'VG'):
        L.append('    constant C_%s : t_i8 := (%s);\n' % (k, ', '.join(str(v) for v in t[k])))
    for k in ('YB', 'UB', 'VB'):
        L.append('    constant C_%s : t_i4 := (%s);\n' % (k, ', '.join(str(v) for v in t[k])))
    L.append('end package;\n')
    write('attract_pkg.vhd', ''.join(L))


def main():
    pats, _ = assets.load()
    rom, info = game.build()
    nchunk = gen_patrom(pats)
    depth = gen_coderom(rom)
    gen_pkg()
    print('ATTRACT: graphics %d patterns (font in logic + %d EBR, %d free patterns)'
          % (len(pats), nchunk, 64 + nchunk * 32 - len(pats)))
    print('ATTRACT: program %d / %d words (%d EBR); work RAM %d / 256 words'
          % (len(rom), depth, depth // 256, info.get('ram', 0)))
    print('ATTRACT: EBR total %d (board 8 + graphics %d + program %d)'
          % (8 + nchunk + depth // 256, nchunk, depth // 256))


if __name__ == '__main__':
    main()
