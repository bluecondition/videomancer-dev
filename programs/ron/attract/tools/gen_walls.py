"""Generate assets/walls.txt: maze-wall join tiles in several styles.

A wall tile's join mask says which neighbours are walls too: N=1 E=2 S=4 W=8.
Each style draws the same 16 joins, so the maze generator only computes the
mask and adds the style's base tile number.  Run once; the output is a normal
text-grid asset (edit by hand afterwards if a join looks wrong).
"""
import os

N, E, S, W = 1, 2, 4, 8


def thick_shape(mask, lo, hi):
    """Pixels (r, c) of a wall bar lo..hi wide, joined toward the mask's
    sides; the grid is padded by one cell so arms run off the tile."""
    s = set()
    for r in range(-1, 9):
        for c in range(-1, 9):
            inr = lo <= r <= hi
            inc = lo <= c <= hi
            if inr and inc:
                s.add((r, c))
            if inc and r < lo and mask & N:
                s.add((r, c))
            if inc and r > hi and mask & S:
                s.add((r, c))
            if inr and c > hi and mask & E:
                s.add((r, c))
            if inr and c < lo and mask & W:
                s.add((r, c))
    return s


def style_tube(mask):
    g = [['.'] * 8 for _ in range(8)]
    sh = thick_shape(mask, 3, 4)
    for (r, c) in sh:
        if 0 <= r < 8 and 0 <= c < 8:
            # bright upper/left edge, base colour lower/right
            g[r][c] = '3' if (r == 3 and (c < 3 or c > 4 or True) and not (3 <= c <= 4 and r > 4)) else '1'
    for (r, c) in sh:
        if 0 <= r < 8 and 0 <= c < 8:
            top = (r - 1, c) not in sh
            left = (r, c - 1) not in sh
            g[r][c] = '3' if (top or left) else '1'
    return g


def style_outline(mask):
    """Double-line look: the outline of a 4-px-wide bar."""
    g = [['.'] * 8 for _ in range(8)]
    sh = thick_shape(mask, 2, 5)
    for (r, c) in sh:
        if 0 <= r < 8 and 0 <= c < 8:
            nb = [(r - 1, c), (r + 1, c), (r, c - 1), (r, c + 1)]
            if any(p not in sh for p in nb):
                g[r][c] = '1'
    return g


def style_block(mask):
    """Solid 4-px bar with a light top edge and a dark core."""
    g = [['.'] * 8 for _ in range(8)]
    sh = thick_shape(mask, 2, 5)
    for (r, c) in sh:
        if 0 <= r < 8 and 0 <= c < 8:
            top = (r - 1, c) not in sh
            bot = (r + 1, c) not in sh
            g[r][c] = '3' if top else ('2' if bot else '1')
    return g


def style_dots(mask):
    """Perforated: a dotted bar."""
    g = [['.'] * 8 for _ in range(8)]
    sh = thick_shape(mask, 3, 4)
    for (r, c) in sh:
        if 0 <= r < 8 and 0 <= c < 8 and (r + c) % 2 == 0:
            g[r][c] = '1'
    return g


STYLES = [('tube', style_tube), ('outline', style_outline)]


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    out = os.path.join(here, '..', 'assets', 'walls.txt')
    lines = ['# GENERATED by tools/gen_walls.py -- maze wall joins.',
             '# Tile order per style: join mask 0..15 (N=1 E=2 S=4 W=8).',
             '# 1 = wall, 2 = shade, 3 = highlight', '']
    for name, fn in STYLES:
        for m in range(16):
            lines.append('@tile wall_%s_%d' % (name, m))
            # an isolated pillar (no wall neighbours) reads as a dot: blank
            rows = [['.'] * 8 for _ in range(8)] if m == 0 else fn(m)
            for row in rows:
                lines.append(''.join(row))
            lines.append('')
    with open(out, 'w') as f:
        f.write('\n'.join(lines))
    print('wrote', out)


if __name__ == '__main__':
    main()
