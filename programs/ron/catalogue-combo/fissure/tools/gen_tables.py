#!/usr/bin/env python3
"""Fissure colour tables: 4 metals x 64 levels {Y10, U10, V10} and 16 Prism hues.

Authored BT.601 then U/V SWAPPED for the hardware (U carries the Cr value,
V the Cb value; CLAUDE.md "Colors").  Level 0 = dark edge, 63 = highlight.
Luma is capped at 860 (the output scale takes it to ~700)."""
import math

def ycc(r, g, b):
    r, g, b = (min(max(c, 0.0), 1.0) for c in (r, g, b))
    y = 0.299*r + 0.587*g + 0.114*b
    cb = 0.564*(b - y); cr = 0.713*(r - y)
    Y = round(64 + 876*y); U = round(512 + 896*cr); V = round(512 + 896*cb)   # swapped
    return min(Y, 860), min(max(U, 4), 1019), min(max(V, 4), 1019)

metals = {
    'gold':   (212/255, 175/255, 55/255),
    'silver': (192/255, 197/255, 206/255),
    'copper': (184/255, 106/255, 58/255),
}
rows = []
for name in ('gold', 'silver', 'copper'):
    base = metals[name]
    for l in range(64):
        t = l / 63.0
        f = 0.28 + 0.92*t                      # dark bronze edge .. full metal
        w = max(0.0, (t - 0.72) / 0.28) * 0.55 # highlight whitens the top levels
        rgb = [c*f*(1 - w) + w for c in base]
        rows.append((name, l, ycc(*rgb)))
# Prism: luma ramp only (chroma comes from the hue table); neutral chroma here
for l in range(64):
    t = l / 63.0
    y = 0.25 + 0.7*t
    rows.append(('prism', l, ycc(y, y, y)))
print('    -- generated by tools/gen_tables.py: gold 0-63, silver 64-127, copper 128-191, prism luma 192-255')
print('    constant C_METAL : t_metal := (')
out = []
for i, (name, l, (Y, U, V)) in enumerate(rows):
    out.append(f'f_c({Y}, {U}, {V})')
for i in range(0, 256, 4):
    tail = ',' if i < 252 else ');'
    print('        ' + ', '.join(out[i:i+4]) + tail)
# Prism hues (swapped), saturation 0.32
print('    constant C_PRISM : t_prism := (')
ph = []
for h in range(16):
    a = 2*math.pi*h/16
    r = 0.5 + 0.5*math.cos(a); g = 0.5 + 0.5*math.cos(a - 2.094); b = 0.5 + 0.5*math.cos(a + 2.094)
    y = 0.299*r + 0.587*g + 0.114*b
    cb = 0.564*(b - y)*0.98; cr = 0.713*(r - y)*0.98
    ph.append(f'f_h({round(512 + 896*cr)}, {round(512 + 896*cb)})')
for i in range(0, 16, 8):
    tail = ',' if i < 8 else ');'
    print('        ' + ', '.join(ph[i:i+8]) + tail)
