#!/usr/bin/env python3
"""Generate the dewdrop ROM constants (palette + sine) as VHDL text.

Palette: 256-entry wrapping hue ramp (yellow -> red -> magenta -> dark ->
blue -> cyan -> green -> black -> back to yellow), BT.601 limited-range
10-bit, intensity 0.8125 (white Y ~775: the HD HDMI thick-bar rule), and
written in the HW-verified Videomancer convention: the u register carries
BT.601 Cr, the v register carries Cb.
"""
import math

KEYS = [  # (index, (r, g, b))
    (0,   (1.0, 1.0, 0.0)),   # yellow
    (40,  (1.0, 0.0, 0.0)),   # red
    (80,  (1.0, 0.0, 1.0)),   # magenta
    (104, (0.05, 0.0, 0.15)), # dark
    (120, (0.0, 0.0, 1.0)),   # blue
    (160, (0.0, 1.0, 1.0)),   # cyan
    (200, (0.0, 1.0, 0.0)),   # green
    (224, (0.0, 0.0, 0.0)),   # black
    (240, (0.3, 0.3, 0.0)),   # dark yellow
    (256, (1.0, 1.0, 0.0)),   # wrap
]
GAIN = 0.8125

def rgb_at(i):
    for (i0, c0), (i1, c1) in zip(KEYS, KEYS[1:]):
        if i0 <= i < i1:
            t = (i - i0) / (i1 - i0)
            return tuple(a + (b - a) * t for a, b in zip(c0, c1))
    raise ValueError(i)

def yuv(rgb):
    r, g, b = rgb
    y = 0.299 * r + 0.587 * g + 0.114 * b
    cb = (b - y) / 1.772
    cr = (r - y) / 1.402
    Y = int(round(64 + 876 * y * GAIN))
    Cb = int(round(512 + 896 * cb * GAIN))
    Cr = int(round(512 + 896 * cr * GAIN))
    return Y, Cr, Cb   # (y, u_reg, v_reg): u carries Cr on this hardware

def fmt(name, vals, width):
    out = [f"    constant {name} : t_rom10 := ("]
    for i in range(0, 256, 8):
        row = ", ".join(f"to_unsigned({v:4d}, {width})" for v in vals[i:i + 8])
        out.append("        " + row + ("," if i < 248 else ");"))
    return "\n".join(out)

ys, us, vs = [], [], []
for i in range(256):
    Y, U, V = yuv(rgb_at(i))
    ys.append(Y); us.append(U); vs.append(V)

sins = []
for i in range(256):
    s = int(round(255 * math.sin((i + 0.5) * 2 * math.pi / 256)))
    sins.append(s & 0x3FF)   # 10-bit two's complement

print("    -- generated by tools/gen_tables.py")
print(fmt("C_PAL_Y", ys, 10)); print()
print(fmt("C_PAL_U", us, 10)); print()
print(fmt("C_PAL_V", vs, 10)); print()
print(fmt("C_SIN", sins, 10)); print()
for name, rgb in (("pale cyan", (0.45, 1.0, 0.9)), ("deep teal", (0.0, 0.25, 0.22))):
    print(f"    -- {name}: Y,U,V = {yuv(rgb)}")
