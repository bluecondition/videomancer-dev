"""
DAZZLE v0.1.0 (Hardline) - build hook.  Writes dazzle_pkg.vhd next to this file (pure python: the builder
runs it with the system python3).  The integer model (.hardline_work/rb_dazzle/imodel.py) reads the same tables.

Package contents:
  C_DZ_EXP    256 x 16   round(32768 * 2^(i/256))                 (the stripe pitch is exponential)
  C_DZ_SIN   1024 x 16   round(16384 * sin(i * pi / 2048))        (a quarter wave; the sequencer interpolates)
  C_DZ_FILL   512 x 8    the shard fills: address = Angles & code (code = the cuts' sign bits),
                         word = 0 q1 q0 sg vb1 vb0 ua1 ua0:
                             phase = (U >> (ua - 1), 0 when ua = 0)  +/-  (V >> (vb - 1), 0 when vb = 0)  + q / 4
                         Designed offline (.hardline_work/rb_dazzle/romdesign.py, simulated annealing) so that
                         flipping any ONE code bit changes the stripe direction by at least 26 degrees:
                         neighbouring shards always conflict.  Bank 0 = Free (12 fills: 0, 90, +-45, +-26.6,
                         +-63.4 degrees at pitches x0.71 .. x2), bank 1 = Square (0, 90, +-45 only).
  C_DZ_BASE / C_DZ_RATE / C_DZ_DIST   the eight cuts: normal angle (65536 per turn), turn rate, scatter distance
"""
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))

# fill id -> (ua, vb, sign): P = (U >> (ua - 1) if ua else 0) +- (V >> (vb - 1) if vb else 0)
FILLS = [(1, 0, 1), (0, 1, 1), (1, 1, 1), (1, 1, -1), (2, 2, 1), (2, 2, -1),
         (2, 1, 1), (2, 1, -1), (1, 2, 1), (1, 2, -1), (2, 0, 1), (0, 2, 1)]
FREE = ("56208914077438ab693b7225541a4192b35130a75083651aa2496b7813360845b592508b3a0113580863410427529a67"
        "026a47148b74a629159b3a2394b0b3a115a60b4392b0ba52341a4091a14336b07a6525b02b3494876702a42358ba1996"
        "9817633a4b5804612b54a2b9700b65344132b80513ab207234b08756a125521a")
SQUARE = ("3a4b0215a2b35104a3105ba25104b43b153a4ba42002135b4b020531b34a2a1205b05aa23ba4152141a31430022b3a05"
          "2104b351b43a40b2a35b2ab45015a140b403403b4b52a51a2034134a152120035a21a2b003b0312502b531043aa4b45b"
          "2152134003102ba4b541abb54aa3b251a41a5b035145023a3002152a123b4013")

# the eight cuts: normal angle at Turn = centre (degrees), turn rate, scatter distance (screen heights)
BASE_DEG = [14.0, 104.0, 62.0, 151.0, 36.0, 128.0, 84.0, 171.0]
RATE = [1, -1, 2, -2, 3, -3, 4, -4]
DIST = [0.30, -0.42, -0.18, 0.55, -0.60, 0.24, 0.48, -0.36]


def qphase(code):
    h = (code * 0x9E5 + 0x3B) & 0xFFF
    h ^= h >> 5
    return (h * 7 >> 2) & 3


def fill_word(f, q):
    ua, vb, sg = FILLS[f]
    return (q << 5) | ((1 if sg < 0 else 0) << 4) | (vb << 2) | ua


def fill_rom():
    out = []
    for bank in (FREE, SQUARE):
        assert len(bank) == 256
        out += [fill_word(int(ch, 16), qphase(code)) for code, ch in enumerate(bank)]
    return out


def exp2_rom():
    return [int(round(32768 * 2 ** (i / 256.0))) for i in range(256)]


def sin_rom():
    return [int(round(16384 * math.sin(i * math.pi / 2048.0))) for i in range(1024)]


def base_tab():
    return [int(round(d * 65536 / 360.0)) & 0xFFFF for d in BASE_DEG]


def dist_tab():
    """D: the scatter distance in pixels (Q3) is (Sd * D) >> 9, Sd = P12 (Q3) scaled to the raster"""
    return [int(round(d * 1080 * 8 * 512 / 8184.0)) for d in DIST]


def vhd_table(name, typ, depth, width, vals):
    lines = ["    type %s is array (0 to %d) of %s(%d downto 0);" % ("t_" + name.lower(), depth - 1, typ, width - 1),
             "    constant %s : %s := (" % (name, "t_" + name.lower())]
    items = ['x"%0*X"' % (width // 4, v & ((1 << width) - 1)) for v in vals]
    for i in range(0, len(items), 16):
        lines.append("        " + ", ".join(items[i:i + 16]) + ("," if i + 16 < len(items) else ""))
    lines.append("    );")
    return "\n".join(lines)


def main():
    parts = ["-- Generated by dazzle.py -- DO NOT EDIT.",
             "library ieee;", "use ieee.std_logic_1164.all;", "use ieee.numeric_std.all;", "",
             "package dazzle_pkg is",
             vhd_table("C_DZ_EXP", "unsigned", 256, 16, exp2_rom()),
             vhd_table("C_DZ_SIN", "unsigned", 1024, 16, sin_rom()),
             vhd_table("C_DZ_FILL", "unsigned", 512, 8, fill_rom()),
             vhd_table("C_DZ_BASE", "unsigned", 8, 16, base_tab()),
             vhd_table("C_DZ_RATE", "signed", 8, 4, RATE),
             vhd_table("C_DZ_DIST", "signed", 8, 12, dist_tab()),
             "end package dazzle_pkg;", ""]
    with open(os.path.join(HERE, "dazzle_pkg.vhd"), "w") as f:
        f.write("\n".join(parts))


if __name__ == "__main__":
    main()
