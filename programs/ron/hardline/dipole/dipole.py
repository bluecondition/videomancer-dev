"""
DIPOLE v0.1.0 (Hardline) - build hook.  Writes dipole_pkg.vhd next to this file (pure python: the
builder runs it with the system python3).  The integer model reads the same formulas.

Package contents:
  C_LOGV / C_LOGS   log2(1 + i/256), Q14, value + slope        (four read ports: hi, lo of each pole)
  C_UG   / C_UGS    0.5 log2(1 + 4^-u), u = i/16 octaves      (log2 r from log2 hi; two ports)
  C_UA   / C_UAS    atan(2^-u) in 2^18 per turn               (the octant angle; two ports)
  C_TAB             512 words for the vblank sequencer: 0..255 = 2^(i/256) Q14 (the pole distance),
                    256..511 = sin(i/256 * pi/2) Q15 (a quarter sine for the axis turn)
  C_LGN6            log2(N / 2 pi), Q6, by the K3 step (N = 4 5 6 8 10 12 16 20 24 32)
"""
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))


def rom(name, vals, typ="t_dp_rom"):
    items = ['x"%04X"' % (v & 0xFFFF) for v in vals]
    s = "    constant %s : %s := (\n" % (name, typ)
    s += ",\n".join("        " + ", ".join(items[i:i + 8]) for i in range(0, len(items), 8)) + ");\n"
    return s


def main():
    o = []
    lv = [round(16384 * math.log2(1 + i / 256)) for i in range(257)]
    o.append(rom("C_LOGV", lv[:256])); o.append(rom("C_LOGS", [lv[i + 1] - lv[i] for i in range(256)]))
    g = [round(16384 * 0.5 * math.log2(1 + 4 ** (-(k / 16)))) for k in range(257)]
    a = [round(math.atan(2 ** (-(k / 16))) / (2 * math.pi) * 2 ** 18) for k in range(257)]
    o.append(rom("C_UG", g[:256])); o.append(rom("C_UGS", [g[k + 1] - g[k] for k in range(256)]))
    o.append(rom("C_UA", a[:256])); o.append(rom("C_UAS", [a[k + 1] - a[k] for k in range(256)]))
    ex = [round(16384 * 2 ** (i / 256)) for i in range(256)]
    sn = [round(32767 * math.sin(i / 256 * math.pi / 2)) for i in range(256)]
    o.append(rom("C_TAB", ex + sn, "t_dp_tab"))
    lg = [0] * 32
    for z, n in enumerate([4, 5, 6, 8, 10, 12, 16, 20, 24, 32]):
        lg[z] = round(64 * math.log2(n / (2 * math.pi)))
    o.append("    type t_dp_lgn is array (0 to 31) of integer range -64 to 255;\n")
    o.append("    constant C_LGN6 : t_dp_lgn := (\n" + ",\n".join(
        "        " + ", ".join(str(v) for v in lg[i:i + 8]) for i in range(0, 32, 8)) + ");\n")

    txt = ("-- Copyright (C) 2026 czartroniks\n-- SPDX-License-Identifier: GPL-3.0-only\n--\n"
           "-- dipole_pkg.vhd: GENERATED by dipole.py; do not edit.\n\n"
           "library ieee;\nuse ieee.std_logic_1164.all;\nuse ieee.numeric_std.all;\n\n"
           "package dipole_pkg is\n"
           "    type t_dp_rom is array (0 to 255) of std_logic_vector(15 downto 0);\n"
           "    type t_dp_tab is array (0 to 511) of std_logic_vector(15 downto 0);\n"
           + "".join(o) + "end package dipole_pkg;\n")
    with open(os.path.join(HERE, "dipole_pkg.vhd"), "w") as f:
        f.write(txt)


if __name__ == "__main__":
    main()
