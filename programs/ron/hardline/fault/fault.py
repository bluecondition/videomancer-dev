"""
FAULT v0.1.0 (Hardline) - build hook.  Writes fault_pkg.vhd next to this file (pure python: the builder runs
it with the system python3).  The integer model (.hardline_work/rb_fault/imodel.py) reads the same tables.

Package contents (all block-RAM ROMs, 16-bit words):
  C_FT_LOGV / C_FT_LOGS   256   log2(1 + i/256), Q14, and its segment slope      (the log-polar engine, as Hypnos)
  C_FT_UG   / C_FT_UGS    256   0.5 log2(1 + 4^-u), u in 1/16 octaves, Q14, and its slope
  C_FT_EXM  / C_FT_EXS    256   2^(i/256), Q14, and its slope
  C_FT_TAB                512   round(16384 sin(i pi / 1024)): a quarter wave (the sequencer's cut direction)
  C_FT_HT                 64    0.5 log2(1 + 2^(-2 d)), d in 1/16 octaves, Q6    (gradient combine)
"""
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))


def tables():
    lv = [round(16384 * math.log2(1 + i / 256)) for i in range(257)]
    g = [round(16384 * 0.5 * math.log2(1 + 4 ** (-(k / 16)))) for k in range(257)]
    em = [round(16384 * 2 ** (i / 256)) for i in range(257)]
    sn = [round(16384 * math.sin(i * math.pi / 1024)) for i in range(512)]
    return {
        "LOGV": lv[:256], "LOGS": [lv[i + 1] - lv[i] for i in range(256)],
        "UG": g[:256], "UGS": [g[k + 1] - g[k] for k in range(256)],
        "EXM": em[:256], "EXS": [em[i + 1] - em[i] for i in range(256)],
        "TAB": sn,
        "HT": [round(64 * 0.5 * math.log2(1 + 2 ** (-2 * (4 * k) / 64))) for k in range(64)],
    }


def rom(name, vals, n):
    items = ['x"%04X"' % (v & 0xFFFF) for v in vals]
    assert len(items) == n
    s = "    constant %s : t_ft_rom%d := (\n" % (name, n)
    return s + ",\n".join("        " + ", ".join(items[i:i + 8]) for i in range(0, n, 8)) + ");\n"


def main():
    t = tables()
    o = ["-- Copyright (C) 2026 czartroniks\n-- SPDX-License-Identifier: GPL-3.0-only\n--\n"
         "-- fault_pkg.vhd: GENERATED by fault.py (do not edit)\n\n"
         "library ieee;\nuse ieee.std_logic_1164.all;\nuse ieee.numeric_std.all;\n\npackage fault_pkg is\n"
         "    type t_ft_rom256 is array (0 to 255) of std_logic_vector(15 downto 0);\n"
         "    type t_ft_rom512 is array (0 to 511) of std_logic_vector(15 downto 0);\n"
         "    type t_ft_ht is array (0 to 63) of unsigned(5 downto 0);\n"]
    for k in ("LOGV", "LOGS", "UG", "UGS", "EXM", "EXS"):
        o.append(rom("C_FT_" + k, t[k], 256))
    o.append(rom("C_FT_TAB", t["TAB"], 512))
    o.append("    constant C_FT_HT : t_ft_ht := (\n" + ",\n".join(
        "        " + ", ".join("to_unsigned(%d, 6)" % v for v in t["HT"][i:i + 8]) for i in range(0, 64, 8)) + ");\n")
    o.append("end package fault_pkg;\n")
    with open(os.path.join(HERE, "fault_pkg.vhd"), "w") as f:
        f.write("".join(o))


if __name__ == "__main__":
    main()
