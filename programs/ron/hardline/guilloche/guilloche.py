"""
GUILLOCHE v0.1.0 (Hardline) - build hook.  Writes guilloche_pkg.vhd next to this file (pure python: the builder
runs it with the system python3).  The integer model (.hardline_work/rb_guilloche/imodel.py, tables.py) builds
the same tables.

Package contents:
  C_GU_EXP   256 x 16    round(32768 * 2^(i/256))                  (Period is exponential; the Drift mantissa)
  C_GU_SIN   1024 x 16   h(s) = acos(s) / 2 pi, Q0.16 cycles         s = i / 512 - 1: the half-width of the
  C_GU_CYC   1024 x 16   h(s) = (acos(s) - sqrt(1 - s^2)) / 2 pi     cam above level s (sine; cycloid, cusps up)
  C_GU_RR    32 x 5      1 / (q (1 + (m + 1/2) / 16)), q = 1: x 16; q = 3: x 64 (the footprint reciprocal)
  per K4 step (8 entries): lace copy counts and the shift-add forms of rho = M lam / lam_i and of M,
  and the drift ratios of laces 1 and 2 (Q16).
"""
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))

MLIST = [2, 3, 4, 6, 8, 12, 16, 24]          # K4 Lines: copies in lace 0
M2LIST = [2, 2, 2, 4, 4, 6, 8, 12]           # copies in laces 1 and 2 (even: no lace inverts the band below it)
FORMS = [(300, 118), (1200, 470)]            # Form: Bands / Sheet: (band pitch, lace-0 amplitude), virtual px
AMPF = (1.0, 0.62, 0.34)                     # lace amplitudes
GAP, RULE = 8, 8                             # the ruled frame: gap from the lace, rule width (virtual px)


def exp_rom():
    return [int(round(32768 * 2 ** (i / 256.0))) for i in range(256)]


def h_sin(s):
    return math.acos(s) / (2 * math.pi)


def h_cyc(s):
    return (math.acos(s) - math.sqrt(max(1 - s * s, 0.0))) / (2 * math.pi)


def h_rom(fn):
    return [min(32768, int(round(65536 * fn(i / 512.0 - 1.0)))) for i in range(1024)]


def rr_rom():
    """1 / (q m), m = 1 + (wm + 1/2) / 16 (the footprint mantissa): q = 1: x 16 (16 .. 8); q = 3: x 64 (21 .. 11)."""
    out = []
    for q in (1, 3):
        for wm in range(16):
            m = 1.0 + (wm + 0.5) / 16.0
            v = 16.0 / m if q == 1 else 64.0 / (3.0 * m)
            out.append(int(round(v)))
    return out


def qk(r):
    for q in (1, 3):
        for k in range(-1, 6):
            if abs(q * 2.0 ** k - r) < 1e-9:
                return q, k
    raise ValueError(r)


def lace_rows():
    """per K4 step: Mq (4 M0, 2 M1, M2), rho (q, k) per lace, M (q, j) per lace, drift ratios r1, r2."""
    rows = []
    for mi in range(8):
        m0, m1 = MLIST[mi], M2LIST[mi]
        rho = [qk(m0), qk(m1 / 2.0), qk(m1 / 4.0)]
        mm = [qk(m0), qk(m1), qk(m1)]
        r1 = int(round(0.75 * (m1 / 2.0) / m0 * 65536))
        r2 = int(round(2.0 / 3.0 * (m1 / 4.0) / m0 * 65536))
        rows.append(dict(mq=(4 * m0, 2 * m1, m1), rho=rho, mm=mm, r1=r1, r2=r2))
    return rows


def vhd_table(name, depth, width, vals):
    lines = ["    type %s is array (0 to %d) of unsigned(%d downto 0);" % ("t_" + name.lower(), depth - 1, width - 1),
             "    constant %s : %s := (" % (name, "t_" + name.lower())]
    if width % 4 == 0:
        items = ['x"%0*X"' % (width // 4, v) for v in vals]
    else:
        items = ['%dx"%0*X"' % (width, (width + 3) // 4, v) for v in vals]
    for i in range(0, len(items), 16):
        lines.append("        " + ", ".join(items[i:i + 16]) + ("," if i + 16 < len(items) else ""))
    lines.append("    );")
    return "\n".join(lines)


def int_table(name, vals):
    return "    constant %s : t_gu_i8 := (%s);" % (name, ", ".join(str(v) for v in vals))


def main():
    rows = lace_rows()
    parts = ["-- Generated by guilloche.py -- DO NOT EDIT.",
             "library ieee;", "use ieee.std_logic_1164.all;", "use ieee.numeric_std.all;", "",
             "package guilloche_pkg is",
             vhd_table("C_GU_EXP", 256, 16, exp_rom()),
             vhd_table("C_GU_SIN", 1024, 16, h_rom(h_sin)),
             vhd_table("C_GU_CYC", 1024, 16, h_rom(h_cyc)),
             vhd_table("C_GU_RR", 32, 5, rr_rom()),
             "    type t_gu_i8 is array (0 to 7) of integer;"]
    for i in range(3):
        parts.append(int_table("C_GU_MQ%d" % i, [r["mq"][i] for r in rows]))
        parts.append(int_table("C_GU_RQ%d" % i, [1 if r["rho"][i][0] == 3 else 0 for r in rows]))
        parts.append(int_table("C_GU_RK%d" % i, [r["rho"][i][1] for r in rows]))
        parts.append(int_table("C_GU_HQ%d" % i, [1 if r["mm"][i][0] == 3 else 0 for r in rows]))
        parts.append(int_table("C_GU_HJ%d" % i, [r["mm"][i][1] for r in rows]))
        parts.append(int_table("C_GU_MC%d" % i, [r["mm"][i][0] * 2 ** r["mm"][i][1] for r in rows]))
    fl = []
    for pitch, a0 in FORMS:
        fl.append(dict(pitch=pitch * 256, half=pitch * 128, a0=a0 * 256, r0=(a0 + GAP) * 256, r1=(a0 + GAP + RULE) * 256,
                       inva=[int(round((1 << 20) / (a0 * af))) for af in AMPF]))
    parts.append("    type t_gu_i2 is array (0 to 1) of integer;")
    for f in fl:
        f["rc"] = (f["r0"] + f["r1"]) // 2
        f["hwr"] = (f["r1"] - f["r0"]) // 2
    for key in ("pitch", "half", "a0", "rc", "hwr"):
        parts.append("    constant C_GU_%s : t_gu_i2 := (%d, %d);" % (key.upper(), fl[0][key], fl[1][key]))
    for i in range(3):
        parts.append("    constant C_GU_INVA%d : t_gu_i2 := (%d, %d);" % (i, fl[0]["inva"][i], fl[1]["inva"][i]))
    parts.append(int_table("C_GU_DR1", [r["r1"] for r in rows]))
    parts.append(int_table("C_GU_DR2", [r["r2"] for r in rows]))
    parts += ["end package guilloche_pkg;", ""]
    with open(os.path.join(HERE, "guilloche_pkg.vhd"), "w") as f:
        f.write("\n".join(parts))


if __name__ == "__main__":
    main()
