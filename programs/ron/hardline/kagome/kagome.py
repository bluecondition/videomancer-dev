"""
KAGOME v0.1.0 (Hardline) - build hook.  Writes kagome_pkg.vhd next to this file (pure python: the builder
runs it with the system python3).  The integer model (.hardline_work/rb_kagome/imodel.py) reads the same tables.
Package contents:
  C_KG_EXP    256 x 16   round(32768 * 2^(i/256))     (pitch, pixel scale and drift speed are exponential)
  C_KG_SIN   1024 x 16   round(16384 * sin(i * pi / 2048))   (a quarter wave; the sequencer interpolates)
  C_KG_SHD     64 x 8    the cane ramp gain for Weave = (i * 128 + 64) / 8 counts: q = 2^20 / hw0 (Q14 half-width)
                         as a 4-bit mantissa (low nibble) and exponent msb(q) - 3 (high nibble); level = (W * mq) >> (14 - e)
"""
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))


def exp2_rom():
    return [int(round(32768 * 2 ** (i / 256.0))) for i in range(256)]


def sin_rom():
    return [int(round(16384 * math.sin(i * math.pi / 2048.0))) for i in range(1024)]


def hw0_q14(gw):
    """strip half-width (Q14 cycles) for the glided Weave value gw (Q3, 0 .. 8184)"""
    return 410 + ((gw * 13107) >> 15) + ((max(0, gw - 4092) * 19661) >> 15)


def shade_rom():
    out = []
    for i in range(64):
        q = (1 << 20) // hw0_q14(i * 128 + 64)
        e = q.bit_length() - 1 - 3
        out.append((e << 4) | (q >> e))
    return out


def vhd_table(name, typ, depth, width, vals):
    lines = ["    type %s is array (0 to %d) of %s(%d downto 0);" % ("t_" + name.lower(), depth - 1, typ, width - 1),
             "    constant %s : %s := (" % (name, "t_" + name.lower())]
    items = ['x"%0*X"' % (width // 4, v & ((1 << width) - 1)) for v in vals]
    for i in range(0, len(items), 16):
        lines.append("        " + ", ".join(items[i:i + 16]) + ("," if i + 16 < len(items) else ""))
    lines.append("    );")
    return "\n".join(lines)


def main():
    parts = ["-- Generated by kagome.py -- DO NOT EDIT.",
             "library ieee;", "use ieee.std_logic_1164.all;", "use ieee.numeric_std.all;", "",
             "package kagome_pkg is",
             vhd_table("C_KG_EXP", "unsigned", 256, 16, exp2_rom()),
             vhd_table("C_KG_SIN", "unsigned", 1024, 16, sin_rom()),
             vhd_table("C_KG_SHD", "unsigned", 64, 8, shade_rom()),
             "end package kagome_pkg;", ""]
    with open(os.path.join(HERE, "kagome_pkg.vhd"), "w") as f:
        f.write("\n".join(parts))


if __name__ == "__main__":
    main()
