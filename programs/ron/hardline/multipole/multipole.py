"""
MULTIPOLE v0.1.0 (Hardline) - build hook.  Writes multipole_pkg.vhd next to this file (pure python: the
builder runs it with the system python3).  The integer model reads the same formulas.

Package contents (256 x 16 block-RAM ROMs, value + slope pairs for piecewise-linear lookups):
  C_LOGV / C_LOGS   log2(1 + i/256), Q14                      (three read ports: hi, lo, the folded angle)
  C_UG   / C_UGS    0.5 log2(1 + 4^-u), u = i/16 octaves      (log2 r from log2 hi)
  C_UA   / C_UAS    atan(2^-u) in 2^18 per turn               (the octant angle)
  C_EXM  / C_EXS    2^(i/256), Q14                            (two read ports: the Re and Im phases)
  C_LCV  / C_LCS    -log2 cos(x), x = (pi/4) i/256, Q14
  C_SNT             -log2(sin(x)/x): slope (Q14, 5 bits) & value (Q13, 11 bits) in one word
"""
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))


def rom(name, vals):
    assert len(vals) == 256
    items = ['x"%04X"' % (v & 0xFFFF) for v in vals]
    s = "    constant %s : t_mp_rom := (\n" % name
    s += ",\n".join("        " + ", ".join(items[i:i + 8]) for i in range(0, 256, 8)) + ");\n"
    return s


def main():
    o = []
    lv = [round(16384 * math.log2(1 + i / 256)) for i in range(257)]
    o.append(rom("C_LOGV", lv[:256])); o.append(rom("C_LOGS", [lv[i + 1] - lv[i] for i in range(256)]))
    g = [round(16384 * 0.5 * math.log2(1 + 4 ** (-(k / 16)))) for k in range(257)]
    a = [round(math.atan(2 ** (-(k / 16))) / (2 * math.pi) * 2 ** 18) for k in range(257)]
    o.append(rom("C_UG", g[:256])); o.append(rom("C_UGS", [g[k + 1] - g[k] for k in range(256)]))
    o.append(rom("C_UA", a[:256])); o.append(rom("C_UAS", [a[k + 1] - a[k] for k in range(256)]))
    em = [round(16384 * 2 ** (i / 256)) for i in range(257)]
    o.append(rom("C_EXM", em[:256])); o.append(rom("C_EXS", [em[i + 1] - em[i] for i in range(256)]))
    lc = [round(-16384 * math.log2(math.cos(math.pi / 4 * i / 256))) for i in range(257)]
    o.append(rom("C_LCV", lc[:256])); o.append(rom("C_LCS", [lc[i + 1] - lc[i] for i in range(256)]))

    def sinc(i):
        x = math.pi / 4 * i / 256
        return 0.0 if i == 0 else -math.log2(math.sin(x) / x)
    s14 = [16384 * sinc(i) for i in range(257)]
    snv = [round(s14[i] / 2) for i in range(256)]
    sns = [round(s14[i + 1] - s14[i]) for i in range(256)]
    assert max(snv) < 2048 and max(sns) < 32 and max(lc) < 16384
    o.append(rom("C_SNT", [(sns[i] << 11) | snv[i] for i in range(256)]))

    txt = ("-- Copyright (C) 2026 czartroniks\n-- SPDX-License-Identifier: GPL-3.0-only\n--\n"
           "-- multipole_pkg.vhd: GENERATED by multipole.py; do not edit.\n\n"
           "library ieee;\nuse ieee.std_logic_1164.all;\nuse ieee.numeric_std.all;\n\n"
           "package multipole_pkg is\n"
           "    type t_mp_rom is array (0 to 255) of std_logic_vector(15 downto 0);\n"
           + "".join(o) + "end package multipole_pkg;\n")
    with open(os.path.join(HERE, "multipole_pkg.vhd"), "w") as f:
        f.write(txt)


if __name__ == "__main__":
    main()
