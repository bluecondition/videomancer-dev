"""
SCALLOP v0.1.0 (Hardline) - build hook.  Writes scallop_pkg.vhd next to this file (pure python: the builder
runs it with the system python3).  The integer model (.hardline_work/rb_scallop/imodel.py) reads the same tables.

Package contents:
  C_SC_EXP   256 x 16   round(32768 * 2^(i/256))       (radius, fan and overlap are exponential)
  C_SC_Y     128 x 10   tone 0 .. 64 -> luma 64 .. 939 (white lands on 775 after the output scaling)
  C_SC_INVN  8 x 17     round(65536 / n), n = 1 .. 8   (the keyline's width in scale radii)
  C_SC_SQ    512 x 16   0 .. 255: i^2 (the squarers' high part, Round);  256 .. 511: i * 128 (Pointed: |dx| itself)
  C_SC_RTV   512 x 16   round(4096 * sqrt(i / 256))    (square root of a Q1.16 sum by its top 9 bits ...)
  C_SC_RTS   512 x 8    ... and the step to the next entry, for the 6-bit linear interpolation
"""
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))
C_SL = 19        # the pixel stage that adds the camera phase (the model aligns the luma stream with it)


def exp2_rom():
    return [int(round(32768 * 2 ** (i / 256.0))) for i in range(256)]


def y_rom():
    return [64 + ((min(v, 64) * 875 + 32) >> 6) for v in range(128)]


def invn_rom():
    """index n (0 unused)."""
    return [0] + [int(round(65536.0 / n)) for n in range(1, 9)]


def sq_rom():
    return [i * i for i in range(256)] + [i * 128 for i in range(256)]


def rtv_rom():
    return [int(round(4096 * math.sqrt(i / 256.0))) for i in range(512)]


def rts_rom():
    v = rtv_rom() + [int(round(4096 * math.sqrt(2.0)))]
    return [min(v[i + 1] - v[i], 255) for i in range(512)]


def vhd_table(name, depth, width, vals):
    digits = (width + 3) // 4
    lines = ["    type %s is array (0 to %d) of unsigned(%d downto 0);" % ("t_" + name.lower(), depth - 1, width - 1),
             "    constant %s : %s := (" % (name, "t_" + name.lower())]
    if width % 4 == 0:
        items = ['x"%0*X"' % (digits, v) for v in vals]
    else:
        items = ['"' + format(v, "0%db" % width) + '"' for v in vals]
    per = 16 if width % 4 == 0 else 8
    for i in range(0, len(items), per):
        lines.append("        " + ", ".join(items[i:i + per]) + ("," if i + per < len(items) else ""))
    lines.append("    );")
    return "\n".join(lines)


def main():
    parts = ["-- Generated by scallop.py -- DO NOT EDIT.",
             "library ieee;", "use ieee.std_logic_1164.all;", "use ieee.numeric_std.all;", "",
             "package scallop_pkg is",
             vhd_table("C_SC_EXP", 256, 16, exp2_rom()),
             vhd_table("C_SC_Y", 128, 10, y_rom()),
             vhd_table("C_SC_INVN", 8, 17, invn_rom()[1:]),
             vhd_table("C_SC_SQ", 512, 16, sq_rom()),
             vhd_table("C_SC_RTV", 512, 16, rtv_rom()),
             vhd_table("C_SC_RTS", 512, 8, rts_rom()),
             "end package scallop_pkg;", ""]
    with open(os.path.join(HERE, "scallop_pkg.vhd"), "w") as f:
        f.write("\n".join(parts))


if __name__ == "__main__":
    main()
