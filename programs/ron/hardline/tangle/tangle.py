"""
TANGLE v0.1.0 (Hardline) - build hook.  Writes tangle_pkg.vhd next to this file (pure python: the builder
runs it with the system python3).  The integer model (.hardline_work/rb_tangle/imodel.py) reads the same tables.

Package contents:
  C_TG_EXP   256 x 16    round(32768 * 2^(i/256))            (the tile size is exponential in K3)
  C_TG_Y     256 x 16    64 + round(i * 876 / 255)           (coverage 0 .. 255 -> luma, black 64 .. white 940)
  C_TG_YS    512 x 16    0 .. 255: the same;  256 + k * 64 + c: step k (0 .. 2) of the 4-step shade plus its
                         edge coverage c (0 .. 63): 64 + round((85 k + 85 c / 63) * 876 / 255)
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))


def exp2_rom():
    return [int(round(32768 * 2 ** (i / 256.0))) for i in range(256)]


def y_rom():
    return [64 + int(round(i * 876 / 255.0)) for i in range(256)]


def ys_rom():
    out = y_rom()
    for k in range(4):
        for c in range(64):
            out.append(64 + int(round(min(k * 85 + c * 85 / 63.0, 255.0) * 876 / 255.0)))
    return out


def vhd_table(name, typ, depth, width, vals):
    lines = ["    type %s is array (0 to %d) of %s(%d downto 0);" % ("t_" + name.lower(), depth - 1, typ, width - 1),
             "    constant %s : %s := (" % (name, "t_" + name.lower())]
    items = ['x"%0*X"' % (width // 4, v) for v in vals]
    for i in range(0, len(items), 16):
        lines.append("        " + ", ".join(items[i:i + 16]) + ("," if i + 16 < len(items) else ""))
    lines.append("    );")
    return "\n".join(lines)


def main():
    parts = ["-- Generated by tangle.py -- DO NOT EDIT.",
             "library ieee;", "use ieee.std_logic_1164.all;", "use ieee.numeric_std.all;", "",
             "package tangle_pkg is",
             vhd_table("C_TG_EXP", "unsigned", 256, 16, exp2_rom()),
             vhd_table("C_TG_Y", "unsigned", 256, 16, y_rom()),
             vhd_table("C_TG_YS", "unsigned", 512, 16, ys_rom()),
             "end package tangle_pkg;", ""]
    with open(os.path.join(HERE, "tangle_pkg.vhd"), "w") as f:
        f.write("\n".join(parts))


if __name__ == "__main__":
    main()
