"""
TWEED v0.1.0 (Hardline) - build hook.  Writes tweed_pkg.vhd next to this file (pure python: the builder runs
it with the system python3).  The integer model (.hardline_work/rb_tweed/imodel.py) builds the same tables.

Package contents:
  C_TW_TAB   512 x 16   0 .. 255:   round(32768 * 2^(i/256))          (the thread size is exponential)
                        256 .. 511: round(32768 * sin(i * pi / 512))  (a quarter wave for the Turn; the
                                                                        sequencer interpolates it)
  C_TW_WV    256 x 8    [weave * 8 + row] -> bit k = column k, 1 = the warp thread is on top (8 x 8 drafts)
  C_TW_SEQ   8 x 16     the colour orders: bit k = thread k is light (used for warp and weft alike)
"""
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))

PERM = [0, 1, 3, 2]
WEAVES = [
    ("Plain",   lambda i, j: (i + j) % 2 == 0),
    ("Basket",  lambda i, j: ((i // 2) + (j // 2)) % 2 == 0),
    ("Twill",   lambda i, j: ((i - j) % 4) < 2),                  # 2/2 twill
    ("Warp",    lambda i, j: ((i - j) % 4) < 3),                  # 3/1 twill (warp-faced)
    ("Broken",  lambda i, j: ((PERM[i % 4] - j) % 4) < 2),        # broken 2/2 twill
    ("Wide",    lambda i, j: ((i - j) % 8) < 4),                  # 4/4 twill
    ("Weft",    lambda i, j: ((i - j) % 4) == 2),                 # 1/3 twill (weft-faced)
    ("Satin",   lambda i, j: ((3 * i - j) % 8) != 0),             # 8-end satin (warp-faced)
]
ORDERS = [("1:1", "DL"), ("2:2", "DDLL"), ("3:1", "DDDL"), ("4:4", "DDDDLLLL"), ("Glen", "DDDDLLLLDDLLDDLL"),
          ("Cabin", "DLDLDLDLLDLDLDLD"), ("1:3", "DLLL"), ("8:8", "DDDDDDDDLLLLLLLL")]


def exp_rom():
    return [int(round(32768 * 2 ** (i / 256.0))) for i in range(256)]


def sin_rom():
    return [int(round(32768 * math.sin(i * math.pi / 512.0))) for i in range(256)]


def weave_rows():
    out = []
    for _, fn in WEAVES:
        for j in range(8):
            out.append(sum((1 << i) for i in range(8) if fn(i, j)))
    return out + [0] * (256 - 64)


def order_masks():
    out = []
    for _, s in ORDERS:
        s = (s * 16)[:16]
        out.append(sum((1 << k) for k in range(16) if s[k] == "L"))
    return out


def vhd_table(name, typ, depth, width, vals):
    lines = ["    type %s is array (0 to %d) of %s(%d downto 0);" % ("t_" + name.lower(), depth - 1, typ, width - 1),
             "    constant %s : %s := (" % (name, "t_" + name.lower())]
    items = ['x"%0*X"' % (width // 4, v) for v in vals]
    for i in range(0, len(items), 16):
        lines.append("        " + ", ".join(items[i:i + 16]) + ("," if i + 16 < len(items) else ""))
    lines.append("    );")
    return "\n".join(lines)


def main():
    parts = ["-- Generated by tweed.py -- DO NOT EDIT.",
             "library ieee;", "use ieee.std_logic_1164.all;", "use ieee.numeric_std.all;", "",
             "package tweed_pkg is",
             vhd_table("C_TW_TAB", "unsigned", 512, 16, exp_rom() + sin_rom()),
             vhd_table("C_TW_WV", "std_logic_vector", 256, 8, weave_rows()),
             vhd_table("C_TW_SEQ", "std_logic_vector", 8, 16, order_masks()),
             "end package tweed_pkg;", ""]
    with open(os.path.join(HERE, "tweed_pkg.vhd"), "w") as f:
        f.write("\n".join(parts))


if __name__ == "__main__":
    main()
