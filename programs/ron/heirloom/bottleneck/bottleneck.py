def u(v, w):
    return v & ((1 << w) - 1)

def hexs(v, w):
    n = (w + 3) // 4
    return 'x"%0*X"' % (n, u(v, 4 * n)) if w % 4 == 0 else '"%s"' % format(u(v, w), '0%db' % w)

def table(name, depth, width, vals):
    vals = list(vals) + [0] * (depth - len(vals))
    t = '    type t_%s is array (0 to %d) of std_logic_vector(%d downto 0);\n' % (name.lower(), depth - 1, width - 1)
    t += '    constant %s : t_%s := (\n' % (name, name.lower())
    rows = []
    for i in range(0, depth, 8):
        rows.append('        ' + ', '.join(hexs(v, width) for v in vals[i:i + 8]))
    return t + ',\n'.join(rows) + '\n    );\n'

