import os

HERE = os.path.dirname(os.path.abspath(__file__))

# one coloured part (fraction, rgb), re-proportioned from the photo's lens-column profile
SEQ = [(0.03, (190, 40, 12)), (0.06, (243, 168, 10)), (0.035, (110, 36, 30)), (0.17, (240, 232, 230)),
       (0.035, (120, 50, 45)), (0.07, (252, 60, 4)), (0.07, (252, 14, 3)), (0.03, (40, 6, 2)),
       (0.07, (250, 18, 2)), (0.06, (252, 70, 4)), (0.035, (120, 40, 30)), (0.17, (240, 232, 230)),
       (0.035, (110, 50, 40)), (0.06, (246, 140, 8)), (0.05, (220, 40, 8))]
BLACK = (12, 8, 9)
DARK = (70, 14, 10)

def ice(rgb):
    r, g, b = rgb
    return (min(255, int(b * 0.55)), min(255, int(g * 0.9 + 20)), min(255, int(r * 1.0 + 30)))

def rgb_to_hw10(rgb):
    r, g, b = [c / 255.0 for c in rgb]
    y = 0.299 * r + 0.587 * g + 0.114 * b
    cb = (b - y) / 1.772
    cr = (r - y) / 1.402
    return int(round(64 + y * 876)), int(round(512 + cr * 896)), int(round(512 + cb * 896))

def prescale(yuv):
    y, u, v = yuv
    y = 64 + (y - 64) * 16.0 / 13.0
    return (min(940, max(64, int(round(y)))), min(1023, max(0, u)), min(1023, max(0, v)))

def word(yuv):
    y, u, v = yuv
    return (y << 22) | (u << 12) | (v << 2)

def part(n):
    tot = sum(f for f, c in SEQ)
    edges = [0.0]
    for f, c in SEQ:
        edges.append(edges[-1] + f / tot)
    out = []
    for i in range(n):
        s = (i + 0.5) / n
        j = 0
        while j < len(SEQ) - 1 and s >= edges[j + 1]:
            j += 1
        out.append(SEQ[j][1])
    return out

def pal_rom():
    a = part(256)
    out = [word(prescale(rgb_to_hw10(c))) for c in a]
    out += [word(prescale(rgb_to_hw10(ice(c)))) for c in a]
    return out

def base_rom():
    return [word(prescale(rgb_to_hw10(c))) for c in (BLACK, DARK, ice(BLACK), ice(DARK))]

def exp2_rom():
    return [int(round(32768 * 2 ** (i / 256.0))) for i in range(256)]

def kinv_rom():
    out = []
    for i in range(256):
        k = 65536.0 / (256 - min(i, 224))
        for e in (3, 4, 5):
            m = int(round(k / 2 ** e))
            if m <= 63:
                break
        out.append(((e - 3) << 6) | min(63, m))
    return out

def vhd_table(name, typ, depth, width, vals):
    lines = ["    type %s is array (0 to %d) of %s(%d downto 0);" % ("t_" + name.lower(), depth - 1, typ, width - 1),
             "    constant %s : %s := (" % (name, "t_" + name.lower())]
    items = ['x"%0*X"' % ((width + 3) // 4, v) if width % 4 == 0 else 'to_unsigned(%d, %d)' % (v, width) for v in vals]
    for i in range(0, len(items), 16):
        lines.append("        " + ", ".join(items[i:i + 16]) + ("," if i + 16 < len(items) else ""))
    lines.append("    );")
    return "\n".join(lines)

def main():
    parts = ["-- Generated by carpet.py -- DO NOT EDIT.",
             "library ieee;", "use ieee.std_logic_1164.all;", "use ieee.numeric_std.all;", "",
             "package carpet_pkg is",
             vhd_table("C_CP_EXP2", "unsigned", 256, 16, exp2_rom()),
             vhd_table("C_CP_KINV", "unsigned", 256, 8, kinv_rom()),
             vhd_table("C_CP_PAL", "std_logic_vector", 512, 32, pal_rom()),
             vhd_table("C_CP_BASE", "std_logic_vector", 4, 32, base_rom()),
             "end package carpet_pkg;", ""]
    with open(os.path.join(HERE, "carpet_pkg.vhd"), "w") as f:
        f.write("\n".join(parts))

if __name__ == "__main__":
    main()
