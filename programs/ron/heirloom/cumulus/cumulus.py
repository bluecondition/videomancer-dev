def ycc(rgb):
    r, g, b = [max(0.0, min(255.0, c)) / 255.0 for c in rgb]
    y = 0.299 * r + 0.587 * g + 0.114 * b
    return y, (b - y) / 1.772, (r - y) / 1.402


def hw10(rgb):
    """rgb -> hardware (Y pre-scaled 16/13 x 0.89, capped 940; U = Cr, V = Cb)"""
    y, cb, cr = ycc(rgb)
    yy = 64 + y * 876
    yy = 64 + (yy - 64) * 16.0 / 13.0 * 0.89          # 0.89: the still's white (865) lands on the 940 cap
    yy = max(64, min(940, int(round(yy))))
    u = max(4, min(1020, int(round(512 + cr * 896))))
    v = max(4, min(1020, int(round(512 + cb * 896))))
    return yy, u, v


def word(t):
    y, u, v = t
    return (y << 22) | (u << 12) | (v << 2)


def pal_rgb(pal, i):
    P = PALS[pal]
    if i < 64:
        f = i / 63.0
        return tuple(P['bandA'][k] * (1 - f) + P['bandB'][k] * f for k in range(3))
    if i < 96:
        s, r = (i - 64) >> 3, (i - 64) & 7
        f = s / 3.0
        base = [P['blue'][k] * (1 - f) + P['shadow'][k] * f for k in range(3)]
        rr = (r - 3.5) / 3.5
        return tuple(base[k] + rr * P['rip'][k] * 0.5 for k in range(3))
    j = i - 96
    return P[SPECIALS[j]] if j < len(SPECIALS) else (0, 0, 0)


def pal_words():
    return [word(hw10(pal_rgb(p, i))) for p in range(2) for i in range(128)]


def blob_words():
    return [((c & 0xFFF) << 12) | (w & 0xFFF) for c, w in BLOB]


def t2_words():
    return [int(round(t * t * 4095.0 / (1023.0 * 1023.0))) for t in range(1024)]


def sc_words():
    return [int(round(255 * (1 - math.cos(2 * math.pi * i / 256.0)) / 2)) for i in range(256)]


def exp2_words():
    return [min(65535, int(round(32768 * 2 ** (i / 256.0)))) for i in range(256)]


def vhd_array(name, words, width, typ):
    lines = ['    type %s is array (0 to %d) of std_logic_vector(%d downto 0);' % (typ, len(words) - 1, width - 1),
             '    constant %s : %s := (' % (name, typ)]
    hexw = (width + 3) // 4
    body = []
    for k in range(0, len(words), 8):
        chunk = words[k:k + 8]
        if width % 4 == 0:
            body.append('        ' + ', '.join('x"%0*X"' % (hexw, w) for w in chunk))
        else:
            body.append('        ' + ', '.join('"%s"' % format(w, '0%db' % width) for w in chunk))
    lines.append(',\n'.join(body))
    lines.append('    );')
    return '\n'.join(lines)


