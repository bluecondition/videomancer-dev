def sat(v, lo, hi):
    return max(lo, min(hi, v))


def tables():
    lt = []
    for i in range(512):
        y = (i + 0.5) * 1080 / 512
        vr = VR[i] & 0xFFF
        gbg = sat(int(round(pl(y, GBG) * 255)), 0, 255)
        bbg = 32 if y < 14 else 0                         # the top strip's blue (x4 = 128)
        gate = sat(int(round(min(1.0, max(0.0, (300 - y) / 120)) * min(1.0, max(0.0, (y - 30) / 20)) * 63)), 0, 63)
        lt.append((vr << 20) | (gbg << 12) | (bbg << 6) | gate)
    gx = []
    for a in range(512):
        F = a * 2 / 512.0
        g = sat(int(round(pl(F, GX) * 255)), -128, 127)
        sd = 470 * (1 - F)
        b = 0.5 * 0.8 * (math.exp(-((sd + 150) / 14) ** 2) + math.exp(-((sd + 60) / 12) ** 2))
        gx.append(((g & 0xFF) << 8) | sat(int(round(b * 255)), 0, 255))
    gf = []
    for a in range(512):
        t = a - 128
        g = sat(int(round(pl(t, GF) * 255)), -128, 127)
        b = 0.95 * (math.exp(-((t - 6) / 9) ** 2) + math.exp(-((t - 56) / 9) ** 2))
        gf.append(((g & 0xFF) << 8) | sat(int(round(b * 255)), 0, 255))
    mats = []
    for ch in range(3):
        m = []
        for v in range(256):
            rgb = [0.0, 0.0, 0.0]; rgb[ch] = v / 255.0
            y = 0.299 * rgb[0] + 0.587 * rgb[1] + 0.114 * rgb[2]
            cb = (rgb[2] - y) / 1.772; cr = (rgb[0] - y) / 1.402
            Y = int(round(y * 876)); CR = int(round(cr * 896)); CB = int(round(cb * 896))
            m.append((Y << 22) | ((CR & 0x7FF) << 11) | (CB & 0x7FF))
        mats.append(m)
    return dict(lt=lt, pr=list(PR), gx=gx, gf=gf, mr=mats[0], mg=mats[1], mb=mats[2])


def vhdl_array(name, typ, vals, width, hexw):
    s = ['    constant %s : %s := (' % (name, typ)]
    for i in range(0, len(vals), 8):
        chunk = ', '.join('x"%0*X"' % (hexw, v & ((1 << width) - 1)) for v in vals[i:i + 8])
        s.append('        ' + chunk + (',' if i + 8 < len(vals) else ''))
    s.append('    );')
    return '\n'.join(s)


