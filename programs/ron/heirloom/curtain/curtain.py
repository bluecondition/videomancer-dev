def vhd_array(name, typ, vals, width, per=16, hexw=None):
    if hexw is None:
        hexw = (width + 3) // 4
    out = [f'    constant {name} : {typ} := (']
    for i in range(0, len(vals), per):
        chunk = ', '.join(f'x"{v:0{hexw}X}"' if width % 4 == 0 else f'"{v:0{width}b}"' for v in vals[i:i+per])
        out.append('        ' + chunk + (',' if i + per < len(vals) else ');'))
    return '\n'.join(out)

