MZ = [int(round(55 + 170 * (cs / 255.0) ** 0.6)) for cs in CS]
LN = [int(round(255 * (cs / 255.0) ** 2)) for cs in CS]

# per timing ID: 0 480i, 1/2 1080i, 3 1080p, 4 480p, 5/6 720p, 7 1080p, 8 576i, 9 1080p, 10 1080i, 11 1080p,
# 12 576p, 13 1080p, 14 720p, 15 1080p   (as escalator.py / the heirloom shell)
YS = [1138, 512, 512, 256, 576, 384, 384, 256, 960, 256, 512, 256, 480, 256, 384, 256]
SX2 = [4, 2, 2, 2, 4, 3, 3, 2, 4, 2, 2, 2, 4, 3, 3, 2]

def tconst(ys, sx2):
    sx = sx2 / 2.0
    return dict(
        sx2=sx2, ys=ys,
        bsl=int(round(ys / 256.0 / 27.72 * 65536)),        # scanline saw phase per line (two periods = 1.0)
        mzl=int(round(ys / 256.0 / 46.0 * 65536)),         # maze vertical oscillator per line
        mzq=int(round(ys / 256.0 / 110.0 * 65536)),        # maze modulator per line
        kax=int(round(65536 * sx / 1280.0)), kbx=int(round(65536 * sx / 1536.0)),   # Osc triangles
        kay=int(round(65536 * ys / 256.0 / 864.0)), kby=int(round(65536 * ys / 256.0 / 1350.0)),
        psk=sx2 * 159)

def arr(name, typ, vals, w):
    rows = []
    for i in range(0, len(vals), 12):
        rows.append("        " + ", ".join('"' + format(int(v) & ((1 << w) - 1), "0" + str(w) + "b") + '"' for v in vals[i:i + 12]))
    return "    constant " + name + " : " + typ + " := (\n" + ",\n".join(rows) + "\n    );"

def emit():
    lw, _, _, _ = lut_fields()
    tw, _, _ = th_rom()
    gw, _ = eg_rom()
    tc = [tconst(YS[i], SX2[i]) for i in range(16)]
    cs = [arr("C_LUT", "t_lut", lw, 16), arr("C_TH", "t_th", tw, 24), arr("C_EG", "t_eg", gw, 10),
          arr("C_CS", "t_r8", CS, 8), arr("C_MZ", "t_r8", MZ, 8), arr("C_LN", "t_r8", LN, 8)]
    widths = dict(sx2=3, ys=11, bsl=12, mzl=12, mzq=12, kax=8, kbx=8, kay=8, kby=8, psk=10)
    for key, w in widths.items():
        cs.append(arr("C_T_" + key.upper(), "t_tim" + str(w), [t[key] for t in tc], w))
    types = "\n".join("    type t_tim%d is array(0 to 15) of std_logic_vector(%d downto 0);" % (w, w - 1)
                      for w in sorted(set(widths.values())))
    txt = ("-- fern_pkg.vhd -- GENERATED by fern.py; edit the generator, not this file.\n\n"
           "library ieee;\nuse ieee.std_logic_1164.all;\n\npackage fern_pkg is\n"
           "    type t_lut is array(0 to 2047) of std_logic_vector(15 downto 0);\n"
           "    type t_th is array(0 to 511) of std_logic_vector(23 downto 0);\n"
           "    type t_eg is array(0 to 1023) of std_logic_vector(9 downto 0);\n"
           "    type t_r8 is array(0 to 255) of std_logic_vector(7 downto 0);\n"
           + types + "\n" +
           "\n".join(cs) + "\nend package fern_pkg;\n")
    with open(os.path.join(HERE, "fern_pkg.vhd"), "w") as fh:
        fh.write(txt)

if __name__ == "__main__":
    emit()
