def lut_fields():
    L = [((w >> 9) & 127) - (128 if ((w >> 9) & 127) >= 64 else 0) for w in LUTW]
    return list(LUTW), L, [(w >> 4) & 31 for w in LUTW], [w & 15 for w in LUTW]

def th_rom():
    t = [int(round(theta_of_c(i * 16.0) * 1024)) for i in range(513)]
    d = [t[i + 1] - t[i] for i in range(512)]
    assert min(d) >= 0 and max(d) < 256, (min(d), max(d))
    return [((t[i] & 0xFFFF) << 8) | d[i] for i in range(512)], t, d

def eg_rom():
    w = [0] * 1024
    g = [int(round(G_of(i + 0.5) * 2)) for i in range(576)]           # Q.1, |dy| = i + 0.5 (cy = 515.5)
    for i in range(576): w[i] = g[i]
    for i in range(128): w[640 + i] = int(round(interp(i * 28 / 128.0, list(range(29)), BT + BT[:1])))
    for i in range(128):
        u = i / 128.0
        w[768 + i] = int(round(154 * (1 - abs(2 * u - 1))))
    return w, g

