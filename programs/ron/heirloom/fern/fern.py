def G_of(ady):
    u = min(float(ady), 557.0) / 557.0
    return sum(c * u ** (k + 1) for k, c in enumerate(GPOLY))

def interp(x, xs, ys):
    if x <= xs[0]: return ys[0]
    if x >= xs[-1]: return ys[-1]
    for i in range(len(xs) - 1):
        if xs[i] <= x <= xs[i + 1]:
            return ys[i] + (ys[i + 1] - ys[i]) * (x - xs[i]) / (xs[i + 1] - xs[i])

def theta_of_c(c):
    s0 = (ARM_K[1] - ARM_K[0]) / (ARM_C[1] - ARM_C[0]); s1 = (ARM_K[-1] - ARM_K[-2]) / (ARM_C[-1] - ARM_C[-2])
    if c < ARM_C[0]: return ARM_K[0] + (c - ARM_C[0]) * s0
    if c > ARM_C[-1]: return ARM_K[-1] + (c - ARM_C[-1]) * s1
    return interp(c, ARM_C, ARM_K)

