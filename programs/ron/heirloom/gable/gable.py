def _dec(parts, digits, n, signed_bits=0):
    h = ''.join(parts)
    out = [int(h[digits * i:digits * i + digits], 16) for i in range(n)]
    if signed_bits:
        out = [v - (1 << signed_bits) if v >= (1 << (signed_bits - 1)) else v for v in out]
    return out


