def glow_curves():
    out = []
    for i in range(512):
        t = (i * 512 + 256 - 65536) / 65536.0
        q = math.sqrt(max(1.0 + t, 0.0)) - 1.0
        if q < 0:
            g = max(0.0, min(1.0, 1 + q / 0.335)) ** 1.2
        else:
            g = max(0.0, min(1.0, 1 - q / 0.207)) ** 1.3
        fb = math.exp(-(q / 0.061) ** 2)
        fc = math.exp(-(q / 0.043) ** 2)
        out.append((int(round(63 * g)), int(round(63 * fb)), int(round(15 * fc))))
    return out


def glow_tab():
    """Cell colour by glow index, with the red level factored out:
    colour = T(t) + Rc * (1 - g) * k;  T = base * (1 - g) + glow * g + blue core + white core, luma pre-boosted."""
    out = []
    for g6, b6, c4 in glow_curves():
        y = 177 * (64 - g6) / 64.0 + 745 * g6 / 64.0 + 80 * b6 / 64.0 + 56 * c4 / 16.0
        u = 430 * (64 - g6) / 64.0 + 554 * g6 / 64.0 - 59 * b6 / 64.0 + 22 * c4 / 16.0
        v = 447 * (64 - g6) / 64.0 + 119 * g6 / 64.0 + 360 * b6 / 64.0 - 32 * c4 / 16.0
        yb = min(1020.0, 64 + (y - 64) * 16 / 13.0)
        ig = min(31, int(round((64 - g6) / 2.0)))
        ty, tu, tv = int(round(yb / 2)), int(round(u / 2)), int(round(v / 2))
        out.append((ty << 23) | (tu << 14) | (tv << 5) | ig)
    return out


def tear_tab():
    a = [int(round(-127 * math.exp(-x * 4 / 160.0) * math.cos(math.pi * x * 4 / 330.0))) for x in range(256)]
    b = [int(round(127 * math.exp(-x * 4 / 45.0))) for x in range(256)]
    return a + b


def nz_tab():
    s = 0x2545F491
    out = []
    for _ in range(256):
        s ^= (s << 13) & 0xFFFFFFFF; s ^= s >> 17; s ^= (s << 5) & 0xFFFFFFFF
        out.append(((s >> 8) % 255) - 127)
    return out


def red_tab():
    return [int(round(36 + 139 * math.exp(-i * 2 / 128.0))) for i in range(256)]


def p12_tab():
    """Halo (P12) -> glow scale s = 256 / halo (bits 27..18), interior valid (17), interior threshold in
    glow-index units tk = 65536 * ((1 - 0.305 halo)^2 - 1) / halo (16..0, signed)."""
    out = []
    for i in range(256):
        halo = 0.3 * (4.0 / 0.3) ** (i / 255.0)
        s = int(round(256.0 / halo))
        a = 0.305 * halo
        if a < 1.0:
            tk = int(round(65536 * ((1 - a) ** 2 - 1) / halo)); ok = 1
        else:
            tk = 0; ok = 0
        out.append((s << 18) | (ok << 17) | (tk & 0x1FFFF))
    return out


def sq_tab():
    return [((2 * i + 1) ** 2) >> 4 for i in range(512)]


def fl_tab():
    out = []
    for i in range(16):
        x = 4 * i
        w = max(0.0, min(1.0, (58 - x) / 40.0)) ** 0.7
        out.append(int(round(4 * w)))
    return out


