import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))

# colouriser knots at v = 0, 1/3, 2/3, ... 3 (photo RGB, measured on the still's polyline)
PAL_RGB = [
    # Blue (the photo): navy .. blue .. cyan .. lavender
    [(5, 14, 89), (4, 40, 125), (7, 75, 169), (20, 115, 214), (53, 150, 238), (100, 190, 240),
     (146, 215, 237), (178, 210, 238), (208, 212, 235), (232, 212, 232)],
    # Ember: maroon .. red .. amber .. cream
    [(40, 6, 22), (70, 10, 26), (110, 16, 26), (170, 34, 22), (205, 66, 22), (232, 110, 30),
     (246, 160, 48), (250, 194, 104), (250, 220, 160), (250, 236, 206)],
]


def rgb_to_hw10(rgb):
    r, g, b = [c / 255.0 for c in rgb]
    y = 0.299 * r + 0.587 * g + 0.114 * b
    cb, cr = (b - y) / 1.772, (r - y) / 1.402
    return (64 + y * 876, 512 + cr * 896, 512 + cb * 896)


def prescale(yuv):
    y, u, v = yuv
    y2 = 64 + (y - 64) * 16.0 / 13.0
    y2 = int(round(min(940, max(64, y2))))
    return (y2, min(1000, max(24, int(round(u)))), min(1000, max(24, int(round(v)))))


def word(yuv):
    y, u, v = prescale(yuv)
    return (y << 22) | (u << 12) | (v << 2)


def interp_rgb(knots, v):
    v = max(0.0, min(3.0, v))
    t = v * 3.0
    i = min(8, int(t))
    f = t - i
    a, b = knots[i], knots[i + 1]
    return tuple(a[c] + f * (b[c] - a[c]) for c in range(3))


def exp2_rom():
    return [int(round(32768 * 2 ** (i / 256.0))) for i in range(256)]


def cos_rom():
    return [int(round(1023 * (1 + math.cos(2 * math.pi * i / 512)) / 2)) for i in range(512)]


def pal_rom():
    out = []
    for p in range(2):
        for i in range(256):
            v = min(i, 192) / 64.0
            out.append(word(rgb_to_hw10(interp_rgb(PAL_RGB[p], v))))
    return out


def vhd_table(name, typ, depth, width, vals):
    lines = ["    type %s is array (0 to %d) of %s(%d downto 0);" % ("t_" + name.lower(), depth - 1, typ, width - 1),
             "    constant %s : %s := (" % (name, "t_" + name.lower())]
    items = []
    for v in vals:
        items.append('x"%0*X"' % ((width + 3) // 4, v) if width % 4 == 0 else 'to_unsigned(%d, %d)' % (v, width))
    per = 16 if width % 4 == 0 else 8
    for i in range(0, len(items), per):
        lines.append("        " + ", ".join(items[i:i + per]) + ("," if i + per < len(items) else ""))
    lines.append("    );")
    return "\n".join(lines)


def main():
    parts = ["-- Generated by herringbone.py -- DO NOT EDIT.",
             "library ieee;", "use ieee.std_logic_1164.all;", "use ieee.numeric_std.all;", "",
             "package herringbone_pkg is",
             vhd_table("C_HB_EXP2", "unsigned", 256, 16, exp2_rom()),
             vhd_table("C_HB_COS", "unsigned", 512, 10, cos_rom()),
             vhd_table("C_HB_PAL", "std_logic_vector", 512, 32, pal_rom()),
             '    constant C_HB_K0 : std_logic_vector(31 downto 0) := x"%08X";' % pal_rom()[0],
             '    constant C_HB_K1 : std_logic_vector(31 downto 0) := x"%08X";' % pal_rom()[256],
             "end package herringbone_pkg;", ""]
    with open(os.path.join(HERE, "herringbone_pkg.vhd"), "w") as f:
        f.write("\n".join(parts))


if __name__ == "__main__":
    main()
