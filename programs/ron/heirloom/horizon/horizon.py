import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))

ARC_U = [0, 120, 195, 300, 400, 500, 600, 700, 800, 900, 1000, 3000]
ARC_Y = [880, 818, 784, 728, 682, 642, 610, 588, 573, 566, 565, 565]
YG_U = [0, 191, 273, 300, 350, 420, 505, 573, 660, 725, 815, 867, 1000, 3000]
YG_Y = [430, 520, 620, 700, 815, 868, 912, 928, 945, 958, 965, 975, 985, 985]


def interp(xs, ys, x):
    if x <= xs[0]:
        return ys[0]
    for i in range(1, len(xs)):
        if x <= xs[i]:
            t = (x - xs[i - 1]) / (xs[i] - xs[i - 1])
            return ys[i - 1] + t * (ys[i] - ys[i - 1])
    return ys[-1]


def tables():
    A, G, C, SQ, EX, E2, CIR, GL = [], [], [], [], [], [], [], []
    for i in range(512):
        u = 2 * i + 1
        arc0 = int(round((interp(ARC_U, ARC_Y, u) - 565) / 2))
        yg0 = int(round(interp(YG_U, YG_Y, u) / 4))
        A.append((max(0, min(255, arc0)) << 8) | max(0, min(255, yg0)))
        hg = int(round(174 * (1 - math.exp(-u / 550.0))))
        th = u / 192.0 - 0.08
        ql = int(round(256 * abs(th - round(th))))
        G.append((max(0, min(255, hg)) << 8) | max(0, min(128, ql)))
        su = 288 + int(round(0.406 * u))
        gq = min(31, max(0, 150 - u) >> 2)
        C.append((su << 6) | (gq << 1))
    for i in range(256):
        SQ.append(min(255, int(round(2.133 * math.sqrt(4 * i + 2)))))
        EX.append(min(255, int(round(240 * (1 - math.exp(-(4 * i + 2) / 130.0))))))
        E2.append(min(65535, int(round(32768 * 2 ** (i / 256.0)))))
    for t in range(40):
        CIR.append(int(round(63 * math.sqrt(1 - (1 - t / 40.0) ** 2))))
    for d in range(64):
        GL.append(max(12, int(round(110 * math.exp(-d / 19.7)))))
    return A, G, C, SQ, EX, E2, CIR, GL


def vrow(vals, fmt, per=8):
    out = []
    for i in range(0, len(vals), per):
        out.append("        " + ", ".join(fmt % v for v in vals[i:i + per]) + ("," if i + per < len(vals) else ""))
    return out


