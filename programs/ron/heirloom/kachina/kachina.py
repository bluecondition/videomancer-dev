def _arc(nodes):
    d = [0.0]
    for a, b in zip(nodes, nodes[1:]):
        d.append(d[-1] + sum((a[i] - b[i]) ** 2 for i in range(3)) ** 0.5)
    return [x / d[-1] for x in d]

def _interp(t, xs, nodes):
    for j in range(len(xs) - 1):
        if t <= xs[j + 1] or j == len(xs) - 2:
            w = 0.0 if xs[j + 1] == xs[j] else (t - xs[j]) / (xs[j + 1] - xs[j])
            w = min(max(w, 0.0), 1.0)
            return [nodes[j][i] * (1 - w) + nodes[j + 1][i] * w for i in range(3)]

def chain(main, side):
    """64 entries: 52 along the main chain, 12 along the side chain, spaced by the Kachina chain's arc length"""
    out = []
    for nodes, ref, n in ((main, MAIN_K, 52), (side, SIDE_K, 12)):
        xs = _arc(ref)
        for k in range(n):
            out.append(_interp(k / (n - 1), xs, nodes))
    return out

def expand256(p64):
    out = []
    for i in range(256):
        a, f = i >> 2, (i & 3) / 4.0
        b = a if a in (51, 63) else a + 1
        out.append([p64[a][c] * (1 - f) + p64[b][c] * f for c in range(3)])
    return out

def hw10(rgb):
    r, g, b = [c / 255.0 for c in rgb]
    y = 0.299 * r + 0.587 * g + 0.114 * b
    cb, cr = (b - y) / 1.772, (r - y) / 1.402
    y10 = 64 + y * 876
    y10 = min(940, 64 + (y10 - 64) * 16 / 13)
    cl = lambda v: max(0, min(1023, int(round(v))))
    return cl(y10), cl(512 + cr * 896), cl(512 + cb * 896)     # (Y, U = Cr, V = Cb)

def pal_words():
    words = []
    for main, side in ((MAIN_K, SIDE_K), (MAIN_F, SIDE_F)):
        for rgb in expand256(chain(main, side)):
            y, u, v = hw10(rgb)
            words.append((y << 22) | (u << 12) | (v << 2))
    return words

def write_pkg():
    L = ['-- Generated by kachina.py - do not edit.', 'library ieee;', 'use ieee.std_logic_1164.all;', '',
         'package kachina_pkg is',
         '    type t_ka_tab is array (0 to 4095) of std_logic_vector(15 downto 0);',
         '    type t_ka_pal is array (0 to 511) of std_logic_vector(31 downto 0);']
    def emit(name, typ, words, hexw):
        L.append('    constant %s : %s := (' % (name, typ))
        row = []
        for i, w in enumerate(words):
            row.append('x"%0*x"' % (hexw, w))
            if len(row) == 8 or i == len(words) - 1:
                L.append('        ' + ', '.join(row) + (',' if i < len(words) - 1 else ''))
                row = []
        L.append('    );')
    emit('C_KA_TAB', 't_ka_tab', TAB, 4)
    emit('C_KA_PAL', 't_ka_pal', pal_words(), 8)
    L += ['end package kachina_pkg;', '']
    with open(os.path.join(HERE, 'kachina_pkg.vhd'), 'w') as fh:
        fh.write('\n'.join(L))

