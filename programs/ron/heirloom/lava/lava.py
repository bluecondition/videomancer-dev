def _rom(name, typ, vals, width, depth, per=16):
    vals = list(vals) + [0] * (depth - len(vals))
    rows = []
    for k in range(0, depth, per):
        rows.append("        " + ", ".join('"' + format(v & ((1 << width) - 1), "0%db" % width) + '"' for v in vals[k:k + per]))
    return "    constant %s : %s := (\n" % (name, typ) + ",\n".join(rows) + "\n    );"


