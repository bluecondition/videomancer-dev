def bits(v, n):
    return '"' + format(v & ((1 << n) - 1), '0%db' % n) + '"'


def rom(name, typ, vals, n):
    out = ['    constant %s : %s := (' % (name, typ)]
    for k in range(0, len(vals), 12):
        out.append('        ' + ', '.join(bits(v, n) for v in vals[k:k + 12]) + (',' if k + 12 < len(vals) else ''))
    out.append('    );')
    return out


