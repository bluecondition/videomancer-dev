def interp(x, tab):
    for (x0, y0), (x1, y1) in zip(tab, tab[1:]):
        if x0 <= x <= x1:
            return y0 + (y1 - y0) * (x - x0) / (x1 - x0)
    return tab[-1][1]


def gp_table():
    out = []
    for w in range(8):
        for p in range(128):
            ph = (p + 0.5) / 128 * 16
            i0 = int(ph) % 16
            fr = ph - int(ph)
            sh = (GS[i0] * (1 - fr) + GS[(i0 + 1) % 16] * fr) / 234.0
            out.append(min(255, int(round(232 * sh ** WEXP[w]))))
    return out


def br_table():
    return [int(round(interp(b / 32.0 - 1.0, BT))) for b in range(256)]


