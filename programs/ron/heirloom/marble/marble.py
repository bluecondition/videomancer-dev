"""
MARBLE v0.1.0 - build hook.  Writes marble_pkg.vhd next to this file (pure python: the builder runs it with the
system python3).  Fitted to the clip still WIN_20230914_01_59_34 at 4.0 s (.heirloom_work/rb_marble/notes.md).

The still is an RGB patch:
  B  = the cream-band key of one hard-synced, FM'd horizontal oscillator u (band ROM: kb, kg, kr over u)
  G  = a wider, slower window of the same oscillator (kg) over a warm floor and the figure field
  R  = a nested-rhombus lattice (rotated triangle pair over a kaleidoscope-folded x) through a ring colouriser

Package contents (all tables also read by .heirloom_work/rb_marble/imodel.py):
  C_MB_BAND  256 x 16   {kb(6), kg(6), kr(4)} over u = i / 256 (cream band from u = 0 to the duty 0.485)
  C_MB_RING  1024 x 8   R over the ring index i / 64 (black core below 0.424 rings, then a ring every 1.0)
  C_MB_SIN   256 x 8    round(127 sin(2 pi i / 256)), signed (melt oscillators)
  C_MB_COS   1024 x 16  round(32767 cos(2 pi i / 1024)), signed (the vertical FM sine)
  C_MB_EXP2  256 x 16   round(32768 * 2^(i / 256))
"""
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))
DUTY = 0.485          # cream / period
CORE = 50.0 / 118.0   # core radius, ring units
RMIN = 70.0           # darkest ring level
RHW = 0.30            # ring half-width (of a ring period)

def clamp(v, lo, hi):
    return max(lo, min(hi, v))

def band_rom():
    out = []
    for i in range(256):
        u = (i + 0.5) / 256.0
        du = u - 1.0 if u > 0.5 else u
        if u > 0.5 + DUTY / 2:
            kb = clamp((du + 0.045) / 0.09, 0, 1)
            kg = clamp((du + 0.07) / 0.04, 0, 1)
        else:
            kb = clamp(min((du + 0.045) / 0.09, (DUTY + 0.03 - u) / 0.06), 0, 1)
            kg = clamp(min((du + 0.07) / 0.04, (DUTY + 0.13 - u) / 0.11), 0, 1)
        kr = 1.0 - 0.85 * clamp(1.0 - abs(du + 0.045) / 0.03, 0, 1)
        kb6 = int(round(kb * 63)); kg6 = int(round(kg * 63)); kr4 = int(round(kr * 15))
        out.append((kb6 << 10) | (kg6 << 4) | kr4)
    return out

def ring_rom():
    out = []
    for i in range(1024):
        r = i / 64.0
        if r < CORE:
            a = CORE - 20.0 / 118.0
            v = 0.0 if r < a else 240.0 * (r - a) / (CORE - a)
        else:
            q = (r - CORE) % 1.0
            bump = clamp(1.0 - abs(q - 0.55) / RHW, 0, 1)
            v = 240.0 - (240.0 - RMIN) * clamp(bump * 1.25, 0, 1)
        out.append(int(round(clamp(v, 0, 255))))
    return out

def sin_rom():
    return [int(round(127 * math.sin(2 * math.pi * i / 256.0))) for i in range(256)]

def cos_rom():
    return [int(round(32767 * math.cos(2 * math.pi * i / 1024.0))) for i in range(1024)]

def exp2_rom():
    return [int(round(32768 * 2 ** (i / 256.0))) for i in range(256)]

def vhd_table(name, typ, depth, width, vals, signed=False):
    lines = ["    type %s is array (0 to %d) of %s(%d downto 0);" % ("t_" + name.lower(), depth - 1, typ, width - 1),
             "    constant %s : %s := (" % (name, "t_" + name.lower())]
    items = []
    for v in vals:
        if signed:
            items.append('to_signed(%d, %d)' % (v, width))
        else:
            items.append('x"%0*X"' % ((width + 3) // 4, v) if width % 4 == 0 else 'to_unsigned(%d, %d)' % (v, width))
    per = 8 if signed else 16
    for i in range(0, len(items), per):
        lines.append("        " + ", ".join(items[i:i + per]) + ("," if i + per < len(items) else ""))
    lines.append("    );")
    return "\n".join(lines)

def main():
    parts = ["-- Generated by marble.py -- DO NOT EDIT.",
             "library ieee;", "use ieee.std_logic_1164.all;", "use ieee.numeric_std.all;", "",
             "package marble_pkg is",
             vhd_table("C_MB_BAND", "unsigned", 256, 16, band_rom()),
             vhd_table("C_MB_RING", "unsigned", 1024, 8, ring_rom()),
             vhd_table("C_MB_SIN", "signed", 256, 8, sin_rom(), signed=True),
             vhd_table("C_MB_COS", "signed", 1024, 16, cos_rom(), signed=True),
             vhd_table("C_MB_EXP2", "unsigned", 256, 16, exp2_rom()),
             "end package marble_pkg;", ""]
    with open(os.path.join(HERE, "marble_pkg.vhd"), "w") as f:
        f.write("\n".join(parts))

if __name__ == "__main__":
    main()
