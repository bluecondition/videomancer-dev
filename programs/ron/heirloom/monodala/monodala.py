"""
MONODALA - build hook.  Generates monodala_pkg.vhd (pure Python, no numpy).

Monodala: concentric contour rings over the whole screen, bent by the video, drawn as accent lines over a
ground of one colour (Heirloom Mandala's contour shaper and colour look, without its face).

ROMs (std_logic_vector):
  C_GP   2048 x 8          line pulse, address width(4) & phase(7); entry = 232 * shape(phase)^e(width)
                           (Mandala's 16 width banks, exponent 0.12 .. 8)
  C_HUE   512 x 30         colour wheel, address ink(1) & hue(8): Y - 64 (10, unsigned) & U (10, signed)
                           & V (10, signed), hardware convention (U = Cr, V = Cb). Ink 0 = the pure hue at
                           full level (HSV S = V = 1), ink 1 = the same hue at 3/8 level.
"""

import colorsys
import os

HERE = os.path.dirname(os.path.abspath(__file__))

# the stripe profile over one period (16 samples, peak 234) and the 16 width exponents
GS = [234, 211, 172, 127, 82, 44, 15, 6, 8, 22, 50, 85, 125, 160, 192, 220]
WEXP = [0.12, 0.15, 0.19, 0.24, 0.31, 0.4, 0.52, 0.68, 0.84, 1.0, 1.35, 1.85, 2.6, 3.7, 5.4, 8.0]


def gp_table():
    out = []
    for w in range(len(WEXP)):
        for p in range(128):
            ph = (p + 0.5) / 128 * 16
            i0 = int(ph) % 16
            fr = ph - int(ph)
            sh = (GS[i0] * (1 - fr) + GS[(i0 + 1) % 16] * fr) / 234.0
            out.append(min(255, int(round(232 * sh ** WEXP[w]))))
    return out


def hue_table():
    out = []
    for ink, lev in ((0, 1.0), (1, 0.375)):
        for h in range(256):
            r, g, b = (round(255 * lev * c) for c in colorsys.hsv_to_rgb(h / 256.0, 1.0, 1.0))
            y = (66 * r + 129 * g + 25 * b) >> 6
            u = (112 * r - 94 * g - 18 * b) >> 6
            v = (112 * b - 38 * r - 75 * g) >> 6
            out.append(((y & 1023) << 20) | ((u & 1023) << 10) | (v & 1023))
    return out


def emit():
    def arr(name, typ, vals, bits):
        vals = [v & ((1 << bits) - 1) for v in vals]
        body = []
        for i in range(0, len(vals), 16):
            body.append("        " + ", ".join(f'"{v:0{bits}b}"' for v in vals[i:i + 16]))
        return f"    constant {name} : {typ} := (\n" + ",\n".join(body) + "\n    );"
    consts = [arr("C_GP", "t_rom_gp", gp_table(), 8), arr("C_HUE", "t_rom_hue", hue_table(), 30)]
    txt = f"""-- monodala_pkg.vhd -- GENERATED by monodala.py; edit the generator, not this file.
--
-- C_GP:  line pulse, address width(4) & phase(7).
-- C_HUE: colour wheel, address ink(1) & hue(8): Y - 64 & U & V (10 bits each; U, V signed; U = Cr).

library ieee;
use ieee.std_logic_1164.all;

package monodala_pkg is
    type t_rom_gp is array(0 to 2047) of std_logic_vector(7 downto 0);
    type t_rom_hue is array(0 to 511) of std_logic_vector(29 downto 0);
{chr(10).join(consts)}
end package monodala_pkg;
"""
    with open(os.path.join(HERE, "monodala_pkg.vhd"), "w") as fh:
        fh.write(txt)


if __name__ == "__main__":
    emit()
