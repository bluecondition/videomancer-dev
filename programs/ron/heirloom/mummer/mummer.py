def interp(x, xs, ys):
    if x <= xs[0]: return ys[0]
    if x >= xs[-1]: return ys[-1]
    lo, hi = 0, len(xs) - 1
    while hi - lo > 1:
        m = (lo + hi) // 2
        if xs[m] <= x: lo = m
        else: hi = m
    t = (x - xs[lo]) / (xs[hi] - xs[lo])
    return ys[lo] + t * (ys[hi] - ys[lo])

def fold(F):
    u = math.fmod(F + 200.0, 1680.0)
    if u < 0: u += 1680.0
    return (1680.0 - u if u > 840.0 else u) - 200.0

def still_rows():
    ys = [r[0] for r in KN]
    return [[interp(y, ys, [r[c] for r in KN]) for y in range(1080)] for c in (1, 2, 3)]

def scroll():
    """Vs, gs, g2s over d = 0 .. LW - 1 (float, palette units / per px)"""
    V0, G0, G20 = still_rows()
    P = [KP * (y - 540.0) for y in range(1080)]
    Gf = [1.0 + KG * max(0.0, y - 540.0) / 540.0 for y in range(1080)]
    out = []
    for tab in ([V0[y] - P[y] for y in range(1080)], [G0[y] / Gf[y] for y in range(1080)], [G20[y] / Gf[y] for y in range(1080)]):
        t = list(tab)
        br = LW - 1080
        for j in range(br):
            w = 0.5 - 0.5 * math.cos(math.pi * (j + 1) / (br + 1))
            t.append(tab[-1] * (1 - w) + tab[0] * w)
        out.append(t)
    return out

def pal_rgb(F, gold=False):
    f = fold(F)
    xs = [k[0] for k in KEYS]
    cols = [GOLD[tuple(k[1])] for k in KEYS] if gold else [k[1] for k in KEYS]
    return tuple(interp(f, xs, [c[i] for c in cols]) for i in range(3))

def rgb_to_hw10(rgb):
    r, g, b = [c / 255.0 for c in rgb]
    y = 0.299 * r + 0.587 * g + 0.114 * b
    cb = (b - y) / 1.772; cr = (r - y) / 1.402
    return round(64 + y * 876), round(512 + cr * 896), round(512 + cb * 896)

def sx(v, bits):
    v &= (1 << bits) - 1
    return v - (1 << bits) if v >> (bits - 1) else v

def build():
    Vs, gs, g2s = scroll()
    exp2 = [round(32768 * 2 ** (i / 256.0)) for i in range(256)]
    sc = []
    for i in range(256):
        d = LW * i / 256.0
        j = int(d); t = d - j
        f = lambda tab: tab[j] + t * (tab[(j + 1) % LW] - tab[j])
        v = max(-4096, min(4095, round(f(Vs) * QF / 2)))
        g = max(-1024, min(1023, round(f(gs) * (466.5 / 1023) * QF * 256)))
        g2 = max(-128, min(127, round(f(g2s) * (233.25 / 1023) * QF * 128)))
        sc.append(((v & 0x1FFF) << 19) | ((g & 0x7FF) << 8) | (g2 & 0xFF))
    cosr = [round(127 * math.cos(2 * math.pi * (i + 0.5) / 256)) & 0xFF for i in range(256)]
    wl = []
    for j in range(64):
        F = -200 + (16 * j + 8) * 1680.0 / 1024
        f = fold(F)
        w = interp(f, [p[0] for p in WK], [p[1] for p in WK])
        inside = 1 if f < 330 else 0
        wl.append((inside << 4) | min(15, round(w * 8)))
    pal = []
    for gold in (False, True):
        for i in range(1024):
            F = -200 + (i + 0.5) * 1680.0 / 1024
            y, u, v = rgb_to_hw10(pal_rgb(F, gold))
            y = min(64 + (y - 64) * 16.0 / 13.0, 940)
            y8, u8, v8 = round(y / 4), min(round(u / 4), 255), min(round(v / 4), 255)
            pal.append((y8 << 16) | (u8 << 8) | v8)
    th = []
    st = 12345
    for i in range(256):
        st = (st * 1103515245 + 12345) & 0x7FFFFFFF
        r = (st >> 8) & 0xFFFF
        if (r & 3) == 0: th.append(0)
        else:
            x = (r >> 4) & 255
            th.append((3 * x - (x >> 2) + (x >> 5) - 357) & 0x7FF)
    return dict(EXP2=exp2, SC=sc, COS=cosr, W=wl, TH=th, PAL=pal)

def vhd_array(name, typ, vals, width):
    digits = (width + 3) // 4
    lines = []
    for i in range(0, len(vals), 8):
        if width % 4 == 0:
            lines.append('        ' + ', '.join('x"%0*X"' % (digits, v) for v in vals[i:i + 8]))
        else:
            lines.append('        ' + ', '.join('"%s"' % format(v, '0%db' % width) for v in vals[i:i + 8]))
    return '    constant %s : %s := (\n%s\n    );\n' % (name, typ, ',\n'.join(lines))

