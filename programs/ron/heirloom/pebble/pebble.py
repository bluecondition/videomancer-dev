def hw10(rgb):
    """rgb 0..255 -> (Y, U = Cr, V = Cb) 10-bit hardware convention, Y pre-scaled 16/13 (cap 940)."""
    r, g, b = [c / 255.0 for c in rgb]
    y = 0.299 * r + 0.587 * g + 0.114 * b
    cb = (b - y) / 1.772
    cr = (r - y) / 1.402
    yy = 64 + y * 876
    yy = 64 + (yy - 64) * 16.0 / 13.0
    yy = int(round(min(940.0, yy)))
    u = int(round(min(1008.0, max(16.0, 512 + cr * 896))))
    v = int(round(min(1008.0, max(16.0, 512 + cb * 896))))
    return yy, u, v

def word(c):
    y, u, v = hw10(c)
    return (y << 22) | (u << 12) | (v << 2)

def cyc(pal, s):
    n = len(pal)
    f = (s % 1.0) * n
    i = int(math.floor(f))
    t = f - i
    a, b = pal[i % n], pal[(i + 1) % n]
    return tuple(a[k] * (1 - t) + b[k] * t for k in range(3))

def exp2_rom():
    return [int(round(32768 * 2 ** (i / 256.0))) for i in range(256)]

def cos_rom():
    return [int(round(32767 * math.cos(2 * math.pi * i / 1024.0))) for i in range(1024)]

def fire_rom():
    return [word(c) for c in FIRE_A] + [word(c) for c in FIRE_B]

def blue_rom():
    out = []
    for pal in (COOL, GREEN):
        for i in range(128):
            out.append(word(cyc(pal, (i + 0.5) / 128.0)))
    return out

def crown_rom():
    return [int(round(255 * (2 * (i + 0.5) / 256.0 - 1) ** 2)) for i in range(256)]

def vhd_table(name, typ, depth, width, vals, signed=False):
    lines = ["    type %s is array (0 to %d) of %s(%d downto 0);" % ("t_" + name.lower(), depth - 1, typ, width - 1),
             "    constant %s : %s := (" % (name, "t_" + name.lower())]
    items = []
    for v in vals:
        if signed:
            items.append('to_signed(%d, %d)' % (v, width))
        elif width % 4 == 0:
            items.append('x"%0*X"' % (width // 4, v))
        else:
            items.append('to_unsigned(%d, %d)' % (v, width))
    per = 8 if signed else 16
    for i in range(0, len(items), per):
        lines.append("        " + ", ".join(items[i:i + per]) + ("," if i + per < len(items) else ""))
    lines.append("    );")
    return "\n".join(lines)

