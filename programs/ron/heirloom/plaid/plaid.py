def unhex(s):
    return [int(s[i:i + 2], 16) for i in range(0, len(s), 2)]


def rgb_to_hw10(rgb):
    r, g, b = [c / 255.0 for c in rgb]
    y = 0.299 * r + 0.587 * g + 0.114 * b
    cb, cr = (b - y) / 1.772, (r - y) / 1.402
    return (64 + y * 876, 512 + cr * 896, 512 + cb * 896)


def word8(rgb):
    y, u, v = rgb_to_hw10(rgb)
    y = 64 + (y - 64) * 16.0 / 13.0
    y = min(940.0, max(64.0, y))
    q = lambda c, lo, hi: min(hi, max(lo, int(round(c / 4.0))))
    return (q(y, 16, 235) << 16) | (q(u, 6, 250) << 8) | q(v, 6, 250)


def grid():
    g = unhex("".join(GRID_HEX))
    return [[tuple(g[(xi * 32 + wi) * 3:(xi * 32 + wi) * 3 + 3]) for wi in range(32)] for xi in range(32)]


def grid_y(xp, wp):
    g = grid()
    return [word8(g[2 * xh + xp][2 * wh + wp]) >> 16 for xh in range(16) for wh in range(16)]


def grid_c(wp):
    g = grid()
    return [word8(g[xi][2 * wh + wp]) & 0xFFFF for xi in range(32) for wh in range(16)]


def back_rom():
    b = unhex("".join(BACK_HEX))
    out = []
    for i in range(256):
        rgb = tuple(b[3 * i:3 * i + 3])
        out.append(word8(rgb) if i < 230 else word8((0, 0, 0)))
    return out


def dist_table(runs, length, step):
    inside = [False] * length
    for s, e in runs:
        for u in range(s, e):
            inside[u % length] = True
    edges = [u for u in range(length) if inside[u] != inside[u - 1]]
    out = []
    for j in range(length // step):
        c = j * step + step / 2.0
        d = min(min(abs(c - e), length - abs(c - e)) for e in edges)
        v = int(round(d - 0.5)) + 1 if inside[int(c)] else -(int(round(d - 0.5)) + 1)
        out.append(max(-127, min(127, v)) & 0xFF)
    return out


def exp2_rom():
    return [int(round(32768 * 2 ** (i / 256.0))) for i in range(256)]


def sin_rom():
    return [int(round(255 * math.sin(math.pi / 2 * (i + 0.5) / 512))) for i in range(512)]


def vhd_table(name, depth, width, vals):
    lines = ["    type t_%s is array (0 to %d) of std_logic_vector(%d downto 0);" % (name.lower(), depth - 1, width - 1),
             "    constant %s : t_%s := (" % (name, name.lower())]
    items = ['x"%0*X"' % ((width + 3) // 4, v) for v in vals]
    for i in range(0, len(items), 16):
        lines.append("        " + ", ".join(items[i:i + 16]) + ("," if i + 16 < len(items) else ""))
    lines.append("    );")
    return "\n".join(lines)


def tables():
    return {
        'C_PL_YEE': grid_y(0, 0), 'C_PL_YEO': grid_y(0, 1), 'C_PL_YOE': grid_y(1, 0), 'C_PL_YOO': grid_y(1, 1),
        'C_PL_CWE': grid_c(0), 'C_PL_CWO': grid_c(1),
        'C_PL_BACK': back_rom(),
        'C_PL_WS': dist_table(T1_RUNS, 2048, 2), 'C_PL_WF': dist_table(T2_RUNS, 4096, 4),
        'C_PL_EXP2': exp2_rom(), 'C_PL_SIN': sin_rom(),
    }


