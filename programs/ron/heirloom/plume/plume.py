LNW = 240


def knot(fn, yp):
    if yp >= 496:
        j, t = 30, yp - 480
    else:
        j, t = yp >> 4, yp & 15
    a, b = KNOTS[fn][j], KNOTS[fn][j + 1]
    return a + (((b - a) * t) >> 4)


def line_vals(yp):
    v = {}
    v["xl"] = knot(0, yp)
    v["kx"] = max(knot(1, yp) - knot(0, yp), 0)
    v["hfw"] = knot(3, yp)
    v["bb"] = knot(4, yp)
    v["bk3"] = (knot(5, yp) + 8) >> 4
    v["tz"] = knot(6, yp)
    v["pg"] = knot(7, yp) & 0xFFFF
    env, gdep = knot(8, yp), knot(9, yp)
    v["e1"] = (env * 232) >> 8
    v["e26"] = (env * (gdep * 116)) >> 17
    v["wa3"] = (knot(10, yp) + 16) >> 5
    v["dlt"] = knot(11, yp) & 0xFFFF
    v["sg"] = knot(12, yp)
    v["rl5"] = (knot(13, yp) + 1) >> 1
    return v


def clampd(d, bits):
    lo, hi = -(1 << (bits - 1)), (1 << (bits - 1)) - 1
    return max(lo, min(hi, d))


def ln_words():
    words = []
    for j in range(256):
        y0, y1 = 2 * j, 2 * j + 1
        v0, v1 = line_vals(y0), line_vals(y1)
        a1, a2, xq, wb, mb, ab, go, gk, gc = ROWB[j]
        f = dict(a1=a1, a2=a2, xq=xq, wb=wb, mb=mb, ab6=ab >> 2, go=go, gk6=gk >> 1, gc6=gc >> 1,
                 a0e=ROWA[y0], a0o=ROWA[y1], xl=v0["xl"], kx=v0["kx"], dkx=clampd(v1["kx"] - v0["kx"], 6),
                 hfw=v0["hfw"], fsel=1 if v0["hfw"] > 87 else 0, bb=v0["bb"], dbb=clampd(v1["bb"] - v0["bb"], 4),
                 bk3=v0["bk3"], tz=v0["tz"], pg=v0["pg"], dpg=max(0, min(255, (v1["pg"] - v0["pg"]) & 0xFFFF)),
                 e1=v0["e1"], de1=clampd(v1["e1"] - v0["e1"], 6), e26=v0["e26"], de26=clampd(v1["e26"] - v0["e26"], 5),
                 wa3m=v0["wa3"] - 1, dlt=v0["dlt"], sg=v0["sg"], rl5=v0["rl5"])
        w = 0
        for name, bits, sgn in FIELDS:
            w = (w << bits) | (f[name] & ((1 << bits) - 1))
        used = sum(b for _, b, _ in FIELDS)
        words.append(w << (LNW - used))
    return words


def pw_table():
    out = []
    for b in range(8):
        w = WS[b]
        for p in range(128):
            ph = (p + 0.5) / 128.0
            d = abs(((ph + 0.5) % 1.0) - 0.5)
            v = (math.cos(math.pi * d / w) ** 2 if d < w / 2 else 0.0) * 2 - 1
            out.append(int(round(127 * v)))
    return out


def sc_table():
    out = []
    for p in range(256):
        ph = (p + 0.5) / 256.0
        fr = (ph - SOFF) % 1.0
        s = 1 - fr / (1 - RW) if fr < 1 - RW else (fr - (1 - RW)) / RW
        saw = min(255, int(round(255 * s ** SP)))
        cg = int(round(127 * math.cos(2 * math.pi * (ph - 0.19))))
        out.append((saw << 8) | (cg & 255))
    return out


def cs_table():
    return [int(round(127 * math.cos(2 * math.pi * (p + 0.5) / 256.0))) for p in range(256)]


