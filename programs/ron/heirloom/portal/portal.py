def tables():
    sq = [(u * u) >> 2 for u in range(512)]
    ey = []
    for u in range(512):                                  # eye edges: {u < 482, top offset t1 (7), bottom offset t2 (8)}
        s4 = 4 * sq[u]
        if u > 216:
            t1 = max(min(((s4 + 46656 - 432 * u) * 7) >> 13, 127), (u - 216) >> 3)
        else:
            t1 = (216 - u) >> 3
        if u > 162:
            t2 = max(min(((s4 + 26244 - 324 * u) * 41) >> 15, 255), (u - 162) >> 3)
        else:
            t2 = (162 - u) >> 3
        ey.append(((1 if u < 482 else 0) << 15) | (min(t1, 127) << 8) | min(t2, 255))
    gt = [min(65535, int(round((1 - math.cos(math.pi * i / 960.0)) * 16384))) if i < 960 else 32768 for i in range(1024)]
    mats = []
    for ch in range(3):
        m = []
        for v in range(256):
            rgb = [0.0, 0.0, 0.0]; rgb[ch] = v / 255.0
            y = 0.299 * rgb[0] + 0.587 * rgb[1] + 0.114 * rgb[2]
            cb = (rgb[2] - y) / 1.772; cr = (rgb[0] - y) / 1.402
            Y = int(round(y * 876)); CR = int(round(cr * 896)); CB = int(round(cb * 896))
            m.append((Y << 22) | ((CR & 0x7FF) << 11) | (CB & 0x7FF))
        mats.append(m)
    return dict(pb=list(PB), pr=list(PR), po=list(PO), sq=sq, ey=ey, gt=gt, mr=mats[0], mg=mats[1], mb=mats[2])


def vhdl_array(name, typ, vals, width, hexw):
    s = ['    constant %s : %s := (' % (name, typ)]
    for i in range(0, len(vals), 8):
        chunk = ', '.join('x"%0*X"' % (hexw, v & ((1 << width) - 1)) for v in vals[i:i + 8])
        s.append('        ' + chunk + (',' if i + 8 < len(vals) else ''))
    s.append('    );')
    return '\n'.join(s)


