KEY = dict(l0=95.0, l1=180.0, lmax=235.0, r=25.0)    # cyan fill: G = B = l0 + l1 d (d = saw - k), R = r
REEF_ANG, REEF_SAT = math.pi, 1.0                     # Reef: the complementary hue (CbCr plane rotated 180 deg)


def ycc(rgb):
    r, g, b = [c / 255.0 for c in rgb]
    y = 0.299 * r + 0.587 * g + 0.114 * b
    return y, (b - y) / 1.772, (r - y) / 1.402


def rot(rgb, ang, sat):
    y, cb, cr = ycc(rgb)
    c, s = math.cos(ang), math.sin(ang)
    return y, (cb * c - cr * s) * sat, (cb * s + cr * c) * sat


def hw10(y, cb, cr):
    """Y' 0..1, Cb, Cr -> hardware (Y pre-scaled 16/13, capped 940; U = Cr, V = Cb)"""
    yy = 64 + y * 876
    yy = 64 + (yy - 64) * 16.0 / 13.0
    yy = max(64, min(940, int(round(yy))))
    u = max(4, min(1020, int(round(512 + cr * 896))))
    v = max(4, min(1020, int(round(512 + cb * 896))))
    return yy, u, v


def word(t):
    y, u, v = t
    return (y << 22) | (u << 12) | (v << 2)


def colour(rgb, pal):
    if pal == 0:
        return hw10(*ycc(rgb))
    return hw10(*rot(rgb, REEF_ANG, REEF_SAT))


def key_rgb(i):
    d = i / 64.0
    lv = max(0.0, min(KEY['lmax'], KEY['l0'] + KEY['l1'] * d))
    return (KEY['r'], lv, lv)


def lut_words():
    out = []
    for pal in range(2):
        for i in range(8):
            r = ROWS[min(i, 5)]
            for s in range(64):
                out.append(word(colour(r[s], pal)))
    return out


def tables():
    lut = lut_words()
    key = [word(colour(key_rgb(i), pal)) for pal in range(2) for i in range(64)]
    exp2 = [int(round(32768 * 2 ** (i / 256.0))) for i in range(256)]
    sin = [int(round(32767 * math.sin(2 * math.pi * i / 256.0))) & 0xFFFF for i in range(256)]
    return lut, key, exp2, sin


def vhd_array(name, typ, vals, width):
    digits = (width + 3) // 4
    body = ',\n'.join('        ' + ', '.join('x"%0*X"' % (digits, v) for v in vals[i:i + 8]) for i in range(0, len(vals), 8))
    return '    constant %s : %s := (\n%s);\n' % (name, typ, body)


