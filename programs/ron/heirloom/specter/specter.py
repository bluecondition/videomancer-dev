def rgb_to_hw10(rgb):
    r, g, b = [c / 255.0 for c in rgb]
    y = 0.299 * r + 0.587 * g + 0.114 * b
    cb = (b - y) / 1.772
    cr = (r - y) / 1.402
    return 64 + y * 876, 512 + cr * 896, 512 + cb * 896


def prescale(y10):
    # the shell's 13/16 output luma scale is folded into the palette: the true luma is stored (drawn whites < 600)
    return min(940, y10)


def green_rgb(pal, g):
    if pal == 0:   # Spectre (the clip): pure green ramp over a faint green black
        base = 6.0 * max(0.0, 1.0 - g / 70.0)
        return (base, min(245.0, 13.0 + g), base)
    # Ember: amber haze and ghost
    return (min(252.0, 6.0 + g * 0.98), min(210.0, 3.0 + g * 0.45), 2.0 + g * 0.03)


def blue_rgb(pal, b):
    if pal == 0:   # blue floor (B up to 255 in the clip's other moments)
        return (0.0, 0.0, min(250.0, b * 0.98))
    return (min(160.0, b * 0.55), 0.0, min(250.0, b * 0.98))   # Ember: a violet floor


def pack(y, u, v):
    yi = max(0, min(1023, int(round(y))))
    ui = max(0, min(1023, int(round(u))))
    vi = max(0, min(1023, int(round(v))))
    return (yi << 22) | (ui << 12) | (vi << 2)


def tables():
    t = {}
    t['bg'] = [v for row in BG_MAP for v in row]
    t['fg'] = [v for row in FIG_MAP for v in row]
    palg = []
    for pal in (0, 1):
        for g in range(256):
            y, u, v = rgb_to_hw10(green_rgb(pal, g))
            palg.append(pack(prescale(y), u, v))
    t['palg'] = palg
    palb = []
    for pal in (0, 1):
        for i in range(128):
            b = 2 * i
            y0, u0, v0 = rgb_to_hw10((0, 0, 0))
            y1, u1, v1 = rgb_to_hw10(blue_rgb(pal, b))
            dy = prescale(y1) - prescale(y0)
            palb.append(pack(dy, u1 - u0 + 512, v1 - v0 + 512))
    t['palb'] = palb
    t['exp2'] = [int(round(32768 * 2 ** (i / 256.0))) for i in range(256)]
    t['sin'] = [int(round(127 * math.sin(2 * math.pi * i / 256.0))) & 255 for i in range(256)]
    t['ss'] = [int(round(255 * (lambda x: x * x * (3 - 2 * x))(i / 63.0))) for i in range(64)]
    return t


def vhdl_array(name, typ, vals, hexw):
    items = ['x"%0*X"' % (hexw, v) for v in vals]
    s = "    constant %s : %s := (\n" % (name, typ)
    for k in range(0, len(items), 8):
        s += "        " + ", ".join(items[k:k + 8]) + ("," if k + 8 < len(items) else "") + "\n"
    s += "    );\n"
    return s


