import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))

# background: every 8th entry of the 256-phase profile (phase 0 = y 210, dark plum at phase 0.5 = y 760)
BG_CP = [(255, 0, 246), (255, 0, 247), (255, 0, 246), (255, 0, 246), (255, 0, 246), (255, 0, 245),
         (251, 0, 247), (231, 0, 247), (205, 0, 249), (176, 0, 251), (150, 0, 241), (129, 0, 194),
         (115, 6, 154), (104, 16, 123), (95, 22, 100), (93, 25, 92), (92, 27, 89), (94, 25, 93),
         (96, 21, 103), (105, 17, 120), (110, 10, 140), (121, 3, 168), (134, 0, 199), (149, 0, 239),
         (164, 0, 251), (187, 0, 250), (209, 0, 249), (229, 0, 246), (234, 0, 246), (240, 0, 246),
         (246, 0, 246), (251, 0, 246)]
# texture ring colours (bright body, dark line) for ring A / ring B, purple (O rows) and green families
P_HI = [(150, 0, 238), (104, 4, 200)]
P_LO = [(76, 8, 132), (44, 14, 64)]
G_HI = [(8, 104, 0), (52, 64, 8)]
G_LO = [(24, 26, 14), (28, 24, 20)]
RIM = (255, 0, 248)
SHADOW = (84, 8, 172)


def hw10(rgb):
    r, g, b = [v / 255.0 for v in rgb]
    y = 0.299 * r + 0.587 * g + 0.114 * b
    cb = (b - y) / 1.772
    cr = (r - y) / 1.402
    yy = 64 + y * 876
    yy = 64 + (yy - 64) * 16.0 / 13.0
    yy = min(940, int(round(yy)))
    uu = max(0, min(1023, int(round(512 + cr * 896))))
    vv = max(0, min(1023, int(round(512 + cb * 896))))
    return yy, uu, vv


def word(c):
    return '"' + format((c[0] << 22) | (c[1] << 12) | (c[2] << 2), '032b') + '"'


def lerp(a, b, t):
    return tuple(a[i] + (b[i] - a[i]) * t for i in range(3))


def tex_entry(zone, ringb, ph):
    rr = (ph + 0.5) / 32.0
    sh = rr / 0.6 if rr < 0.6 else (1 - rr) / 0.4 * 0.6 + 0.4
    sh = max(0.0, min(1.0, sh))
    wp = zone / 7.0
    hi = lerp(G_HI[ringb], P_HI[ringb], wp)
    lo = lerp(G_LO[ringb], P_LO[ringb], wp)
    return lerp(lo, hi, sh)


def hk(i):
    # pointed teeth, rounded bays: 1/4 cosine + 3/4 inverted full-wave-rectified sine (zero mean)
    ph = 2 * math.pi * i / 256.0
    return 0.25 * math.cos(ph) + 0.75 * (1 - 2 * abs(math.sin(ph / 2)) + 0.273)


def main():
    exp2 = [int(round(32768 * 2 ** (i / 256.0))) for i in range(256)]
    cos = [int(round(32767 * math.cos(2 * math.pi * i / 1024))) for i in range(1024)]
    ch = [int(round(127 * math.cos(2 * math.pi * i / 256))) for i in range(256)]
    hkt = [int(round(100 * hk(i))) for i in range(256)]
    tex = [hw10(tex_entry(a >> 6, (a >> 5) & 1, a & 31)) for a in range(512)]
    bg = []
    for i in range(256):
        j, t = divmod(i, 8)
        bg.append(hw10(lerp(BG_CP[j], BG_CP[(j + 1) % 32], t / 8.0)))
    sha = []
    for n in range(64):
        v = max(0.0, 1 - n / 56.0) ** 0.7
        sha.append(int(round(16 * v)))
    rim = hw10(RIM)
    shd = hw10(SHADOW)
    L = []
    L.append('-- Generated by spine.py (do not edit).  Hardware colour convention: U = Cr, V = Cb; luma x16/13.')
    L.append('library ieee;\nuse ieee.std_logic_1164.all;\nuse ieee.numeric_std.all;\n')
    L.append('package spine_pkg is')
    L.append('    type t_sp_u16 is array (natural range <>) of unsigned(15 downto 0);')
    L.append('    type t_sp_s16 is array (natural range <>) of signed(15 downto 0);')
    L.append('    type t_sp_s8 is array (natural range <>) of signed(7 downto 0);')
    L.append('    type t_sp_w32 is array (natural range <>) of std_logic_vector(31 downto 0);')
    L.append('    type t_sp_u5 is array (natural range <>) of unsigned(4 downto 0);')
    L.append('    constant C_SP_RIM_Y : integer := %d;' % rim[0])
    L.append('    constant C_SP_RIM_U : integer := %d;' % rim[1])
    L.append('    constant C_SP_RIM_V : integer := %d;' % rim[2])
    L.append('    constant C_SP_SHD_Y : integer := %d;' % shd[0])
    L.append('    constant C_SP_SHD_U : integer := %d;' % shd[1])
    L.append('    constant C_SP_SHD_V : integer := %d;' % shd[2])

    def arr(name, typ, n, vals, fmt):
        L.append('    constant %s : %s(0 to %d) := (' % (name, typ, n - 1))
        items = [fmt(v) for v in vals]
        for k in range(0, n, 8):
            L.append('        ' + ', '.join(items[k:k + 8]) + (',' if k + 8 < n else ''))
        L.append('    );')
    arr('C_SP_EXP2', 't_sp_u16', 256, exp2, lambda v: 'to_unsigned(%d, 16)' % v)
    arr('C_SP_COS', 't_sp_s16', 1024, cos, lambda v: 'to_signed(%d, 16)' % v)
    arr('C_SP_CH', 't_sp_s8', 256, ch, lambda v: 'to_signed(%d, 8)' % v)
    arr('C_SP_HK', 't_sp_s8', 256, hkt, lambda v: 'to_signed(%d, 8)' % v)
    arr('C_SP_TEX', 't_sp_w32', 512, tex, word)
    arr('C_SP_BG', 't_sp_w32', 256, bg, word)
    arr('C_SP_SHA', 't_sp_u5', 64, sha, lambda v: 'to_unsigned(%d, 5)' % v)
    L.append('end package spine_pkg;')
    with open(os.path.join(HERE, 'spine_pkg.vhd'), 'w') as f:
        f.write('\n'.join(L) + '\n')


if __name__ == '__main__':
    main()
