"""
STAIRCASE v0.1.0 - build hook.  Writes staircase_pkg.vhd next to this file (pure python: the builder runs it
with the system python3).  The tables are also imported by the integer model (.heirloom_work/rb_staircase/imodel.py).

Fitted to the still WIN_20230318_14_13_38 at 0.5 s (see .heirloom_work/rb_staircase/notes.md):
  cells  37.55 virtual px x 30.14 virtual lines (51.1 x 35.8 per frame), cell (cx, cy) of the screen centre
         = (25.81, 18.585)
  bricks a cyan / grey checker of bricks 4 cells x 1 row: cyan when floor((cx - 23) / 4) and cy have equal parity
  glyphs a 10 x 10 cell glyph (GLYPH below) on a lattice: group m starts at cell row 17 + 8 m, its glyph's left
         column is 11 - 8 m (mod 32): chains climbing 8 cells right per 8 rows, 32 cells apart
  codes  C cyan, g grey, M magenta, Y yellow, W white, S silver, K black, D dark grey (in that order: the camera
         walks a brick's code along it)

Package contents:
  C_SC_EXP    256 x 16  round(32768 * 2^(i/256))
  C_SC_GLYPH  256 x 5   {opaque, x-cell, code(3)}: index = row * 16 + col (rows 0..9, cols 0..9 used)
  C_SC_PAL    16 x 30   {Y, U, V}: index = palette * 8 + code; U = Cr, V = Cb (hardware convention); luma
                        pre-scaled 16/13 for the shell's 13/16 output scale, capped at 940 (drawn whites ~776)
  C_SC_LUTQ / LUTL / LUTT  16-entry knob tables (rise rows, brick cells, mosaic new-run threshold)
  C_SC_MOS    16 x 3    mosaic code weights (the alt clip's shares)
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))

EXP = [int(round(32768 * 2 ** (i / 256.0))) for i in range(256)]
CODES = 'CgMYWSKD'
GLYPH_ROWS = [
    '.......CYW',
    '......DSC.',
    '.....CKCYW',
    '....DCKC..',
    '...gKCKCYW',
    '..MgKCKC..',
    '.gYgKCKCYW',
    'MWgYCKCKW.',
    '...gKCKS..',
    '..YWCKS...',
]
GLYPH_ARR = [0] * 256
for r, row in enumerate(GLYPH_ROWS):
    for c, ch in enumerate(row):
        if ch == '.':
            continue
        x = 1 if (r == 7 and c >= 4) or r >= 8 else 0     # the X / rail-foot cells
        GLYPH_ARR[r * 16 + c] = 16 | (x << 3) | CODES.index(ch)

def prescale(y):
    return min(940, int(round(64 + (y - 64) * 16 / 13.0)))

# output-referred (Y, U=Cr, V=Cb), hardware convention
PAL_OUT = [
    # the still: cyan, grey, magenta, yellow (luma-capped), white (cream, capped), silver, black, dark grey
    [(683, 83, 637), (483, 525, 496), (449, 871, 794), (776, 587, 70), (776, 520, 476), (708, 521, 489),
     (166, 522, 498), (262, 523, 497)],
    # the alt clip's mosaic: teal, pink, purple, yellow, green, spring green, blue, orange
    [(548, 172, 609), (398, 906, 617), (397, 803, 820), (776, 619, 105), (651, 271, 176), (584, 152, 422),
     (221, 453, 925), (480, 842, 283)],
]
PAL = [[(prescale(y), u, v) for (y, u, v) in p] for p in PAL_OUT]

LUT_Q = [5, 5, 6, 6, 7, 7, 8, 8, 9, 10, 11, 12, 13, 14, 16, 20]
LUT_L = [1, 1, 2, 2, 3, 3, 4, 4, 5, 6, 7, 8, 10, 12, 14, 16]
LUT_T = [min(256, 512 // (l + 1)) for l in LUT_L]
MOS = [1, 1, 1, 1, 0, 0, 0, 0, 4, 4, 6, 6, 7, 3, 5, 2]
FX0C = int(round((25.81 + 128) * 2 ** 20))
FY0C = int(round((18.585 + 64) * 2 ** 20))
OXS = {2: 102, 3: 153, 4: 204}

def vec(v, w):
    return '"' + format(v, '0%db' % w) + '"'

def main():
    L = []
    L.append('-- Generated by staircase.py -- do not edit.')
    L.append('library ieee;\nuse ieee.std_logic_1164.all;\nuse ieee.numeric_std.all;\n')
    L.append('package staircase_pkg is')
    L.append('    type t_sc_exp is array (0 to 255) of unsigned(15 downto 0);')
    L.append('    type t_sc_glyph is array (0 to 255) of std_logic_vector(4 downto 0);')
    L.append('    type t_sc_pal is array (0 to 15) of std_logic_vector(29 downto 0);')
    L.append('    type t_sc_lut is array (0 to 15) of unsigned(4 downto 0);')
    L.append('    type t_sc_lut9 is array (0 to 15) of unsigned(8 downto 0);')
    L.append('    type t_sc_mos is array (0 to 15) of unsigned(2 downto 0);')
    L.append('    constant C_SC_FX0C : integer := %d;' % FX0C)
    L.append('    constant C_SC_FY0C : integer := %d;' % FY0C)
    L.append('    constant C_SC_EXP : t_sc_exp := (')
    L.append(',\n'.join('        to_unsigned(%d, 16)' % v for v in EXP) + ');')
    L.append('    constant C_SC_GLYPH : t_sc_glyph := (')
    L.append(',\n'.join('        %s' % vec(v, 5) for v in GLYPH_ARR) + ');')
    L.append('    constant C_SC_PAL : t_sc_pal := (')
    rows = []
    for p in PAL:
        for (y, u, v) in p:
            rows.append('        %s' % vec((y << 20) | (u << 10) | v, 30))
    L.append(',\n'.join(rows) + ');')
    for name, t in (('C_SC_LUTQ', LUT_Q), ('C_SC_LUTL', LUT_L)):
        L.append('    constant %s : t_sc_lut := (%s);' % (name, ', '.join('to_unsigned(%d, 5)' % v for v in t)))
    L.append('    constant C_SC_LUTT : t_sc_lut9 := (%s);' % ', '.join('to_unsigned(%d, 9)' % v for v in LUT_T))
    L.append('    constant C_SC_MOS : t_sc_mos := (%s);' % ', '.join('to_unsigned(%d, 3)' % v for v in MOS))
    L.append('end package staircase_pkg;')
    with open(os.path.join(HERE, 'staircase_pkg.vhd'), 'w') as f:
        f.write('\n'.join(L) + '\n')

if __name__ == '__main__':
    main()
