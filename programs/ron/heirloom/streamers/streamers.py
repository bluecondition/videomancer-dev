def rgb_to_hw10(rgb):
    r, g, b = [c / 255.0 for c in rgb]
    y = 0.299 * r + 0.587 * g + 0.114 * b
    cb, cr = (b - y) / 1.772, (r - y) / 1.402
    return (64 + y * 876, 512 + cr * 896, 512 + cb * 896)

def drgb_to_hw10(d):
    """an RGB delta -> (dY, dU = dCr, dV = dCb), no offsets"""
    r, g, b = [c / 255.0 for c in d]
    y = 0.299 * r + 0.587 * g + 0.114 * b
    return (y * 876, (r - y) / 1.402 * 896, (b - y) / 1.772 * 896)

def prescale(yuv):
    y, u, v = yuv
    y2 = 64 + (y - 64) * 16.0 / 13.0
    return (int(round(min(940, max(64, y2)))), int(round(min(1000, max(24, u)))), int(round(min(1000, max(24, v)))))

def word(yuv):
    y, u, v = prescale(yuv)
    return (y << 22) | (u << 12) | (v << 2)

def dword(dyuv):
    dy, du, dv = dyuv
    dy = dy * 16.0 / 13.0
    q = [max(-511, min(511, int(round(c)))) & 1023 for c in (dy, du, dv)]
    return (q[0] << 22) | (q[1] << 12) | (q[2] << 2)

def cables(rgb):
    r, g, b = rgb
    return (g, b, r)

def tables():
    lo, hi, gl = [], [], []
    for page in (0, 1):
        for i in range(256):
            a, b, c = T_LO[i], T_HI[i], T_GL[i]
            if page:
                a, b, c = cables(a), cables(b), cables(c)
            lo.append(word(rgb_to_hw10(a)))
            hi.append(word(rgb_to_hw10(b)))
            gl.append(dword(drgb_to_hw10(c)))
    return lo, hi, gl

def sin_rom():
    return [int(round(2047 * math.sin(2 * math.pi * i / 1024.0))) for i in range(1024)]

def exp2_rom():
    return [int(round(32768 * 2 ** (i / 256.0))) for i in range(256)]

def vhd_table(name, typ, depth, width, vals, signed=False):
    lines = ["    type %s is array (0 to %d) of %s(%d downto 0);" % ("t_" + name.lower(), depth - 1, typ, width - 1),
             "    constant %s : %s := (" % (name, "t_" + name.lower())]
    items = []
    for v in vals:
        if signed:
            items.append('to_signed(%d, %d)' % (v, width))
        else:
            items.append('x"%0*X"' % ((width + 3) // 4, v) if width % 4 == 0 else 'to_unsigned(%d, %d)' % (v, width))
    per = 8 if signed else 16
    for i in range(0, len(items), per):
        lines.append("        " + ", ".join(items[i:i + per]) + ("," if i + per < len(items) else ""))
    lines.append("    );")
    return "\n".join(lines)

def main():
    lo, hi, gl = tables()
    parts = ["-- Generated by streamers.py -- DO NOT EDIT.",
             "library ieee;", "use ieee.std_logic_1164.all;", "use ieee.numeric_std.all;", "",
             "package streamers_pkg is",
             vhd_table("C_SM_SIN", "signed", 1024, 12, sin_rom(), signed=True),
             vhd_table("C_SM_EXP2", "unsigned", 256, 16, exp2_rom()),
             vhd_table("C_SM_TLO", "std_logic_vector", 512, 32, lo),
             vhd_table("C_SM_THI", "std_logic_vector", 512, 32, hi),
             vhd_table("C_SM_TGL", "std_logic_vector", 512, 32, gl),
             "end package streamers_pkg;", ""]
    with open(os.path.join(HERE, "streamers_pkg.vhd"), "w") as f:
        f.write("\n".join(parts))

if __name__ == "__main__":
    main()
