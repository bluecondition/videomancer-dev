"""
TARTAN v0.5.0 - build hook.  Emits tartan_pkg.vhd (pure Python, no dependencies).

Fitted to the source photo WIN_20230410_01_13_24 in .heirloom_work/rb_tartan (notes.md,
mkbar.py, rowfit.py); the fitted tables are carried here as data.

  C_TT_BAR  4096 x 8: the A-frame colourizer.  Address = side (0 = left family, 1 = right)
            & 11-bit index (u + 1024, u = |x - 984.5| - 0.9 y in virtual px, folded at the
            table ends).  Bits 2..0 = colour code in the bright bands, 5..3 = in the dark
            bands, 6 = the top-left corner flag (left family, u > 438).
            Codes: 0 black, 1 cyan, 2 green, 3 orange, 4 magenta.
  C_TT_SIN  256 x 16: quarter-wave sine (sin(2 pi (i + 0.5) / 1024) * 32767) for the row
            oscillator's FM.
  C_TT_PAL  16 x 30: two palettes (S10) of 8 entries: black, cyan, green, orange, magenta,
            the yellow fringe on cyan, the fringe on green, the sync-glitch dot.
            Y pre-boosted 16/13 for the output's 13/16 luma scale; U = Cr, V = Cb.
"""
import math, os
HERE = os.path.dirname(os.path.abspath(__file__))

# measured barcodes: (start index, code) runs; index = u + 1024
RLE = {
    (0, 0): [(0, 1), (73, 2), (109, 1), (255, 2), (263, 1), (298, 2), (339, 3), (451, 4), (459, 3), (483, 4),
             (538, 3), (740, 2), (765, 3), (823, 2), (859, 3), (899, 2), (948, 3), (975, 2), (1161, 1), (1187, 2),
             (1230, 1), (1374, 2), (1386, 1), (1419, 2), (1465, 3), (1550, 4), (1747, 3), (1773, 4), (1815, 3)],
    (0, 1): [(0, 0), (53, 2), (75, 0), (130, 2), (163, 0), (454, 1), (472, 0), (534, 1), (563, 0), (609, 1),
             (650, 0), (682, 1), (791, 0), (1251, 2), (1284, 0), (1656, 1), (1674, 0), (1724, 1), (1761, 0),
             (1792, 1), (1874, 0)],
    (1, 0): [(0, 1), (299, 2), (333, 1), (534, 2), (613, 3), (736, 2), (763, 3), (811, 2), (851, 3), (887, 2),
             (944, 3), (967, 2), (1170, 1), (1213, 2), (1240, 1), (1425, 2), (1460, 1), (1660, 2), (1746, 3),
             (1789, 4), (1824, 3)],
    (1, 1): [(0, 0), (132, 2), (280, 0), (457, 1), (480, 0), (530, 1), (566, 0), (604, 1), (657, 0), (683, 1),
             (885, 2), (909, 1), (1081, 0), (1258, 2), (1299, 0), (1328, 2), (1346, 0), (1582, 1), (1603, 0),
             (1657, 1), (1690, 0), (1732, 1), (1782, 0), (1811, 1)],
}
CORNER_IDX = 1024 + 438

# photo colours (RGB), then the alternate "Night" palette
PAL_RGB = [
    [(16, 21, 10), (2, 217, 218), (4, 245, 137), (251, 96, 7), (253, 18, 174), (205, 222, 93), (90, 240, 30),
     (185, 200, 84)],
    [(10, 12, 48), (40, 110, 255), (150, 70, 255), (255, 214, 40), (255, 90, 150), (110, 215, 225),
     (240, 150, 240), (120, 200, 210)],
]


def expand(runs):
    out = [0] * 2048
    for k, (i, c) in enumerate(runs):
        j = runs[k + 1][0] if k + 1 < len(runs) else 2048
        for n in range(i, j):
            out[n] = c
    return out


def bar_table():
    t = []
    for side in (0, 1):
        w = expand(RLE[(side, 0)]); d = expand(RLE[(side, 1)])
        for i in range(2048):
            v = w[i] | (d[i] << 3)
            if side == 0 and i > CORNER_IDX:
                v |= 64
            t.append(v)
    return t


def sin_table():
    return [int(round(32767 * math.sin(2 * math.pi * (i + 0.5) / 1024))) for i in range(256)]


def rgb_to_hw10(r, g, b):
    y = (0.299 * r + 0.587 * g + 0.114 * b) / 255.0
    cb = (b / 255.0 - y) / 1.772
    cr = (r / 255.0 - y) / 1.402
    y10 = 64 + y * 876
    y10 = 64 + (y10 - 64) * 16.0 / 13.0          # pre-boost for the output's 13/16
    return (min(1015, int(round(y10))), max(16, min(1008, int(round(512 + cr * 896)))),
            max(16, min(1008, int(round(512 + cb * 896)))))


def pal_table():
    out = []
    for p in PAL_RGB:
        for rgb in p:
            out.append(rgb_to_hw10(*rgb))
    return out


def arr(name, typ, vals, w):
    rows = []
    for i in range(0, len(vals), 16):
        rows.append("        " + ", ".join('"' + format(v & ((1 << w) - 1), "0" + str(w) + "b") + '"' for v in vals[i:i + 16]))
    return "    constant " + name + " : " + typ + " := (\n" + ",\n".join(rows) + "\n    );"


def emit():
    pal = pal_table()
    cs = [arr("C_TT_BAR", "t_tt_bar", bar_table(), 8),
          arr("C_TT_SIN", "t_tt_sin", sin_table(), 16),
          arr("C_TT_PAL", "t_tt_pal", [(y << 20) | (u << 10) | v for (y, u, v) in pal], 30)]
    txt = ("-- tartan_pkg.vhd -- GENERATED by tartan.py; edit the generator, not this file.\n"
           "-- C_TT_BAR: A-frame colourizer barcodes.  C_TT_SIN: quarter sine.  C_TT_PAL: palettes.\n\n"
           "library ieee;\nuse ieee.std_logic_1164.all;\n\npackage tartan_pkg is\n"
           "    type t_tt_bar is array(0 to 4095) of std_logic_vector(7 downto 0);\n"
           "    type t_tt_sin is array(0 to 255) of std_logic_vector(15 downto 0);\n"
           "    type t_tt_pal is array(0 to 15) of std_logic_vector(29 downto 0);\n" +
           "\n".join(cs) + "\nend package tartan_pkg;\n")
    with open(os.path.join(HERE, "tartan_pkg.vhd"), "w") as fh:
        fh.write(txt)


if __name__ == "__main__":
    emit()
