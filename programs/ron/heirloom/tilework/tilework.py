"""
TILEWORK v0.1.0 - build hook.  Writes tilework_pkg.vhd next to this file (pure python: the builder runs it with
the system python3).

Fitted to the still WIN_20230318_12_24_18 at 4.0 s (see .heirloom_work/rb_tilework/notes.md):

  V      = a triangle through a 3-bit quantizer: v = o + fold(r), r = (y - y_s) / step, fold period 16.1 levels
           (amplitude 8.05: trough 1.0, peak 9.05, clipped at level 7); step 108.75 lines, reset y_s = step - 32;
           above the reset the wave holds the previous field's last value
  H      = a square wave, phi = (x + 97) (1 - 0.024 y / 1080) / 711.1 - 0.184 half-periods, reset per line
  colour = a hue-wheel colouriser: wheel position W = L xor 1 in the side columns, 7 - W in the centre column;
           at every column edge the wheel sweeps the LONG way round (5 or 7 steps), the half turn first, a dwell
           at the complement colour, then the rest (FR_A, FR_B over a 32 virtual px edge)

Package contents (all tables also read by imodel.py):
  C_TW_EXP2  256 x 16   round(32768 * 2^(i/256))
  C_TW_PAL   256 x 32   {Y, U, V, 00} hue wheel: index = 32 * W + fraction (RGB-linear between the 8 wheel colours)
  C_TW_FR    64 x 8     fringe wheel offset (32nds of a step): index = (|D| = 7) * 32 + t, t = 0..31 across the edge
Colours are in the hardware convention (U register = Cr, V register = Cb); luma pre-scaled 16/13 for the shell's
13/16 output scale, capped at 940 (drawn whites ~777).
"""
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))

# colouriser wheel in wheel order (band means measured on the still): blue, magenta, pink, orange, yellow, lime,
# green, cyan.  Side columns show W = L xor 1, so L = 1..7 reads blue, orange, pink, lime, yellow, cyan, green.
WHEEL = [(23, 15, 255), (215, 5, 255), (255, 5, 151), (255, 74, 0),
         (255, 228, 0), (74, 255, 0), (4, 238, 103), (7, 201, 190)]
FR_A, FR_B = 0.30, 0.80


def rgb_to_hw10(rgb):
    r, g, b = [c / 255.0 for c in rgb]
    y = 0.299 * r + 0.587 * g + 0.114 * b
    cb = (b - y) / 1.772
    cr = (r - y) / 1.402
    return (int(round(64 + y * 876)), int(round(512 + cr * 896)), int(round(512 + cb * 896)))


def exp2_rom():
    return [int(round(32768 * 2 ** (i / 256.0))) for i in range(256)]


def wheel_rgb(w):
    i = int(math.floor(w)) % 8
    f = w - math.floor(w)
    a, b = WHEEL[i], WHEEL[(i + 1) % 8]
    return tuple(a[k] * (1 - f) + b[k] * f for k in range(3))


def pal_entry(i):
    y, u, v = rgb_to_hw10(wheel_rgb(i / 32.0))
    y = min(940, int(round((y - 64) * 16 / 13.0 + 64)))
    return y, u, v


def pal_rom():
    out = []
    for i in range(256):
        y, u, v = pal_entry(i)
        out.append((y << 22) | (u << 12) | (v << 2))
    return out


def fr_off(mag, t):
    """wheel offset (32nds of a step) after t/32 of a column edge, for a sweep of |D| = mag steps"""
    tt = t / 32.0
    s1 = min(1.0, tt / FR_A)
    s2 = min(1.0, max(0.0, (tt - FR_B) / (1 - FR_B)))
    return int(round(32 * (4 * s1 + (mag - 4) * s2)))


def fr_rom():
    return [fr_off(5, t) for t in range(32)] + [fr_off(7, t) for t in range(32)]


def vhd_table(name, typ, depth, width, vals):
    lines = ["    type %s is array (0 to %d) of %s(%d downto 0);" % ("t_" + name.lower(), depth - 1, typ, width - 1),
             "    constant %s : %s := (" % (name, "t_" + name.lower())]
    items = [('x"%0*X"' % ((width + 3) // 4, v)) if width % 4 == 0 else 'to_unsigned(%d, %d)' % (v, width)
             for v in vals]
    for i in range(0, len(items), 16):
        lines.append("        " + ", ".join(items[i:i + 16]) + ("," if i + 16 < len(items) else ""))
    lines.append("    );")
    return "\n".join(lines)


def main():
    parts = ["-- Generated by tilework.py -- DO NOT EDIT.",
             "library ieee;", "use ieee.std_logic_1164.all;", "use ieee.numeric_std.all;", "",
             "package tilework_pkg is",
             vhd_table("C_TW_EXP2", "unsigned", 256, 16, exp2_rom()),
             vhd_table("C_TW_PAL", "std_logic_vector", 256, 32, pal_rom()),
             vhd_table("C_TW_FR", "unsigned", 64, 8, fr_rom()),
             "end package tilework_pkg;", ""]
    with open(os.path.join(HERE, "tilework_pkg.vhd"), "w") as f:
        f.write("\n".join(parts))


if __name__ == "__main__":
    main()
