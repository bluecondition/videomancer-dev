    variable h16 : unsigned(15 downto 0);
    variable h : unsigned(11 downto 0);
  begin
    h16 := (cx & cy) xor seed;
    h16 := h16 xor (x"0" & h16(15 downto 4));
    h := h16(11 downto 0);
    return h + rotate_left(h, 5);
  end function;

