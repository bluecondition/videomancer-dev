-- Inferno: Procedural flame — domain-warped multi-octave value noise
-- LZX Industries Community FPGA Program
--
-- Algorithm (shader-style fire, streaming at 1 px/clk, no divides):
--   1. World coords in 1/16 px units rise over time (sub-pixel advection);
--      the warp field rises slower than the flame body so shapes evolve
--      as they climb.  A slow sine-integrated lateral drift sways the flame.
--   2. A low-frequency value noise domain-warps x — real turbulence,
--      licking tongues instead of sinusoidal wobble.
--   3. Three octaves of smooth value noise (16-step smoothstep bilinear) at
--      2:1..4:1 vertical stretch; the finest octave is ridged for filaments.
--   4. Vertical gradient (1 heat unit per line, start value servo-locked to
--      the measured frame height — no divide, adapts to any video mode)
--      minus a noise "cut" -> ragged flame heat field.
--   5. 256-entry blackbody palette in BRAM (fire + blue-flame banks),
--      LFSR heat dither breaks contour banding.
--
