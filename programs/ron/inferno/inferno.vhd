  -- per-frame registers and advances the rise accumulators.  Also samples the
  -- random fade modifiers: two-rate fire flicker and a smoke-extent jitter.
  -- (Sequential because combinational knob*boost products would be real STA
  -- paths into vsync-latched registers.)
  -- ========================================================================
  p_boost : process(clk)
    variable v_op : unsigned(9 downto 0);
    variable v_acc : unsigned(16 downto 0);
    variable v_g : unsigned(11 downto 0);
    variable v_hk : unsigned(6 downto 0);
    variable v_k13 : unsigned(12 downto 0);
    variable v_t : unsigned(6 downto 0);
