    if rising_edge(clk) then
      case b_idx is
        when "00" => v_op := unsigned(registers_in(0));
        when "01" => v_op := unsigned(registers_in(5));
        when others => v_op := unsigned(registers_in(3));
      end case;

      case bst is
        when BI =>
          if data_in.vsync_n = '0' and s_prev_vsync_n = '1' then
            b_boost <= resize(unsigned(registers_in(7)(9 downto 4)), 7) + 16;
            b_idx <= "00";
            b_bit <= "110";
            b_acc <= (others => '0');
            bst <= BM;
          end if;
        when BM =>
          if b_boost(to_integer(b_bit)) = '1' then
            v_acc := (b_acc sll 1) + resize(v_op, 17);
          else
            v_acc := b_acc sll 1;
          end if;
          b_acc <= v_acc;
          if b_bit = 0 then
            case b_idx is
              when "00" => b_fuel <= v_acc;
              when "01" => b_rise <= v_acc;
              when others => b_turb <= v_acc;
            end case;
            b_acc <= (others => '0');
            b_bit <= "110";
            if b_idx = 2 then
              bst <= BF1;
            else
              b_idx <= b_idx + 1;
            end if;
          else
            b_bit <= b_bit - 1;
          end if;
        when BF1 =>
          -- gbot = min(260 + fuel*boost/32, 1023)
          v_g := resize(b_fuel srl 5, 12) + 260;
          if v_g > 1023 then v_g := to_unsigned(1023, 12); end if;
          s_gbot <= v_g(9 downto 0);
          -- heatk = min(10 + fuel*boost/1024, 31)
          v_hk := resize(b_fuel srl 10, 7) + 10;
          if v_hk > 31 then v_hk := to_unsigned(31, 7); end if;
          s_heatk <= v_hk(4 downto 0);
          -- turb4 = min(turb*boost/1024, 15)
          v_t := resize(b_turb srl 10, 7);
          if v_t > 15 then v_t := to_unsigned(15, 7); end if;
          s_turb4 <= v_t(3 downto 0);
          -- rise_eff = rise*boost/16 (13 bits)
          b_riseff <= resize(b_rise srl 4, 13);
          -- Layer 2 sits 1/4 of the fuel height below layer 1.  At 3/8 it
          -- almost never won the max (it needed fbm2-fbm1 > ~78 to break
          -- through) so it was invisible; at 1/8 it flooded 44% of the frame.
          -- 1/4 lets it hold coherent patches among layer 1's flames.
          s_g2off <= signed(resize(v_g srl 2, 13));
          bst <= BF2;
        when BF2 =>
          -- (255*heatk)/8 via shift-sub; combined fire jitter
          v_k13 := resize(s_heatk, 13);
          v_k13 := (v_k13 sll 8) - v_k13;
          s_c255k3 <= resize(v_k13 srl 3, 10);
          -- Smoke extent is K3 ALONE (K3/4 -> 0..255), NOT boosted.
          -- Intensify used to multiply it (smk*boost/64): at 5x that is
          -- 1.23*K3, so the smoke hit its 255 ceiling by ~20% of the knob and
          -- the rest of the travel did nothing.  Fuel/rise/turbulence still
          -- scale with Intensify; smoke now spans the full knob at any boost.
          s_smokek <= unsigned(registers_in(2)(9 downto 2));
          -- advance the rise accumulators (moved here from the vsync block)
          s_yoff  <= s_yoff  + resize(b_riseff srl 3, 16);
          s_yoffw <= s_yoffw + resize(b_riseff srl 4, 16)
                            + resize(b_riseff srl 5, 16);
          s_yoffd <= s_yoffd + resize(b_riseff srl 4, 16);
          bst <= BF3;
        when BF3 =>
          s_gbotc <= signed(resize(s_gbot, 13))
                   - signed(resize(s_c255k3, 13));
          bst <= BI;
      end case;
    end if;
  end process p_boost;

  -- ========================================================================
  -- Canny edge detector (half-res ticks on odd pixels) -> surf map
  -- ========================================================================
  p_canny : process(clk)
    variable v_pair : unsigned(11 downto 0);
    variable v_gs : unsigned(9 downto 0);
    variable v_gxp, v_gxn, v_gyp, v_gyn : unsigned(9 downto 0);
    variable v_gx, v_gy : signed(11 downto 0);
    variable v_mag : unsigned(11 downto 0);
    variable v_prev, v_acc, v_new, v_fb : std_logic;
    variable v_yw : unsigned(10 downto 0);
    variable v_y2, v_lasty : unsigned(9 downto 0);
    variable v_cnt : unsigned(1 downto 0);
  begin
    if rising_edge(clk) then
      -- ---- tick generation (half-res): phase 0 stores the even pixel and
      -- issues the line-buffer reads; phase 1 launches a pipeline tick.
      d1_v <= '0';
      sf_we0 <= '0';  sf_we1 <= '0';  sf_we2 <= '0';
      if data_in.avid = '1' then
        case s_pixel_x(1 downto 0) is
          when "00" =>
            c_acc <= resize(unsigned(data_in.y), 12);
          when "01" =>
            c_acc <= c_acc + unsigned(data_in.y);
          when "10" =>
            c_acc <= c_acc + unsigned(data_in.y);
            c_q1 <= lb1(to_integer(c_dcx));
            c_q2 <= lb2(to_integer(c_dcx));
          when others =>
            v_pair := c_acc + unsigned(data_in.y);
            d1_th <= v_pair(11 downto 4);
            d1_q1 <= c_q1;
            d1_q2 <= c_q2;
            d1_col <= c_dcx;
            d1_v <= '1';
            c_dcx <= c_dcx + 1;
        end case;
        c_seen <= '1';
      end if;

      -- ---- D1: horizontal [1,2,1] -> gsm; line-buffer row rotate; window
      if d1_v = '1' then
        v_gs := ("00" & d1_th) + ('0' & c_h1 & '0') + ("00" & c_h2);
        d2_g  <= v_gs(9 downto 2);
        d2_br <= v_gs(9);
        d2_q1 <= d1_q1;
        d2_q2 <= d1_q2;
        lb1(to_integer(d1_col)) <= v_gs(9 downto 2);
        lb2(to_integer(d1_col)) <= d1_q1;
        c_h2 <= c_h1;
        c_h1 <= d1_th;
        d2_col <= d1_col;
      end if;
      d2_v <= d1_v;

      -- ---- D2: 3x3 Sobel column/row sums (window = d2 regs + p1 + p2)
      if d2_v = '1' then
        v_gxp := ("00" & d2_g) + ('0' & d2_q1 & '0') + ("00" & d2_q2);
        v_gxn := ("00" & c_p2g) + ('0' & c_p2q1 & '0') + ("00" & c_p2q2);
        v_gyp := ("00" & d2_q2) + ('0' & c_p1q2 & '0') + ("00" & c_p2q2);
        v_gyn := ("00" & d2_g) + ('0' & c_p1g & '0') + ("00" & c_p2g);
        d3_gx <= signed(resize(v_gxp, 12)) - signed(resize(v_gxn, 12));
        d3_gy <= signed(resize(v_gyp, 12)) - signed(resize(v_gyn, 12));
        c_p2g <= c_p1g;  c_p2q1 <= c_p1q1;  c_p2q2 <= c_p1q2;
        c_p1g <= d2_g;   c_p1q1 <= d2_q1;   c_p1q2 <= d2_q2;
        d3_col <= d2_col;
        d3_br <= d2_br;
      end if;
      d3_v <= d2_v;

      -- ---- D3: |gx|+|gy| magnitude + double threshold; state read issue
      if d3_v = '1' then
        v_gx := d3_gx;  if v_gx < 0 then v_gx := -v_gx; end if;
        v_gy := d3_gy;  if v_gy < 0 then v_gy := -v_gy; end if;
        v_mag := unsigned(v_gx) + unsigned(v_gy);
        v_mag := '0' & v_mag(11 downto 1);
        d4_strong <= '0';  d4_weak <= '0';
        if v_mag > resize(s_thi, 12) then d4_strong <= '1'; end if;
        if v_mag > resize(s_tlo, 12) then d4_weak <= '1'; end if;
        c_sbq <= sbuf(to_integer(d3_col - 2));
        d4_col <= d3_col - 2;
        d4_br <= d3_br;
      end if;
      d4_v <= d3_v;

      -- ---- D4: hysteresis + per-column edge slots (up to 3, >=8 lines
      --      apart so a thick edge doesn't eat every slot)
      if d4_v = '1' then
        v_prev := '0';
        v_cnt := "00";
        v_lasty := (others => '0');
        if c_sbq(14 downto 13) = std_logic_vector(s_lmframe) then
          v_prev := c_sbq(12);
          v_cnt := unsigned(c_sbq(11 downto 10));
          v_lasty := unsigned(c_sbq(9 downto 0));
        end if;
        v_acc := d4_strong or (d4_weak and (v_prev or c_left));
        -- first two ACTIVE lines: the window still holds the previous
        -- frame's bottom rows -> spurious edges would steal the slots
        if c_warm < 2 then v_acc := '0'; end if;
        c_left <= v_acc;

        if s_pixel_y = 0 then v_yw := (others => '0');
        else v_yw := resize(s_pixel_y - 1, 11); end if;
        v_y2 := v_yw(10 downto 1);

        -- slot policy: first two distinct edges + ALWAYS the lowest edge
        -- (first-3-from-top starved the lower edges of stacked columns ->
        -- black boxes; the lowest root's rising flames cover the middle).
        -- 24 half-line spacing (48 lines) spreads the roots: closer edges
        -- produce near-identical flames anyway.
        v_new := '0';
        if v_acc = '1'
           and (v_cnt = 0 or (v_y2 - v_lasty) >= 24) then
          v_new := '1';
        end if;
        -- luma fallback: while a column has NO edges yet (cnt=0), every
        -- bright sample re-roots slot0 -> an edgeless bright column (e.g. a
        -- full-height near-vertical bar mid-rotation, tips off-screen) ends
        -- the frame rooted at its lowest bright pixel and burns bottom-up
        -- instead of leaving a moving black bar.  A real edge takes slot0
        -- back the moment it appears.
        v_fb := d4_br and not v_cnt(1) and not v_cnt(0);
        sf_we0 <= (v_new and not v_cnt(1) and not v_cnt(0)) or v_fb;
        sf_we1 <= v_new and not v_cnt(1) and v_cnt(0);
        sf_we2 <= v_new and v_cnt(1);
        sf_waddr <= d4_col;
        sf_wdata <= '1' & std_logic_vector(v_y2);
        if v_new = '1' then
          if v_cnt /= 3 then v_cnt := v_cnt + 1; end if;
          v_lasty := v_y2;
        end if;
        sbuf(to_integer(d4_col)) <= std_logic_vector(s_lmframe) & v_acc
          & std_logic_vector(v_cnt) & std_logic_vector(v_lasty);
      end if;

      if data_in.hsync_n = '0' and s_prev_hsync_n = '1' then
        c_dcx <= (others => '0');
        c_left <= '0';
        c_h1 <= (others => '0');  c_h2 <= (others => '0');
        c_p1g <= (others => '0'); c_p1q1 <= (others => '0'); c_p1q2 <= (others => '0');
        c_p2g <= (others => '0'); c_p2q1 <= (others => '0'); c_p2q2 <= (others => '0');
        if c_seen = '1' then
          c_seen <= '0';
          if c_warm /= 3 then c_warm <= c_warm + 1; end if;
        end if;
      end if;
      if data_in.vsync_n = '0' and s_prev_vsync_n = '1' then
        c_warm <= (others => '0');
        c_seen <= '0';
      end if;
    end if;
  end process p_canny;

  -- ========================================================================
  -- Vblank: flip the write bank, then clear it (512 writes) before the
  -- detector refills it.  Display reads the bank completed last frame.
  -- ========================================================================
  p_sweep : process(clk)
  begin
    if rising_edge(clk) then
      if sw_active = '1' then
        sw_addr <= sw_addr + 1;
        if sw_addr = 511 then sw_active <= '0'; end if;
      end if;
      if data_in.vsync_n = '0' and s_prev_vsync_n = '1' then
        s_bank <= not s_bank;
        sw_active <= '1';
        sw_addr <= (others => '0');
      end if;
    end if;
  end process p_sweep;

  -- slot RAM ports: display reads the completed bank; detector (or the
  -- vblank clear) writes the other
  -- shading read runs 8 px behind the raster so the 5-stage shading chain
  -- (read/hop/w/candidates/max) lands exactly at S14 without an 8-deep
  -- 13-bit result pipe (saved ~104 FFs).  First 8 px of a line clamp to
  -- column 0 (luma-mod only; 4px columns make this invisible).
  p_lmaddr : process(clk)
  begin
    if rising_edge(clk) then
      if s_pixel_x < 7 then
        s_lmx <= (others => '0');
      else
        s_lmx <= s_pixel_x - 7;
      end if;
    end if;
  end process p_lmaddr;
  srf_raddr <= (not s_bank) & unsigned(s_lmx(10 downto 2));
  srf_waddr_lo <= sw_addr when sw_active = '1' else sf_waddr;
  srf_waddr <= s_bank & srf_waddr_lo;
  srf_wd <= (others => '0') when sw_active = '1' else sf_wdata;
  srf_we <= sw_active;

  -- ========================================================================
  -- Luma-Mod shading: per-pixel gradient rooted on the surface map
  --   (read S2, fabric hop S3, distance S4, gradient S5, gc S6, pipe to S14)
  -- ========================================================================
  p_lm : process(clk)
    variable v_d : signed(11 downto 0);
    variable v_g : signed(14 downto 0);
    variable v_m : signed(12 downto 0);
    variable v_sq : std_logic_vector(10 downto 0);
  begin
    if rising_edge(clk) then
      -- S3: fabric FF hop off the BRAM read ports (reads in p_surf0..2)
      lm3_sq0 <= lm_sq0;
      lm3_sq1 <= lm_sq1;
      lm3_sq2 <= lm_sq2;
      -- S4: per-slot WEIGHTED distance (g is monotone decreasing in it:
      --     w = -d above the edge, 16*d in the glow skirt below, big if
      --     stale/deep) -> the envelope needs only min(w), one gradient cone
      for i in 0 to 2 loop
        case i is
          when 0 => v_sq := lm3_sq0;
          when 1 => v_sq := lm3_sq1;
          when others => v_sq := lm3_sq2;
        end case;
        v_d := signed(resize(s_pixel_y(11 downto 1), 12))
             - signed(resize(unsigned(v_sq(9 downto 0)), 12));
        if v_sq(10) = '0' or v_d >= 32 then
          lm4_w(i) <= to_unsigned(1023, 10);
        elsif v_d >= 0 then
          lm4_w(i) <= resize(unsigned(v_d(5 downto 0)) & "0000", 10);
        else
          lm4_w(i) <= resize(unsigned(-v_d), 10);
        end if;
      end loop;
      -- S5: per-slot gradient candidates in PARALLEL (g is monotone in w,
      --     so max(g_i) == g(min(w)); the serial min->sub->clamp chain was
      --     the HD Analog critical path).  gbot - 255k/8 is pre-folded.
      for i in 0 to 2 loop
        v_g := resize(s_gbotc, 15) - signed(resize(lm4_w(i) & '0', 15));
        if v_g < -1024 then v_g := to_signed(-1024, 15); end if;
        lm5_p(i) <= resize(v_g, 13);
      end loop;
      -- S6: envelope = max of the candidates; S7..S13 pipe
      if lm5_p(1) > lm5_p(0) then v_m := lm5_p(1); else v_m := lm5_p(0); end if;
      if lm5_p(2) > v_m then v_m := lm5_p(2); end if;
      s_gclm <= v_m;
    end if;
  end process p_lm;

  -- ========================================================================
  -- Edge-slot RAMs in canonical 1W1R single-process form (a case-mux write
  -- from the detector process defeated BRAM inference -> 70k LC explosion)
  -- ========================================================================
  p_surf0 : process(clk)
  begin
    if rising_edge(clk) then
      if srf_we = '1' or (sw_active = '0' and sf_we0 = '1') then
        surf0(to_integer(srf_waddr)) <= srf_wd;
      end if;
      lm_sq0 <= surf0(to_integer(srf_raddr));
    end if;
  end process p_surf0;

  p_surf1 : process(clk)
  begin
    if rising_edge(clk) then
      if srf_we = '1' or (sw_active = '0' and sf_we1 = '1') then
        surf1(to_integer(srf_waddr)) <= srf_wd;
      end if;
      lm_sq1 <= surf1(to_integer(srf_raddr));
    end if;
  end process p_surf1;

  p_surf2 : process(clk)
  begin
    if rising_edge(clk) then
      if srf_we = '1' or (sw_active = '0' and sf_we2 = '1') then
        surf2(to_integer(srf_waddr)) <= srf_wd;
      end if;
      lm_sq2 <= surf2(to_integer(srf_raddr));
    end if;
  end process p_surf2;

  -- ========================================================================
  -- S2: Horizontal width scaling -> world coords (1/16 px units)
  -- world_x = (px - 512) * widthk, where widthk/16 is the zoom factor
  -- ========================================================================
  p_s2 : process(clk)
    variable v_xc : signed(13 downto 0);
    variable v_m  : signed(20 downto 0);
  begin
    if rising_edge(clk) then
      v_xc := signed(resize(s_pixel_x, 14)) - to_signed(512, 14);
      v_m  := v_xc * signed('0' & s_widthk);
      s2_wxs <= unsigned(v_m(15 downto 0));
      s2_wy  <= (resize(s_pixel_y, 12) & "0000") + s_yoff;
      s2_wyw <= (resize(s_pixel_y, 12) & "0000") + s_yoffw;
    end if;
  end process p_s2;

  -- ========================================================================
  -- S3: Warp noise corners (2 noises, 64 px cells) — 8 hashes, half A
  -- ========================================================================
  p_s3 : process(clk)
    variable v_wxw : unsigned(15 downto 0);
    variable v_cxa, v_cya : unsigned(5 downto 0);
  begin
    if rising_edge(clk) then
      v_wxw := s2_wxs + unsigned(s_drift);
      v_cxa := v_wxw(15 downto 10);
      v_cya := s2_wyw(15 downto 10);
      s3_ha(0) <= hash_a(resize(v_cxa, 8),     resize(v_cya, 8),     x"517C");
      s3_ha(1) <= hash_a(resize(v_cxa + 1, 8), resize(v_cya, 8),     x"517C");
      s3_ha(2) <= hash_a(resize(v_cxa, 8),     resize(v_cya + 1, 8), x"517C");
      s3_ha(3) <= hash_a(resize(v_cxa + 1, 8), resize(v_cya + 1, 8), x"517C");
      s3_fxa <= C_SS(to_integer(v_wxw(9 downto 6)));
      s3_fya <= C_SS(to_integer(s2_wyw(9 downto 6)));

      d_wxs(0) <= s2_wxs;  d_wy(0) <= s2_wy;
      for i in 1 to 3 loop d_wxs(i) <= d_wxs(i-1); d_wy(i) <= d_wy(i-1); end loop;
    end if;
  end process p_s3;

  -- ========================================================================
  -- S4: Warp hashes, half B
  -- ========================================================================
  p_s4 : process(clk)
  begin
    if rising_edge(clk) then
      for i in 0 to 3 loop s4_h(i) <= hash_b(s3_ha(i)); end loop;
      s4_fxa <= s3_fxa;  s4_fya <= s3_fya;
    end if;
  end process p_s4;

  -- ========================================================================
  -- S5: Warp X lerps (4 mults)
  -- ========================================================================
  p_s5 : process(clk)
  begin
    if rising_edge(clk) then
      s5_ta <= lerp8(s4_h(0), s4_h(1), s4_fxa);
      s5_ba <= lerp8(s4_h(2), s4_h(3), s4_fxa);
      s5_fya <= s4_fya;
    end if;
  end process p_s5;

  -- ========================================================================
  -- S6: Warp Y lerps -> nwx, nwy
  -- ========================================================================
  p_s6 : process(clk)
  begin
    if rising_edge(clk) then
      s6_nwx <= lerp8(s5_ta, s5_ba, s5_fya);
    end if;
  end process p_s6;

  -- ========================================================================
  -- S7: Apply domain warp: dx = (nwx-128)*turb/2 (x only — the x warp
  --      dominates the look; the y warp did not justify its cost)
  -- ========================================================================
  p_s7 : process(clk)
    variable v_dx : signed(13 downto 0);
  begin
    if rising_edge(clk) then
      v_dx := resize((signed(resize(s6_nwx, 9)) - 128) * signed('0' & s_turb4), 14);
      s7_ax  <= d_wxs(3) + unsigned(resize(v_dx sra 1, 16));
      s7_ay  <= d_wy(3);
      s7_ay3 <= d_wy(3) + s_yoffd;
    end if;
  end process p_s7;

  -- ========================================================================
  -- S8: Main octave corners — 12 hashes, half A
  --   o1: 32x128 px cells (tall tongues), o2: 16x32, o3 (ridged): 8x16
  -- ========================================================================
  p_s8 : process(clk)
  begin
    if rising_edge(clk) then
      -- corner +1 wraps within each cell field so 16-bit coords stay seamless
      s8_ha(0) <= hash_a(resize(s7_ax(15 downto 9), 8),     resize(s7_ay(15 downto 11), 8),     x"1234");
      s8_ha(1) <= hash_a(resize(s7_ax(15 downto 9) + 1, 8), resize(s7_ay(15 downto 11), 8),     x"1234");
      s8_ha(2) <= hash_a(resize(s7_ax(15 downto 9), 8),     resize(s7_ay(15 downto 11) + 1, 8), x"1234");
      s8_ha(3) <= hash_a(resize(s7_ax(15 downto 9) + 1, 8), resize(s7_ay(15 downto 11) + 1, 8), x"1234");
      s8_fx1 <= C_SS(to_integer(s7_ax(8 downto 5)));
      s8_fy1 <= C_SS6(to_integer(s7_ay(10 downto 5)));

      s8_ha(4) <= hash_a(s7_ax(15 downto 8),     resize(s7_ay(15 downto 9), 8),     x"5678");
      s8_ha(5) <= hash_a(s7_ax(15 downto 8) + 1, resize(s7_ay(15 downto 9), 8),     x"5678");
      s8_ha(6) <= hash_a(s7_ax(15 downto 8),     resize(s7_ay(15 downto 9) + 1, 8), x"5678");
      s8_ha(7) <= hash_a(s7_ax(15 downto 8) + 1, resize(s7_ay(15 downto 9) + 1, 8), x"5678");
      s8_fx2 <= C_SS(to_integer(s7_ax(7 downto 4)));
      s8_fy2 <= C_SS(to_integer(s7_ay(8 downto 5)));

      -- LAYER 2: same warped coords sampled one bit coarser in both axes
      -- (64x256 px cells = wider tongues, and the rise baked into ay is
      -- halved with it -> a slower, more distant fire).  Own seed.
      s8_ha(12) <= hash_a(s7_ax(14 downto 7),     s7_ay3(15 downto 8),     x"9ABC");
      s8_ha(13) <= hash_a(s7_ax(14 downto 7) + 1, s7_ay3(15 downto 8),     x"9ABC");
      s8_ha(14) <= hash_a(s7_ax(14 downto 7),     s7_ay3(15 downto 8) + 1, x"9ABC");
      s8_ha(15) <= hash_a(s7_ax(14 downto 7) + 1, s7_ay3(15 downto 8) + 1, x"9ABC");
      s8_fx3 <= C_SS(to_integer(s7_ax(6 downto 3)));
      s8_fy3 <= C_SS(to_integer(s7_ay3(7 downto 4)));

      s8_ha(8)  <= hash_a(resize(s7_ax(15 downto 10), 8),     resize(s7_ay(15 downto 12), 8),     x"BEEF");
      s8_ha(9)  <= hash_a(resize(s7_ax(15 downto 10) + 1, 8), resize(s7_ay(15 downto 12), 8),     x"BEEF");
      s8_ha(10) <= hash_a(resize(s7_ax(15 downto 10), 8),     resize(s7_ay(15 downto 12) + 1, 8), x"BEEF");
      s8_ha(11) <= hash_a(resize(s7_ax(15 downto 10) + 1, 8), resize(s7_ay(15 downto 12) + 1, 8), x"BEEF");
      s8_fx4 <= C_SS(to_integer(s7_ax(9 downto 6)));
      s8_fy4 <= C_SS6(to_integer(s7_ay(11 downto 6)));
    end if;
  end process p_s8;

  -- ========================================================================
  -- S9: Main hashes, half B
  -- ========================================================================
  p_s9 : process(clk)
  begin
    if rising_edge(clk) then
      for i in 0 to 15 loop s9_h(i) <= hash_b(s8_ha(i)); end loop;
      s9_fx1 <= s8_fx1;  s9_fy1 <= s8_fy1;
      s9_fx2 <= s8_fx2;  s9_fy2 <= s8_fy2;
      s9_fx3 <= s8_fx3;  s9_fy3 <= s8_fy3;
      s9_fx4 <= s8_fx4;  s9_fy4 <= s8_fy4;
    end if;
  end process p_s9;

  -- ========================================================================
  -- S10: Main octave X lerps (6 mults)
  -- ========================================================================
  p_s10 : process(clk)
  begin
    if rising_edge(clk) then
      s10_t1 <= lerp8(s9_h(0), s9_h(1), s9_fx1);
      s10_b1 <= lerp8(s9_h(2), s9_h(3), s9_fx1);
      s10_t2 <= lerp8(s9_h(4), s9_h(5), s9_fx2);
      s10_b2 <= lerp8(s9_h(6), s9_h(7), s9_fx2);
      s10_t3 <= lerp8(s9_h(12), s9_h(13), s9_fx3);
      s10_b3 <= lerp8(s9_h(14), s9_h(15), s9_fx3);
      s10_t4 <= lerp8(s9_h(8), s9_h(9), s9_fx4);
      s10_b4 <= lerp8(s9_h(10), s9_h(11), s9_fx4);
      s10_fy1 <= s9_fy1;  s10_fy2 <= s9_fy2;  s10_fy3 <= s9_fy3;
      s10_fy4 <= s9_fy4;
    end if;
  end process p_s10;

  -- ========================================================================
  -- S11: Main octave Y lerps (3 mults)
  -- ========================================================================
  p_s11 : process(clk)
    variable v_d1, v_d2, v_d3, v_d4 : signed(9 downto 0);
  begin
    if rising_edge(clk) then
      -- S11a: difference * fraction only.  lerp8 chained sub -> mult -> add in
      -- ONE stage and was the critical path (5 ns logic + 9 ns routing); the
      -- add now happens in S11b.
      v_d1 := signed(resize(s10_b1, 10)) - signed(resize(s10_t1, 10));
      v_d2 := signed(resize(s10_b2, 10)) - signed(resize(s10_t2, 10));
      v_d3 := signed(resize(s10_b3, 10)) - signed(resize(s10_t3, 10));
      v_d4 := signed(resize(s10_b4, 10)) - signed(resize(s10_t4, 10));
      s11a_m1 <= resize(v_d1 * signed('0' & s10_fy1), 17);
      s11a_m2 <= resize(v_d2 * signed('0' & s10_fy2), 14);
      s11a_m3 <= resize(v_d3 * signed('0' & s10_fy3), 14);
      s11a_m4 <= resize(v_d4 * signed('0' & s10_fy4), 17);
      s11a_t1 <= s10_t1;  s11a_t2 <= s10_t2;
      s11a_t3 <= s10_t3;  s11a_t4 <= s10_t4;
    end if;
  end process p_s11;

  -- ========================================================================
  -- S11b: a + product>>shift  (o1 and L2 use the 6-bit fine fraction, o2 the
  -- 4-bit coarse one)
  -- ========================================================================
  p_s11b : process(clk)
    variable v_r : signed(11 downto 0);
  begin
    if rising_edge(clk) then
      v_r := resize(signed(resize(s11a_t1, 10)) + resize(s11a_m1 sra 6, 12), 12);
      s11_n1 <= unsigned(v_r(7 downto 0));
      v_r := resize(signed(resize(s11a_t2, 10)) + resize(s11a_m2 sra 4, 12), 12);
      s11_n2 <= unsigned(v_r(7 downto 0));
      v_r := resize(signed(resize(s11a_t3, 10)) + resize(s11a_m3 sra 4, 12), 12);
      s11_n3 <= unsigned(v_r(7 downto 0));
      v_r := resize(signed(resize(s11a_t4, 10)) + resize(s11a_m4 sra 6, 12), 12);
      s11_n4 <= unsigned(v_r(7 downto 0));
    end if;
  end process p_s11b;

  -- ========================================================================
  -- S12: FBM combine — fbm = (n1*9 + n2*5 + ridge(n3)*2) / 16
  -- ========================================================================
  p_s12 : process(clk)
    variable v_d9, v_d9b : unsigned(8 downto 0);
    variable v_r3, v_r4 : unsigned(7 downto 0);
    variable v_sum, v_sum2 : unsigned(11 downto 0);
  begin
    if rising_edge(clk) then
      -- ridge: 255 - 2*|n3 - 128|  (peaks where n3 crosses mid) -> filaments
      if s11_n3 >= 128 then
        v_d9 := resize(s11_n3 - 128, 9) sll 1;
      else
        v_d9 := resize(128 - s11_n3, 9) sll 1;
      end if;
      if v_d9 > 255 then v_d9 := to_unsigned(255, 9); end if;
      v_r3 := 255 - v_d9(7 downto 0);
      v_sum := (resize(s11_n1, 12) sll 3) + resize(s11_n1, 12)
             + (resize(s11_n2, 12) sll 2) + resize(s11_n2, 12)
             + (resize(v_r3, 12) sll 1);
      s12_fbm <= v_sum(11 downto 4);

      -- LAYER 2 fbm: value + its own ridge fold (one sample, two characters:
      -- soft body + a licking crease) -> (n4*10 + ridge(n4)*6) / 16
      if s11_n4 >= 128 then
        v_d9b := resize(s11_n4 - 128, 9) sll 1;
      else
        v_d9b := resize(128 - s11_n4, 9) sll 1;
      end if;
      if v_d9b > 255 then v_d9b := to_unsigned(255, 9); end if;
      v_r4 := 255 - v_d9b(7 downto 0);
      v_sum2 := (resize(s11_n4, 12) sll 3) + (resize(s11_n4, 12) sll 1)
              + (resize(v_r4, 12) sll 2) + (resize(v_r4, 12) sll 1);
      s12_fbm2 <= v_sum2(11 downto 4);
    end if;
  end process p_s12;

  -- ========================================================================
  -- S13: fbm*heatk product (raw = gc + this>>3, the "255-fbm" inversion
  --       is algebraically folded into the per-line gc constant) + wisp gate
  -- ========================================================================
  p_s13 : process(clk)
  begin
    if rising_edge(clk) then
      s13_fk <= s12_fbm * s_heatk;
      s13_fk2 <= s12_fbm2 * s_heatk;
      -- wisp gate for smoke: clip((fbm-110)*2, 0..240)
      if s12_fbm > 230 then
        s13_wisp <= to_unsigned(240, 8);
      elsif s12_fbm > 110 then
        s13_wisp <= resize((s12_fbm - 110) sll 1, 8);
      else
        s13_wisp <= (others => '0');
      end if;
    end if;
  end process p_s13;

  -- ========================================================================
  -- S14: raw heat = g - cut/8 + dither (unclamped; knee/clamp in S15,
  --      the negative range drives the smoke band above the flame)
  -- ========================================================================
  p_s14 : process(clk)
  begin
    if rising_edge(clk) then
      if s_lumamod = '1' then
        s14_raw <= resize(s_gclm, 14) + signed(resize(s13_fk srl 3, 14))
                 + resize(signed('0' & s_lfsr_q(2 downto 0)), 14) - 4;
        s14_raw2 <= resize(s_gclm, 14) - resize(s_g2off, 14)
                  + signed(resize(s13_fk2 srl 3, 14));
      else
        s14_raw <= resize(s_gc, 14) + signed(resize(s13_fk srl 3, 14))
                 + resize(signed('0' & s_lfsr_q(2 downto 0)), 14) - 4;
        s14_raw2 <= resize(s_gc, 14) - resize(s_g2off, 14)
                  + signed(resize(s13_fk2 srl 3, 14));
      end if;
      s14_wisp <= s13_wisp;
    end if;
  end process p_s14;

  -- ========================================================================
  -- S14b: superimpose the layers.  MAX in raw-heat space == max after the
  -- knee/clamp (both are monotone), so the layers composite like real fire
  -- (the hotter one wins) for one 14-bit compare and no second palette read.
  -- ========================================================================
  p_s14b : process(clk)
  begin
    if rising_edge(clk) then
      if s14_raw2 > s14_raw then
        s14b_raw <= s14_raw2;
        s14b_l2 <= '1';          -- layer 2 is the hotter one here
      else
        s14b_raw <= s14_raw;
        s14b_l2 <= '0';
      end if;
      s14b_wisp <= s14_wisp;
    end if;
  end process p_s14b;

  -- ========================================================================
  -- S15: heat via PARALLEL compares on raw + one 4:1 mux (serial
  --      knee->clamp->ember chained ~8 ns of logic and missed timing):
  --        raw < 0            -> 0
  --        ember band 49..175 -> raw + 64   (max 239, needs no knee/clamp)
  --        raw > 584          -> 255        (knee output ceiling)
  --        raw > 208          -> 208 + (raw-208)/8
  --        else               -> raw
  --      Smoke terms are computed here but min-reduced over S16/S17,
  --      one 8-bit compare per stage.
  -- ========================================================================
  p_s15 : process(clk)
    variable v_raw  : signed(13 downto 0);
    variable v_kn   : signed(13 downto 0);
    variable v_t    : signed(13 downto 0);
    variable v_emb  : std_logic;
  begin
    if rising_edge(clk) then
      v_raw := s14b_raw;
      s15_l2 <= s14b_l2;
      -- opaque-fire flag for Overlay (raw >= 16 == the visible flame envelope)
      if v_raw >= 16 then s15_fire <= '1'; else s15_fire <= '0'; end if;
      v_kn := 208 + ((v_raw - 208) sra 3);
      v_emb := '0';
      if s_ember = '1' and s_lfsr_q(8 downto 4) = "00000"
         and v_raw > 48 and v_raw < 176 then
        v_emb := '1';
      end if;

      if v_raw < 0 then
        s15_heat <= (others => '0');
      elsif v_emb = '1' then
        s15_heat <= unsigned(v_raw(7 downto 0)) + 64;
      elsif v_raw > 584 then
        s15_heat <= (others => '1');
      elsif v_raw > 208 then
        s15_heat <= unsigned(v_kn(7 downto 0));
      else
        s15_heat <= unsigned(v_raw(7 downto 0));
      end if;

      -- smoke ramp-in: clip((16 - raw)*4, 0..255)
      v_t := (to_signed(16, 14) - v_raw) sll 2;
      if v_t < 0 then s15_ri <= (others => '0');
      elsif v_t > 255 then s15_ri <= to_unsigned(255, 8);
      else s15_ri <= unsigned(v_t(7 downto 0)); end if;
      -- altitude attenuation: clip((-raw)/8 + (255-S)/2, 0..255) — smoke
      -- dissipates as it rises; weak wisps die low, strong ones reach the top
      v_t := signed(resize((to_unsigned(255, 8) - s_smokek) srl 1, 14))
           - (v_raw sra 3);
      if v_t < 0 then s15_att <= (others => '0');
      elsif v_t > 255 then s15_att <= to_unsigned(255, 8);
      else s15_att <= unsigned(v_t(7 downto 0)); end if;
      -- wisp gate capped at the smoke luma ceiling
      if s14b_wisp > 120 then s15_w2 <= to_unsigned(120, 8);
      else s15_w2 <= s14b_wisp; end if;
    end if;
  end process p_s15;

  -- ========================================================================
  -- S16: Palette BRAM read (bank select = blue flame)
  -- ========================================================================
  p_s16 : process(clk)
  begin
    if rising_edge(clk) then
      s16_pal <= C_PAL(to_integer(unsigned'(s_blue & s15_l2 & s15_heat)));
      s16_fire <= s15_fire;
      if s15_w2 < s15_ri then s16_m1 <= s15_w2; else s16_m1 <= s15_ri; end if;
      s16_att <= s15_att;
    end if;
  end process p_s16;

  -- ========================================================================
  -- S17: Register palette word off the BRAM read port; centre the chroma
  -- ========================================================================
  p_s17 : process(clk)
  begin
    if rising_edge(clk) then
      s17_py <= unsigned(s16_pal(29 downto 20));
      s17_cu <= signed(resize(unsigned(s16_pal(19 downto 10)), 11)) - 512;
      s17_cv <= signed(resize(unsigned(s16_pal( 9 downto  0)), 11)) - 512;
      s17_fire <= s16_fire;
      if s16_att >= s16_m1 then s17_smoke <= (others => '0');
      else s17_smoke <= s16_m1 - s16_att; end if;
    end if;
  end process p_s17;

  -- ========================================================================
  -- S18: Intensity (Y and chroma) + tint; smoke gets the same 4-step gain
  -- ========================================================================
  p_s18 : process(clk)
    variable v_y, v_u, v_v : unsigned(9 downto 0);
    variable v_cu, v_cv : signed(10 downto 0);
    variable v_sy : unsigned(9 downto 0);
  begin
    if rising_edge(clk) then
      -- P12 is now the Intensify boost (applied per-frame in p_boost);
      -- output gain is fixed at full
      v_y := s17_py;
      v_cu := s17_cu;
      v_cv := s17_cv;

      -- smoke luma: value<<2 (0..480)
      v_sy := resize(s17_smoke, 10) sll 2;
      s18_smk <= v_sy;
      s18_fire <= s17_fire;

      if v_cu > 511 then v_cu := to_signed(511, 11); end if;
      if v_cv > 511 then v_cv := to_signed(511, 11); end if;
      v_cu := v_cu + 512;
      v_cv := v_cv + 512;
      v_u := unsigned(v_cu(9 downto 0));
      v_v := unsigned(v_cv(9 downto 0));

      s18_y <= v_y;  s18_u <= v_u;  s18_v <= v_v;
    end if;
  end process p_s18;

  -- ========================================================================
  -- S19: Composite.  Overlay = fire OVER video: fire is OPAQUE inside the
  -- flame envelope (s18_fire), smoke is 50% transparent, and the video shows
  -- through everywhere else.  (Was a saturating ADD, which tinted the whole
  -- picture instead of covering it.)  Smoke chroma is neutral 512, so the 50%
  -- blend is 256 + video/2 — shifts and adds only, no multiplies.
  -- ========================================================================
  p_s19 : process(clk)
    variable v_vy, v_vu, v_vv : unsigned(9 downto 0);
  begin
    if rising_edge(clk) then
      v_vy := unsigned(vd_q19(29 downto 20));
      v_vu := unsigned(vd_q19(19 downto 10));
      v_vv := unsigned(vd_q19( 9 downto  0));

      if s_overlay = '1' then
        if s18_fire = '1' then
          -- fire covers the video completely
          s19_y <= s18_y;  s19_u <= s18_u;  s19_v <= s18_v;
        elsif s18_smk > (to_unsigned(48, 10)
                         + (unsigned(s_lfsr_q(1 downto 0)) & "00")) then
          -- smoke: 50/50 with the video, chroma pulled halfway to neutral
          s19_y <= ('0' & s18_smk(9 downto 1)) + ('0' & v_vy(9 downto 1));
          s19_u <= to_unsigned(256, 10) + ('0' & v_vu(9 downto 1));
          s19_v <= to_unsigned(256, 10) + ('0' & v_vv(9 downto 1));
        else
          s19_y <= v_vy;  s19_u <= v_vu;  s19_v <= v_vv;
        end if;
      else
        -- no video: fire on black, smoke gray where it is brighter
        if s18_smk > s18_y then
          s19_y <= s18_smk;
          s19_u <= to_unsigned(512, 10);
          s19_v <= to_unsigned(512, 10);
        else
          s19_y <= s18_y;  s19_u <= s18_u;  s19_v <= s18_v;
        end if;
      end if;
    end if;
  end process p_s19;

  -- ========================================================================
  -- Output
  -- ========================================================================
  data_out.y <= data_in.y when s_bypass = '1' else std_logic_vector(s19_y);
  data_out.u <= data_in.u when s_bypass = '1' else std_logic_vector(s19_u);
  data_out.v <= data_in.v when s_bypass = '1' else std_logic_vector(s19_v);
  data_out.hsync_n <= data_in.hsync_n when s_bypass = '1' else sync_hs(C_LATENCY - 1);
  data_out.vsync_n <= data_in.vsync_n when s_bypass = '1' else sync_vs(C_LATENCY - 1);
  -- field_n changes once per field; a 21-clock skew is irrelevant, so it
  -- passes straight through instead of riding a 21-bit shift register
  data_out.field_n <= data_in.field_n;
  data_out.avid    <= data_in.avid when s_bypass = '1' else sync_avid(C_LATENCY - 1);

end architecture inferno;
