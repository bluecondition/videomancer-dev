"""
WALLPAPER v0.1.0 (Kinetic) - build hook.  Writes wallpaper_pkg.vhd next to this file (pure python: the builder
runs it with the system python3).  The integer model (.kinetic_work/rb_wallpaper/imodel.py) reads the same tables.

Package contents:
  C_WP_TAB   1024 x 16   0 .. 255: round(32768 * 2^(i/256))       (pitch and rate are exponential)
                         256 + palette * 12 + colour * 3 + (0 Y, 1 U, 2 V): the 16 shared Kinetic palettes x
                         (ground, A, B, accent), 10-bit, hardware convention (U register = Cr, V register = Cb)
                         512 + figure * 16 + n: the five motif figures, ten parameters each (10-bit signed)
  C_WP_SIN   1024 x 16   round(16383 * sin((i + 1/2) pi / 2048))  (a quarter wave; 4096 points per cycle)
  C_WP_SQ    512 x 16    (i * i) >> 2                             (the disc's squares)
"""
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))

# The 16 shared Kinetic palettes (copied from .kinetic_work/tools/kpalette.py so this folder is self-contained)
PALETTES = [
    # label        ground     A          B          accent
    ("Ink",        "#0E0E10", "#F2EFE6", "#8C8C8C", "#E23B2E"),
    ("Paper",      "#F2EFE6", "#141414", "#9A9A94", "#1F4E9E"),
    ("Bauhaus",    "#EDE4CF", "#D1362F", "#1F4E9E", "#F0B81C"),
    ("Vega",       "#0B1E5B", "#1BB5E8", "#D81E8C", "#F5D90A"),
    ("Outrun",     "#12002B", "#FF2E97", "#00D9F5", "#FFB000"),
    ("Ultra",      "#0D0221", "#7B2CBF", "#E0AAFF", "#3CF2C0"),
    ("Ocean",      "#03045E", "#0096C7", "#90E0EF", "#F4F1DE"),
    ("Ice",        "#06141B", "#9BD1E5", "#F1F7FA", "#4A7C9B"),
    ("Moss",       "#0F2A1D", "#7FB069", "#E6F0A3", "#F18F01"),
    ("Citrus",     "#14213D", "#FCA311", "#E5E5E5", "#E63946"),
    ("Terra",      "#2B1A12", "#C8553D", "#F2D0A4", "#588B8B"),
    ("Ember",      "#1A0A00", "#FF4500", "#FFB347", "#8C1C13"),
    ("Gold",       "#0A0A0A", "#D4A017", "#F6E7B0", "#7A5C00"),
    ("Candy",      "#FFF1E6", "#FF6B9D", "#56CBF9", "#FFD23F"),
    ("Mint",       "#F7F3E9", "#2EC4B6", "#FF6B6B", "#1D3557"),
    ("Plum",       "#2D1E2F", "#F7B2AD", "#9ABCA7", "#F2E94E"),
]

# The motif: a disc (accent), a bar (colour A) and a wedge (colour B: a right triangle, right angle top-left),
# in motif units (the motif's quadrant is +-512 at full size; x right, y down).  Each primitive keeps to its own
# sector in every figure (bar x <= -20; wedge x >= 20, y <= -20; disc x, y >= 20), so they never touch while the
# Shape knob interpolates between neighbouring figures.
#            cx   cy    R    bx   by   hw   hh   x0    y0    c  (wedge: x >= x0, y >= y0, x + y <= c)
FIGURES = [
    ("Pin",  160, 190, 125, -150,   0,  55, 420,  30, -300,  -20),
    ("Flag", 210, 230, 175, -110,   0,  75, 400,  25, -350,  -15),
    ("Sail", 120, 120,  85, -215, 230, 165,  65,  20, -350,  -10),
    ("Dot",  200, 200, 180, -260,   0,  55, 300, 110, -310,  -20),
    ("Slab", 200, 200, 135, -210,   0, 160, 270,  40, -280,  -10),
]


def hw10(h):
    """sRGB hex -> (y, u, v) 10-bit, hardware convention (u = Cr, v = Cb), BT.601, Y = 64 + 876 y."""
    h = h.lstrip("#")
    r, g, b = [int(h[i:i + 2], 16) / 255.0 for i in (0, 2, 4)]
    y = 0.299 * r + 0.587 * g + 0.114 * b
    cb = (b - y) / 1.772
    cr = (r - y) / 1.402
    return (int(round(64 + y * 876)), int(round(512 + cr * 896)), int(round(512 + cb * 896)))


def pal_table():
    """16 x 4 list of (y, u, v)."""
    return [[hw10(c) for c in p[1:]] for p in PALETTES]


def exp2_rom():
    return [int(round(32768 * 2 ** (i / 256.0))) for i in range(256)]


def sin_rom():
    return [int(round(16383 * math.sin((i + 0.5) * math.pi / 2048.0))) for i in range(1024)]


def sq_rom():
    return [(i * i) >> 2 for i in range(512)]


def tab_rom():
    out = exp2_rom()
    for p in pal_table():
        for (y, u, v) in p:
            out += [y, u, v]
    out += [0] * (512 - len(out))
    for f in FIGURES:
        out += [v & 0xFFFF for v in f[1:]] + [0] * 6
    return out + [0] * (1024 - len(out))


def vhd_table(name, typ, depth, width, vals):
    lines = ["    type %s is array (0 to %d) of %s(%d downto 0);" % ("t_" + name.lower(), depth - 1, typ, width - 1),
             "    constant %s : %s := (" % (name, "t_" + name.lower())]
    items = ['x"%0*X"' % (width // 4, v) for v in vals]
    for i in range(0, len(items), 16):
        lines.append("        " + ", ".join(items[i:i + 16]) + ("," if i + 16 < len(items) else ""))
    lines.append("    );")
    return "\n".join(lines)


def main():
    parts = ["-- Generated by wallpaper.py -- DO NOT EDIT.",
             "library ieee;", "use ieee.std_logic_1164.all;", "use ieee.numeric_std.all;", "",
             "package wallpaper_pkg is",
             vhd_table("C_WP_TAB", "unsigned", 1024, 16, tab_rom()),
             vhd_table("C_WP_SIN", "unsigned", 1024, 16, sin_rom()),
             vhd_table("C_WP_SQ", "unsigned", 512, 16, sq_rom()),
             "end package wallpaper_pkg;", ""]
    with open(os.path.join(HERE, "wallpaper_pkg.vhd"), "w") as f:
        f.write("\n".join(parts))


if __name__ == "__main__":
    main()
