"""
MOOD - build hook.

Generates mood_pkg.vhd (shared by MOOD and MOOD HD):

  C_UCODE    1024 x 32  the virtual-time sample program (mood_ucode.py,
                        assembled by mood_uasm.py)
  C_ROM      1024 x 16  quarter sine + raw tables (mood_tables.py)
  C_RF_INIT   128 x 16  register-file power-up values
  C_XSTEP / C_YSTEP / C_HSTC / C_VSTC / C_TICK
                        per format class: virtual clocks per pixel, virtual
                        lines per field line, CLEAN tile-phase steps, and
                        pixel clocks per 15.734 kHz sample tick
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import mood_tables as T                     # noqa: E402
from mood_ucode import build                # noqa: E402

TICK = {'1080p': 4719, '1080i': 4719, '720p': 4719,
        '480i': 858, '576i': 858, '480p': 1716, '576p': 1716}


def arr(name, typ, vals, fmt):
    rows = []
    for i in range(0, len(vals), 8):
        rows.append('        ' + ', '.join(fmt(v) for v in vals[i:i + 8]))
    return f'    constant {name} : {typ} := (\n' + ',\n'.join(rows) + ');\n'


def main():
    A = build()
    words = A.words()
    words += [0] * (1024 - len(words))
    rom = T.rom()
    rf = A.rf_init()
    cls = T.CLASSES + [T.CLASSES[0]]       # class 7 unused: 1080p
    xstep = [round(T.VIS_CLK * 65536 / w) for _, w, _ in cls]
    ystep = [round(T.VIS_LINES * 65536 / l) for _, _, l in cls]
    hstc = [round(2 ** 24 / w) for _, w, _ in cls]
    vstc = [round(2 ** 24 / l) for _, _, l in cls]
    tick = [TICK[n] - 1 for n, _, _ in cls]
    assert max(xstep) < 65536 and max(ystep) < 65536 and max(vstc) < 2 ** 17

    h32 = lambda v: f'x"{v & 0xFFFFFFFF:08X}"'
    h16 = lambda v: f'x"{v & 0xFFFF:04X}"'
    u = lambda w: (lambda v: f'to_unsigned({v}, {w})')

    out = []
    w = out.append
    w('-- Generated by mood.py -- DO NOT EDIT')
    w(f'-- microcode: {len(A.code)} words, {len(A.regs)} registers')
    w('library ieee;\nuse ieee.std_logic_1164.all;\nuse ieee.numeric_std.all;\n')
    w('package mood_pkg is')
    w('    type t_ucode is array (0 to 1023) of std_logic_vector(31 downto 0);')
    w('    type t_rom   is array (0 to 1023) of std_logic_vector(15 downto 0);')
    w('    type t_rf    is array (0 to 127) of std_logic_vector(15 downto 0);')
    w('    type t_cu16  is array (0 to 7) of unsigned(15 downto 0);')
    w('    type t_cu17  is array (0 to 7) of unsigned(16 downto 0);')
    w('    type t_cu13  is array (0 to 7) of unsigned(12 downto 0);')
    w(f'    constant C_Y_OBJ : natural := {T.Y_OBJ};')
    w(arr('C_XSTEP', 't_cu16', xstep, u(16)))
    w(arr('C_YSTEP', 't_cu16', ystep, u(16)))
    w(arr('C_HSTC', 't_cu16', hstc, u(16)))
    w(arr('C_VSTC', 't_cu17', vstc, u(17)))
    w(arr('C_TICK', 't_cu13', tick, u(13)))
    w(arr('C_RF_INIT', 't_rf', rf, h16))
    w(arr('C_ROM', 't_rom', rom, h16))
    w(arr('C_UCODE', 't_ucode', words, h32))
    w('end package mood_pkg;')
    text = '\n'.join(out) + '\n'
    targets = [os.path.join(HERE, 'mood_pkg.vhd')]
    hd = os.path.join(os.path.dirname(HERE), 'mood_hd')
    if os.path.isdir(hd):
        targets.append(os.path.join(hd, 'mood_pkg.vhd'))
    for t in targets:
        old = open(t).read() if os.path.exists(t) else None
        if old != text:
            open(t, 'w').write(text)
    print(f'mood_pkg.vhd: {len(A.code)} microcode words, {len(A.regs)} registers')


if __name__ == '__main__':
    main()
