"""
MOOD HD - build hook.

MOOD HD is MOOD's CLEAN render: the same design (programs/ron/mood) built
with G_CLEAN = true.  This hook refreshes the two shared sources in this
folder from MOOD's: mood_core.vhd (copied) and mood_pkg.vhd (regenerated by
mood.py, which writes both folders).
"""
import os
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(os.path.dirname(HERE), 'mood')

subprocess.run([sys.executable, os.path.join(SRC, 'mood.py')], check=True)
src = os.path.join(SRC, 'mood_core.vhd')
dst = os.path.join(HERE, 'mood_core.vhd')
if not os.path.exists(dst) or open(src).read() != open(dst).read():
    shutil.copyfile(src, dst)
print('mood_hd: shared sources refreshed')
