"""
HACHURE v0.1.0 - build hook.  Writes hachure_pkg.vhd next to this file (pure python: the builder runs it with the
system python3).  The integer model (.onevolt_work/rb_hachure/imodel.py) imports the same tables.

Package contents:
  C_HA_SIN   256 x 16   round(1023 sin(pi/2 n / 256)), n = 0 .. 255 (n = 256 is 1023, handled in logic): the
                        Navigator's quarter-wave sine (1024 steps per turn)
  C_HA_PAL   256 x 16   the Matte colours: index = set (3 bits) & tint (1) & zone (2) & channel (2: Y, U, V, -)
                        eight designed four-colour sets (zone 0 = outermost .. zone 3 = centre, luma ascending);
                        tint = 1: one hue per set, the zones differing only in brightness and whiteness
Colours are in the hardware convention (U register = Cr, V register = Cb).  Luma is pre-scaled 16/13 for the
shell's 13/16 output scale (capped at 940).
"""
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))

SETS = [
    [(140, 60, 20), (230, 60, 30), (250, 190, 40), (255, 240, 200)],     # 0 Engraver
    [(230, 0, 200), (0, 210, 255), (255, 235, 0), (250, 250, 250)],      # 1 CMY
    [(20, 40, 200), (0, 160, 170), (160, 240, 40), (200, 255, 250)],     # 2 Lagoon
    [(130, 40, 255), (255, 40, 170), (0, 230, 255), (200, 255, 60)],     # 3 Neon
    [(40, 50, 230), (230, 30, 120), (255, 140, 0), (255, 245, 120)],     # 4 Relief (the default)
    [(30, 60, 200), (230, 30, 30), (255, 210, 0), (250, 250, 245)],      # 5 Bauhaus
    [(20, 110, 40), (40, 200, 60), (190, 230, 0), (240, 255, 180)],      # 6 Moss
    [(60, 40, 200), (40, 120, 255), (110, 200, 255), (240, 250, 255)],   # 7 Ice
]
BLACK = (64, 512, 512)


def tint_ramp(cols):
    """one hue (the set's third colour at full value): deep, full, then two steps toward white"""
    c = cols[2]
    m = max(c)
    t = [v * 255.0 / m for v in c]
    w = 255.0
    return [tuple(v * 0.5 for v in t), tuple(v * 0.8 for v in t),
            tuple(v + (w - v) * 0.35 for v in t), tuple(v + (w - v) * 0.7 for v in t)]


def rgb_to_hw10f(rgb):
    r, g, b = [c / 255.0 for c in rgb]
    y = 0.299 * r + 0.587 * g + 0.114 * b
    cb, cr = (b - y) / 1.772, (r - y) / 1.402
    return (64 + y * 876, 512 + cr * 896, 512 + cb * 896)


def prescale(yuv):
    y, u, v = yuv
    y2 = 64 + (y - 64) * 16.0 / 13.0
    y2 = int(round(min(940, max(64, y2))))
    return (y2, int(round(min(1023, max(0, u)))), int(round(min(1023, max(0, v)))))


def pal_rom():
    out = []
    for s in range(8):
        for tint in (0, 1):
            cols = SETS[s] if tint == 0 else tint_ramp(SETS[s])
            for z in range(4):
                y, u, v = prescale(rgb_to_hw10f(cols[z]))
                out += [y, u, v, 0]
    return out


def sin_rom():
    return [int(round(1023 * math.sin(math.pi / 2 * n / 256))) for n in range(256)]


def vhd_table(name, typ, depth, width, vals):
    lines = ["    type %s is array (0 to %d) of %s(%d downto 0);" % ("t_" + name.lower(), depth - 1, typ, width - 1),
             "    constant %s : %s := (" % (name, "t_" + name.lower())]
    items = ['x"%0*X"' % ((width + 3) // 4, v) for v in vals]
    for i in range(0, len(items), 16):
        lines.append("        " + ", ".join(items[i:i + 16]) + ("," if i + 16 < len(items) else ""))
    lines.append("    );")
    return "\n".join(lines)


def main():
    parts = ["-- Generated by hachure.py -- DO NOT EDIT.",
             "library ieee;", "use ieee.std_logic_1164.all;", "use ieee.numeric_std.all;", "",
             "package hachure_pkg is",
             vhd_table("C_HA_SIN", "unsigned", 256, 16, sin_rom()),
             vhd_table("C_HA_PAL", "unsigned", 256, 16, pal_rom()),
             "end package hachure_pkg;", ""]
    with open(os.path.join(HERE, "hachure_pkg.vhd"), "w") as f:
        f.write("\n".join(parts))


if __name__ == "__main__":
    main()
