"""
MARQUETRY v0.1.0 - build hook.  Writes marquetry_pkg.vhd next to this file (pure python, no numpy: the builder
runs it with the system python3).  The integer model (.onevolt_work/rb_marquetry/imodel.py) imports the same data.

Package contents:
  (Isohelie's eight bit orders, ORD / perm_rom(), are written out as the case function f_perm in marquetry.vhd)
  C_MQ_COL   256 x 16   Matrice colourings for the K5 sweep: address = pair * 32 + item * 2 + sel
                        pair  = 0 .. 6 (colouring i blended toward colouring i + 1)
                        item  = 0 oY, 1 oU, 2 oV (offset, codes), 3 .. 11 = A Y U V, B Y U V, C Y U V
                                (the table writer's increment per index step, Q8 codes; Y pre-scaled 16/13)
                        sel   = 0 the value of colouring i, 1 its difference to colouring i + 1
Colours are in the hardware convention (U register = Cr, V register = Cb).
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))

# Isohelie bit orders: output bits (b2', b1', b0') taken from input bits; z = 0 is the original order.  The guide
# shows eight different stepped shapes but does not list them: six are the permutations of three bits, the last two
# are multiplexer settings that send one input bit to two outputs (the ramp folds into two repeats).
ORD = [(2, 1, 0), (2, 0, 1), (1, 2, 0), (0, 1, 2), (1, 0, 2), (0, 2, 1), (0, 1, 0), (1, 0, 0)]

# Matrice colourings: RGB columns for channels A (diamond), B (rectangle), C (cross) and an offset (inverts)
COL = [
    # 0 RGB hot: Isohelie on R, G, B with the crosspoints and the encoder pushed (the hero)
    dict(o=(-0.25, -0.25, -0.25), a=(1.40, 0.0, 0.0), b=(0.0, 1.23, 0.0), c=(0.0, 0.0, 1.40)),
    # 1 Primaries: red-orange / blue / a little green
    dict(o=(-0.05, -0.05, -0.05), a=(1.05, 0.15, 0.0), b=(0.0, 0.30, 1.05), c=(0.05, 0.60, 0.10)),
    # 2 CMY: magenta / yellow / cyan
    dict(o=(-0.05, -0.05, -0.05), a=(0.66, 0.0, 0.62), b=(0.64, 0.58, 0.0), c=(0.0, 0.55, 0.66)),
    # 3 Neon: magenta / azure, the cross inverted (pre-invert) onto green
    dict(o=(0.0, 0.45, 0.10), a=(0.90, 0.0, 0.70), b=(0.0, 0.45, 0.90), c=(0.0, -0.45, -0.10)),
    # 4 Ice
    dict(o=(0.0, 0.02, 0.06), a=(0.05, 0.32, 0.70), b=(0.38, 0.38, 0.32), c=(0.0, 0.42, 0.22)),
    # 5 Mono
    dict(o=(0.0, 0.0, 0.0), a=(0.48, 0.48, 0.48), b=(0.33, 0.33, 0.33), c=(0.24, 0.24, 0.24)),
    # 6 Woods (marquetry proper)
    dict(o=(0.02, 0.01, 0.0), a=(0.58, 0.32, 0.08), b=(0.34, 0.21, 0.06), c=(0.24, 0.18, 0.10)),
    # 7 Fire
    dict(o=(0.0, 0.0, 0.02), a=(0.80, 0.05, 0.0), b=(0.32, 0.42, 0.0), c=(0.20, 0.25, 0.28)),
]
LEVELS = 224        # Matrice table index of a full-scale level (Isohelie: 32 per DAC step, 7 steps)


def yuv(rgb):
    """linear RGB (0..1 units, any sign) -> hardware YUV contribution in codes (Y pre-scaled 16/13), floats"""
    r, g, b = rgb
    y = 0.299 * r + 0.587 * g + 0.114 * b
    cb, cr = (b - y) / 1.772, (r - y) / 1.402
    return (y * 876.0 * 16.0 / 13.0, cr * 896.0, cb * 896.0)


def items(col):
    """the 12 per-colouring numbers: offset (codes, absolute) and the nine table increments (Q8 per index step)"""
    o = yuv(col['o'])
    out = [int(round(64 + o[0])), int(round(512 + o[1])), int(round(512 + o[2]))]
    for k in ('a', 'b', 'c'):
        m = yuv(col[k])
        out += [int(round(v * 256.0 / LEVELS)) for v in m]
    return out


def col_rom():
    rom = [0] * 256
    it = [items(c) for c in COL]
    for i in range(7):
        for j in range(12):
            v = it[i][j]
            d = it[i + 1][j] - it[i][j]
            assert -2048 <= v < 2048 and -2048 <= d < 2048, (i, j, v, d)
            assert j < 3 or -1020 <= v <= 1020, (i, j, v)       # table accumulators: 255 x inc < 2^18
            rom[i * 32 + j * 2] = v & 0xFFFF
            rom[i * 32 + j * 2 + 1] = d & 0xFFFF
    return rom


def perm_rom():
    t = []
    for z in range(8):
        o = ORD[z]
        for n in range(8):
            b = [(n >> i) & 1 for i in range(3)]
            t.append((b[o[0]] << 2) | (b[o[1]] << 1) | b[o[2]])
    return t


def vhd_table(name, typ, depth, width, vals):
    lines = ["    type %s is array (0 to %d) of %s(%d downto 0);" % ("t_" + name.lower(), depth - 1, typ, width - 1),
             "    constant %s : %s := (" % (name, "t_" + name.lower())]
    if width % 4 == 0:
        items_ = ['x"%0*X"' % (width // 4, v) for v in vals]
    else:
        items_ = ['"%s"' % format(v, '0%db' % width) for v in vals]
    for i in range(0, len(items_), 16):
        lines.append("        " + ", ".join(items_[i:i + 16]) + ("," if i + 16 < len(items_) else ""))
    lines.append("    );")
    return "\n".join(lines)


def main():
    parts = ["-- Generated by marquetry.py -- DO NOT EDIT.",
             "library ieee;", "use ieee.std_logic_1164.all;", "use ieee.numeric_std.all;", "",
             "package marquetry_pkg is",
             vhd_table("C_MQ_COL", "std_logic_vector", 256, 16, col_rom()),
             "end package marquetry_pkg;", ""]
    with open(os.path.join(HERE, "marquetry_pkg.vhd"), "w") as f:
        f.write("\n".join(parts))


if __name__ == "__main__":
    main()
