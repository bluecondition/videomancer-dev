"""
ONDINE v0.1.0 - build hook.  Writes ondine_pkg.vhd next to this file (pure python: the builder runs it with the
system python3).  The integer model (.onevolt_work/rb_ondine/imodel.py) imports the same tables.

Package contents:
  C_OD_SIN   512 x 16   Formes sine shaper, half range: round(65536 (1 - cos(pi (i + 1/2) / 1024)) / 2)
                        (t in 0 .. 1/2; the upper half is 65535 - s(1 - t)); also the LFOs' raised cosine
  C_OD_EXP   256 x 16   round(32768 * 2^(i / 256))
  C_OD_COL   128 x 16   Matrice colourings: 8 x 16 words, words 0..8 = per-tap Y, U, V coefficients
                        (tap k at word 3 j + k for channel j = Y, U, V; signed, x 256/255 so a tap value
                        cv (0..255) contributes (coef * cv) >> 8), words 9..11 = Y, U, V offsets
Colours are in the hardware convention (U register = Cr, V register = Cb).  The Matrice settings are pure
assignments of the three taps (s0 = Combines out, r2 = after rectifier 2, r4 = after rectifier 4) to R, G, B with
inverts, so R, G, B stay inside 0 .. 1 V and every blend between two settings does too.
"""
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))

# R, G, B rows: tap letter a = s0, b = r2, c = r4; '~' = inverted (1 - v)
COLS = ['~b,~c,~a', '~c,~b,~a', 'c,~b,~a', 'c,~b,a', 'a,~b,c', 'a,~c,~b', '~a,~c,~b', '~a,~c,b']
KY = (0.299, 0.587, 0.114)
KU = (0.5, -0.418688, -0.081312)       # Cr  (hardware U)
KV = (-0.168736, -0.331264, 0.5)       # Cb  (hardware V)


def sin_rom():
    return [int(round(65536 * (1 - math.cos(math.pi * (i + 0.5) / 1024)) / 2)) for i in range(512)]


def exp_rom():
    return [int(round(32768 * 2 ** (i / 256.0))) for i in range(256)]


def colouring(spec):
    w = [[0, 0, 0], [0, 0, 0], [0, 0, 0]]     # w[channel][tap]
    o = [0, 0, 0]
    for ch, s in enumerate(spec.split(',')):
        inv = s.startswith('~')
        k = 'abc'.index(s[-1])
        w[ch][k] = -1 if inv else 1
        o[ch] = 1 if inv else 0
    words = []
    for K, full, base in ((KY, 876, 64), (KU, 896, 512), (KV, 896, 512)):
        for k in range(3):
            v = full * sum(K[ch] * w[ch][k] for ch in range(3)) * 256.0 / 255.0
            words.append(int(round(v)))
    for K, full, base in ((KY, 876, 64), (KU, 896, 512), (KV, 896, 512)):
        words.append(int(round(base + full * sum(K[ch] * o[ch] for ch in range(3)))))
    return words          # 12: cY0 cY1 cY2 cU0 cU1 cU2 cV0 cV1 cV2 oY oU oV


def col_rom():
    out = []
    for s in COLS:
        w = colouring(s)
        out += w + [0, 0, 0, 0]
    return out


def _vec(vals, width):
    return ',\n        '.join(', '.join('x"%0*X"' % ((width + 3) // 4, v & ((1 << width) - 1)) for v in vals[i:i + 8])
                              for i in range(0, len(vals), 8))


def main():
    s = sin_rom()
    e = exp_rom()
    c = col_rom()
    assert max(s) < 32768 and max(e) < 65536
    with open(os.path.join(HERE, 'ondine_pkg.vhd'), 'w') as f:
        f.write('-- generated by ondine.py: do not edit\n')
        f.write('library ieee;\nuse ieee.std_logic_1164.all;\nuse ieee.numeric_std.all;\n\n')
        f.write('package ondine_pkg is\n')
        f.write('    type t_od_sin is array (0 to 511) of unsigned(15 downto 0);\n')
        f.write('    type t_od_exp is array (0 to 255) of unsigned(15 downto 0);\n')
        f.write('    type t_od_col is array (0 to 127) of std_logic_vector(15 downto 0);\n')
        f.write('    constant C_OD_SIN : t_od_sin := (\n        %s);\n' % _vec(s, 16))
        f.write('    constant C_OD_EXP : t_od_exp := (\n        %s);\n' % _vec(e, 16))
        f.write('    constant C_OD_COL : t_od_col := (\n        %s);\n' % _vec(c, 16))
        f.write('end package ondine_pkg;\n')


if __name__ == '__main__':
    main()
