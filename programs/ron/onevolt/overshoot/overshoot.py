"""
OVERSHOOT v0.1.0 - build hook.  Writes overshoot_pkg.vhd next to this file (pure python: the builder runs it with
the system python3).  The integer model (.onevolt_work/rb_overshoot/imodel.py) uses the same table.

  C_OS_SIN  1024 x 16  round(32767 sin(2 pi k / 4096)), k = 0 .. 1023: a quarter wave of a 4096-step cycle
                       (k = 1024, the peak 32767, is handled in logic).  The vblank sequencer reads it for the
                       Navigator angle (cos, sin) and the sway LFO; the line engine for the DWO3's V-range sine.
  C_OS_K5   256 x 16   the SMX3 path for K5 >> 2: per row (R, G, B at bits 0, 5, 10) the source index (2 bits:
                       0..2 = Contour channel 0..2, 3 = off) and the crossfade to the next source (3 bits)
  C_OS_KC   256 x 32   the serial multiplier's constant operand by slot x 16 + timing id (signed)
"""
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))


def sin_rom():
    return [int(round(32767 * math.sin(2 * math.pi * k / 4096))) for k in range(1024)]


SPOS = [(2, 1, 0), (1, 2, 0), (0, 1, 2), (1, 0, 2), (2, 0, 1), (2, -1, 1), (2, 1, 3), (3, 2, 5)]


def k5_rom():
    out = []
    for k in range(256):
        z5 = (4 * k + 2) * 7
        i5 = min(6, z5 >> 10)
        fr5 = z5 - (i5 << 10)
        w = 0
        for r in range(3):
            p = SPOS[i5][r] * 1024 + (SPOS[i5 + 1][r] - SPOS[i5][r]) * fr5
            w |= ((((p >> 10) & 3) << 3) | ((p >> 7) & 7)) << (5 * r)
        out.append(w)
    return out


def tid_class(t):
    xs = 4 if t in (0, 4, 8, 12) else (3 if t in (5, 6, 14) else 2)
    ys = {0: 1138, 4: 576, 8: 960, 12: 480, 5: 384, 6: 384, 14: 384, 1: 512, 2: 512, 10: 512}.get(t, 256)
    return xs, ys


def kc_rom():
    out = [0] * 256
    for t in range(16):
        xs, ys = tid_class(t)
        kuy = {256: 26214, 384: 39322, 512: 52429, 1138: 116530, 576: 58982, 960: 98304, 480: 49152}[ys]
        kb = {(2, 256): 426, (2, 512): 852, (3, 384): 958, (4, 1138): 3787, (4, 576): 1917, (4, 960): 3195,
              (4, 480): 1597}.get((xs, ys), 426)
        vals = [284, {2: 26214, 3: 39322, 4: 52429}[xs], {2: 52429, 3: 78643, 4: 104858}[xs], kuy, kuy,
                -576 if xs == 4 else -768, -432, 1152 if xs == 4 else 1536, -864,
                {2: -25559, 3: -38339, 4: -38339}[xs], {2: -14377, 3: -21566, 4: -28754}[xs], kb, 110]
        for k, v in enumerate(vals):
            out[k * 16 + t] = v & 0xFFFFFFFF
    return out


def table(L, name, typ, n, w, vals):
    L.append('    type %s is array (0 to %d) of std_logic_vector(%d downto 0);' % (typ, n - 1, w - 1))
    L.append('    constant %s : %s := (' % (name, typ))
    rows = []
    for i in range(0, n, 8):
        rows.append('        ' + ', '.join('x"%0*x"' % (w // 4, v) for v in vals[i:i + 8]))
    L.append(',\n'.join(rows))
    L.append('    );')


def main():
    s = sin_rom()
    L = ['-- generated by overshoot.py -- do not edit', 'library ieee;', 'use ieee.std_logic_1164.all;',
         'use ieee.numeric_std.all;', '', 'package overshoot_pkg is',
         '    type t_os_sin is array (0 to 1023) of unsigned(15 downto 0);',
         '    constant C_OS_SIN : t_os_sin := (']
    rows = []
    for i in range(0, 1024, 8):
        rows.append('        ' + ', '.join('to_unsigned(%d, 16)' % v for v in s[i:i + 8]))
    L.append(',\n'.join(rows))
    L += ['    );']
    table(L, 'C_OS_K5', 't_os_k5', 256, 16, k5_rom())
    table(L, 'C_OS_KC', 't_os_kc', 256, 32, kc_rom())
    L += ['end package overshoot_pkg;', '']
    with open(os.path.join(HERE, 'overshoot_pkg.vhd'), 'w') as f:
        f.write('\n'.join(L))


if __name__ == '__main__':
    main()
