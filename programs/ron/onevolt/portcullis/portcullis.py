"""
PORTCULLIS v0.1.0 - build hook.  Writes portcullis_pkg.vhd next to this file (pure python: the builder runs it with
the system python3).  The integer model (.onevolt_work/rb_portcullis/imodel.py) imports the same tables.

Package contents:
  C_PC_SIN   256 x 16   round(2047 sin(2 pi k / 256)), two's complement (the LFOs and the V-range ripple)
  C_PC_EXP   256 x 16   round(32768 * 2^(k / 256)) (Bands and Clock exponentials)
  C_PC_PAL   256 x 32   {Y, U, V, 00} keyframe colours: index = output * 128 + keyframe * 8 + level
                        output 0 (bits -> ESG3): nine cable configurations (order / polarity) of the three bits
                        output 1 (DAC -> SMX3): nine designed 8-step families
                        (indexes 72 .. 127 and 200 .. 255 unused)
  C_PC_K     black (outside the active picture)
Colours are in the hardware convention (U register = Cr, V register = Cb).  Luma is pre-scaled 16/13 for the
shell's 13/16 output scale (capped at 940).
"""
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))

AMP = 0.78          # ESG3 level of a full "1": 75 % bars, drawn luma under ~780
DACAMP = 0.80
# bits: b0 = D2 (LSB), b1 = D1, b2 = D0 (MSB); each entry = (source bit, inverted) for R, G, B
CABLES = [
    ((0, 0), (2, 0), (1, 0)),     # 0
    ((1, 0), (0, 0), (2, 0)),     # 1
    ((2, 1), (1, 1), (0, 1)),     # 2 all three inverted
    ((2, 0), (0, 0), (1, 0)),     # 3 G <-> B
    ((2, 0), (1, 0), (0, 0)),     # 4 straight: black blue green cyan red magenta yellow white
    ((1, 0), (2, 0), (0, 0)),     # 5 R <-> G
    ((2, 0), (1, 1), (0, 0)),     # 6 G inverted
    ((0, 1), (1, 0), (2, 0)),     # 7 reversed, R inverted
    ((0, 0), (1, 0), (2, 0)),     # 8 reversed
]
FAMS = [
    [(0, 8, 4), (0, 40, 20), (10, 90, 40), (30, 150, 60), (60, 200, 90), (110, 235, 130), (170, 250, 180), (225, 255, 225)],
    [(10, 0, 0), (70, 0, 10), (140, 10, 10), (200, 40, 0), (235, 90, 0), (250, 150, 10), (255, 205, 60), (255, 240, 170)],
    [(0, 0, 40), (0, 20, 100), (0, 60, 170), (0, 120, 210), (20, 180, 230), (90, 220, 240), (170, 240, 250), (230, 250, 255)],
    [(30, 0, 40), (90, 0, 90), (170, 20, 120), (230, 60, 110), (250, 120, 90), (200, 200, 40), (140, 240, 60), (220, 255, 170)],
    [(5, 5, 60), (40, 10, 130), (100, 20, 170), (170, 30, 160), (225, 60, 110), (250, 120, 50), (255, 185, 40), (255, 235, 180)],
    [(0, 30, 35), (0, 80, 85), (20, 130, 120), (120, 150, 110), (190, 120, 60), (220, 90, 30), (240, 140, 60), (250, 210, 160)],
    [(10, 0, 30), (50, 0, 90), (100, 20, 150), (90, 90, 160), (40, 160, 130), (40, 210, 110), (150, 240, 150), (230, 255, 220)],
    [(0, 0, 0), (36, 36, 36), (73, 73, 73), (109, 109, 109), (146, 146, 146), (182, 182, 182), (219, 219, 219), (255, 255, 255)],
    [(0, 10, 50), (0, 40, 140), (40, 60, 220), (150, 60, 200), (230, 40, 90), (255, 40, 20), (255, 120, 60), (255, 220, 200)],
]


def rgb_to_hw10f(rgb):
    r, g, b = [c / 255.0 for c in rgb]
    y = 0.299 * r + 0.587 * g + 0.114 * b
    cb, cr = (b - y) / 1.772, (r - y) / 1.402
    return (64 + y * 876, 512 + cr * 896, 512 + cb * 896)


def prescale(yuv):
    y, u, v = yuv
    y2 = 64 + (y - 64) * 16.0 / 13.0
    return (int(round(min(940, max(64, y2)))), int(round(min(1023, max(0, u)))), int(round(min(1023, max(0, v)))))


def word(yuv):
    y, u, v = yuv
    return (y << 22) | (u << 12) | (v << 2)


def cable_rgb(cfg, lev):
    bits = [(lev >> 0) & 1, (lev >> 1) & 1, (lev >> 2) & 1]
    return tuple(abs(bits[src] - pol) * AMP * 255.0 for src, pol in cfg)


def pal_rom():
    out = [0] * 256
    for k in range(9):
        for n in range(8):
            out[k * 8 + n] = word(prescale(rgb_to_hw10f(cable_rgb(CABLES[k], n))))
            out[128 + k * 8 + n] = word(prescale(rgb_to_hw10f(tuple(c * DACAMP for c in FAMS[k][n]))))
    blk = word(prescale(rgb_to_hw10f((0, 0, 0))))
    for i in range(256):
        if out[i] == 0:
            out[i] = blk
    return out


def sin_rom():
    return [int(round(2047 * math.sin(2 * math.pi * k / 256))) & 0xFFFF for k in range(256)]


def exp_rom():
    return [int(round(32768 * 2 ** (k / 256.0))) for k in range(256)]


def vhd_table(name, typ, depth, width, vals):
    lines = ["    type %s is array (0 to %d) of %s(%d downto 0);" % ("t_" + name.lower(), depth - 1, typ, width - 1),
             "    constant %s : %s := (" % (name, "t_" + name.lower())]
    items = ['x"%0*X"' % ((width + 3) // 4, v) for v in vals]
    for i in range(0, len(items), 16):
        lines.append("        " + ", ".join(items[i:i + 16]) + ("," if i + 16 < len(items) else ""))
    lines.append("    );")
    return "\n".join(lines)


def main():
    parts = ["-- Generated by portcullis.py -- DO NOT EDIT.",
             "library ieee;", "use ieee.std_logic_1164.all;", "use ieee.numeric_std.all;", "",
             "package portcullis_pkg is",
             vhd_table("C_PC_SIN", "std_logic_vector", 256, 16, sin_rom()),
             vhd_table("C_PC_EXP", "unsigned", 256, 16, exp_rom()),
             vhd_table("C_PC_PAL", "std_logic_vector", 256, 32, pal_rom()),
             '    constant C_PC_K : std_logic_vector(31 downto 0) := x"%08X";' % word(prescale(rgb_to_hw10f((0, 0, 0)))),
             "end package portcullis_pkg;", ""]
    with open(os.path.join(HERE, "portcullis_pkg.vhd"), "w") as f:
        f.write("\n".join(parts))


if __name__ == "__main__":
    main()
