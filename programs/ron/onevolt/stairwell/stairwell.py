"""
STAIRWELL v0.1.0 - build hook.  Writes stairwell_pkg.vhd next to this file (pure python: the builder runs it with
the system python3).  The integer model (.onevolt_work/rb_stairwell/imodel.py) imports the same tables.

Package contents:
  C_SW_R / C_SW_G / C_SW_B   256 x 32  the ESG3 channels: channel value (8-bit, 0 .. 1 V) -> contrast about 0.5 V
                             (x 4) with soft clipping at 0 and 1 V -> that channel's share of Y, U, V:
                             {Y (10 bits, pre-scaled 16/13 for the shell's 13/16), U = Cr (11-bit two's complement),
                             V = Cb (11-bit two's complement)}; the three shares sum to the encoded colour
  C_SW_ARR                   8 x 12    the K5 cable arrangements: per channel R, G, B a Stairs output (0 .. 5 =
                             2X .. 64X) and an ESG3 invert bit: {inv, tap(2 downto 0)} x 3, R in the top nibble
Colours are in the hardware convention (U register = Cr, V register = Cb).
"""
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))

CONTRAST = 4.0
KNEE_LO, KNEE_HI = 0.12, 0.88
WY = (0.299, 0.587, 0.114)
WCR = (0.5, -0.587 / 1.402, -0.114 / 1.402)
WCB = (-0.299 / 1.772, -0.587 / 1.772, 0.5)
# R, G, B sources: Stairs output 1 .. 6 = 2X .. 64X; negative = inverted in ESG3
# neighbours differ in ONE cable, so K5's transition (that cable dims to 0.5 V and returns re-patched) never
# leaves fewer than two cables alive
ARR = [(3, 3, 1), (3, 2, 1), (1, 2, 1), (1, 2, 3), (-1, 2, 3), (-1, 2, 5), (4, 2, 5), (4, -2, 5)]


def esg3(v):
    x = 0.5 + CONTRAST * (v / 255.0 - 0.5)
    if x < KNEE_LO:
        y = KNEE_LO * math.exp((x - KNEE_LO) / KNEE_LO)
    elif x > KNEE_HI:
        y = 1 - (1 - KNEE_HI) * math.exp((KNEE_HI - x) / (1 - KNEE_HI))
    else:
        y = x
    return min(1.0, max(0.0, y))


def chan_rom(c):
    out = []
    for v in range(256):
        e = esg3(v)
        y = int(round(876 * 16 / 13 * WY[c] * e))
        u = int(round(896 * WCR[c] * e)) & 2047
        w = int(round(896 * WCB[c] * e)) & 2047
        out.append((y << 22) | (u << 11) | w)
    return out


def arr_rom():
    out = []
    for a in ARR:
        word = 0
        for tp in a:
            word = (word << 4) | ((8 if tp < 0 else 0) | (abs(tp) - 1))
        out.append(word)
    return out


def vhd_table(name, typ, depth, width, vals):
    lines = ["    type %s is array (0 to %d) of %s(%d downto 0);" % ("t_" + name.lower(), depth - 1, typ, width - 1),
             "    constant %s : %s := (" % (name, "t_" + name.lower())]
    items = ['x"%0*X"' % ((width + 3) // 4, v) for v in vals]
    for i in range(0, len(items), 16):
        lines.append("        " + ", ".join(items[i:i + 16]) + ("," if i + 16 < len(items) else ""))
    lines.append("    );")
    return "\n".join(lines)


def main():
    parts = ["-- Generated by stairwell.py -- DO NOT EDIT.",
             "library ieee;", "use ieee.std_logic_1164.all;", "use ieee.numeric_std.all;", "",
             "package stairwell_pkg is",
             vhd_table("C_SW_R", "std_logic_vector", 256, 32, chan_rom(0)),
             vhd_table("C_SW_G", "std_logic_vector", 256, 32, chan_rom(1)),
             vhd_table("C_SW_B", "std_logic_vector", 256, 32, chan_rom(2)),
             vhd_table("C_SW_ARR", "std_logic_vector", 8, 12, arr_rom()),
             "end package stairwell_pkg;", ""]
    with open(os.path.join(HERE, "stairwell_pkg.vhd"), "w") as f:
        f.write("\n".join(parts))


if __name__ == "__main__":
    main()
