"""
SUBCARRIER v0.1.0 - build hook.  Writes subcarrier_pkg.vhd next to this file (pure python: the builder runs it
with the system python3).  The integer model (.onevolt_work/rb_subcarrier/imodel.py) imports the same tables.

Package contents:
  C_SC_SINU  256 x 16  quarter-wave of the quadrature shaper (Syntonie VU005, slightly over-driven: min(1, OD sin)),
                       sampled at the half steps (k + 1/2) * 90 / 256 deg: {full magnitude (8), 0.737 x magnitude (8)}
  C_SC_SINV  256 x 16  the same with {full (8), 0.676 x magnitude (8)}
                       (0.737 / -0.676 are the U = Cr / V = Cb components of the +I axis: the S7 "Q cable out" duotone)
  C_SC_GAM   2048 x 8  the gamut limiter: max saturation (s units) by {S7, Y >> 5, hue >> 11}, conservative over each
                       bin, with room for the orbit LFO
  C_SC_DAC   8 x 10    Ribbons' DAC levels (internal luma codes)
Hardware colour convention: U register = Cr, V register = Cb.  Internal luma is pre-scaled 16/13 for the shell's
13/16 output scale: y_out = (Yint - 64) * 13 / 16 / 876.
"""
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))

OD = 1.25                  # VU005 drive
KU_OUT = 0.737             # +I axis, Cr component
KV_OUT = 0.676             # +I axis, -Cb component
ORB = 40                   # orbit radius (chroma codes), reserved in the gamut table
DAC_LO, DAC_HI = 0.05, 0.75


def sod(th):
    return min(1.0, OD * math.sin(th))


def sin_rom(k_out):
    out = []
    for k in range(256):
        th = (k + 0.5) * (math.pi / 2) / 256
        m = sod(th)
        a = int(round(255 * m))
        b = int(round(255 * k_out * m))
        out.append((a << 8) | b)
    return out


SINU = sin_rom(KU_OUT)
SINV = sin_rom(KV_OUT)


def rom_read(rom, a10, field):
    """signed magnitude read as the RTL folds it: a10 = 10-bit phase (1024 per turn); field 0 = full, 1 = out"""
    q = (a10 >> 8) & 3
    i = a10 & 255
    if q & 1:
        i = 255 - i
    w = rom[i]
    m = (w >> 8) & 255 if field == 0 else w & 255
    return -m if q & 2 else m


# phase offsets (16-bit phase): U = Cr = s sin(phi + C), V = Cb = s sin(phi + C + 90); +I (orange) at phi = 0
C_HU = 24121               # 132.5 deg
C_HV = 40505               # 222.5 deg
C_HO = 16384               # 90 deg: S7 Out reads cos(phi) on both sides


def chroma(s, ph16, out):
    """(U - 512, V - 512) codes before the orbit, as the RTL forms them"""
    if out:
        a = ((ph16 + C_HO) & 0xFFFF) >> 6
        mu = rom_read(SINU, a, 1)
        mv = -rom_read(SINV, a, 1)
    else:
        mu = rom_read(SINU, ((ph16 + C_HU) & 0xFFFF) >> 6, 0)
        mv = rom_read(SINV, ((ph16 + C_HV) & 0xFFFF) >> 6, 0)
    return smul(s, mu), smul(s, mv)


def smul(s, m):
    p = (s * abs(m)) >> 7
    return -p if m < 0 else p


def yout(yint):
    return (yint - 64) * 13.0 / 16.0 / 876.0


def gamut_rom():
    wR, wG, wB = 1.402 * ORB / 896, 0.793 * ORB / 896, 1.772 * ORB / 896
    out = []
    for bank in (0, 1):
        for yb in range(32):
            ys = [yout(32 * yb), yout(32 * yb + 31)]
            for hb in range(32):
                best = 255
                for k in range(32):
                    ph = (hb << 11) + (k << 6) + 32
                    # unit chroma per s step (Cr, Cb) at s = 128: codes / 896
                    u, v = chroma(128, ph, bank)
                    cr, cb = u / 896.0 / 128.0, v / 896.0 / 128.0
                    dR, dG, dB = 1.402 * cr, -0.344 * cb - 0.714 * cr, 1.772 * cb
                    for y in ys:
                        for d, m in ((dR, wR), (dG, wG), (dB, wB)):
                            if d > 1e-9:
                                lim = (1.0 - m - y) / d
                            elif d < -1e-9:
                                lim = (y - m) / -d
                            else:
                                continue
                            if lim < best:
                                best = lim
                best = max(0, min(255, int(math.floor(best))))
                out.append(best)
    return out


def dac_rom():
    return [int(round(64 + (DAC_LO + l * (DAC_HI - DAC_LO) / 7.0) * 876 * 16 / 13)) for l in range(8)]


def vhd_table(name, typ, depth, width, vals):
    lines = ["    type %s is array (0 to %d) of %s(%d downto 0);" % ("t_" + name.lower(), depth - 1, typ, width - 1),
             "    constant %s : %s := (" % (name, "t_" + name.lower())]
    items = ['x"%0*X"' % ((width + 3) // 4, v) for v in vals]
    for i in range(0, len(items), 16):
        lines.append("        " + ", ".join(items[i:i + 16]) + ("," if i + 16 < len(items) else ""))
    lines.append("    );")
    return "\n".join(lines)


def main():
    dac = dac_rom()
    parts = ["-- Generated by subcarrier.py -- DO NOT EDIT.",
             "library ieee;", "use ieee.std_logic_1164.all;", "use ieee.numeric_std.all;", "",
             "package subcarrier_pkg is",
             vhd_table("C_SC_SINU", "std_logic_vector", 256, 16, SINU),
             vhd_table("C_SC_SINV", "std_logic_vector", 256, 16, SINV),
             vhd_table("C_SC_GAM", "std_logic_vector", 2048, 8, gamut_rom()),
             "    type t_c_sc_dac is array (0 to 7) of unsigned(9 downto 0);",
             "    constant C_SC_DAC : t_c_sc_dac := (" + ", ".join("to_unsigned(%d, 10)" % d for d in dac) + ");",
             "end package subcarrier_pkg;", ""]
    with open(os.path.join(HERE, "subcarrier_pkg.vhd"), "w") as f:
        f.write("\n".join(parts))


if __name__ == "__main__":
    main()
