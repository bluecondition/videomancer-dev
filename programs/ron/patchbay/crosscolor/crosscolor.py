"""
CROSSCOLOR v0.1.0 - build hook.  Writes crosscolor_pkg.vhd next to this file (pure python: the builder
runs it with the system python3).

Package contents (both tables are also built by the integer model, .patchbay_work/rb_crosscolor/imodel.py):
  C_CC_EXP2  256 x 16   round(32768 * 2^(i/256))                 the exponential controls' mantissa
  C_CC_SIN   512 x 8    round(255 * min(1, 1.6 sin(pi (i + 1/2) / 512)))   half a cycle of the pattern
                        oscillator's soft-clipped sine (the sign comes from the phase's top bit)
"""
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))


def exp2_rom():
    return [int(round(32768 * 2 ** (i / 256.0))) for i in range(256)]


def sin_rom():
    return [int(round(255 * min(1.0, 1.6 * math.sin(math.pi * (i + 0.5) / 512)))) for i in range(512)]


def vhd_table(name, depth, width, vals):
    lines = ["    type %s is array (0 to %d) of unsigned(%d downto 0);" % ("t_" + name.lower(), depth - 1, width - 1),
             "    constant %s : %s := (" % (name, "t_" + name.lower())]
    items = ['x"%0*X"' % (width // 4, v) for v in vals]
    for i in range(0, len(items), 16):
        lines.append("        " + ", ".join(items[i:i + 16]) + ("," if i + 16 < len(items) else ""))
    lines.append("    );")
    return "\n".join(lines)


def main():
    parts = ["-- Generated by crosscolor.py -- DO NOT EDIT.",
             "library ieee;", "use ieee.std_logic_1164.all;", "use ieee.numeric_std.all;", "",
             "package crosscolor_pkg is",
             vhd_table("C_CC_EXP2", 256, 16, exp2_rom()),
             vhd_table("C_CC_SIN", 512, 8, sin_rom()),
             "end package crosscolor_pkg;", ""]
    with open(os.path.join(HERE, "crosscolor_pkg.vhd"), "w") as f:
        f.write("\n".join(parts))


if __name__ == "__main__":
    main()
