"""
EUCLID v0.1.0 - build hook.  Writes euclid_pkg.vhd next to this file (pure python: the builder runs it
with the system python3).  The tables are also read by the integer model (.patchbay_work/rb_euclid/imodel.py).

  C_EU_PAL  1024 x 32  {Y, U, V, 00} the colouriser: index = hue * 64 + level (16 hues, 64 levels).
                       Flat bands with thin fringes: black, deep, body, a dark ring, bright, a hot fringe,
                       hot tint, white, then the upper register the camera / Osc drives (a second hue, a dark
                       line, a third hue, white).
  C_EU_ENV  1024 x 16  the envelope generator: index = tails * 512 + age * 16 + frac (age in steps since the
                       strike, frac = sixteenths of a step; tails 0 = Long, 1 = Short).
                       bits 6..0 the envelope in half levels (Long peaks at 52, Short at 76: a harder strike
                       that reaches the upper register), 11..7 the camera window gain (0..31), 15..12 the accent
                       bus level (0..14, always on the Long curve).
Colours are in the hardware convention (U register = Cr, V register = Cb); luma pre-scaled 16/13 for the
shell's 13/16 output scale, capped at 940 (drawn whites ~777).
"""
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))

TAU_LONG, TAU_SHORT = 6.0, 1.5
ENV_PEAK_LONG, ENV_PEAK_SHORT = 52, 76      # half levels
ACC_PEAK = 14            # levels
# per-track fill offsets (Q8): a track fills in between FILL = o / 2 and (o + 1) / 2
OFS = [0, 159, 61, 220, 123, 26, 184, 87, 245, 148, 51, 210]

def hsv(h, s, v):
    h = (h % 1.0) * 6
    i = int(h)
    f = h - i
    p, q, t = v * (1 - s), v * (1 - s * f), v * (1 - s * (1 - f))
    return [(v, t, p), (q, v, p), (p, v, t), (p, q, v), (t, p, v), (v, p, q)][i % 6]

def hue_rgb(hi, v=1.0, s=1.0):
    """16 rack hues: index 0 = hot pink, then round the wheel"""
    return tuple(c * 255 for c in hsv(0.90 + hi / 16.0, s, v))

def mix(a, b, w):
    return tuple(a[i] * (1 - w) + b[i] * w for i in range(3))

def band_table(hi):
    """64 levels -> RGB for hue index hi"""
    K = (8, 8, 10)
    white = (255, 255, 255)
    deep = hue_rgb(hi, 0.36)
    body = hue_rgb(hi, 0.62)
    ring = hue_rgb(hi + 8, 0.16, 0.8)
    bright = hue_rgb(hi, 1.0)
    fr2 = hue_rgb(hi + 3, 1.0, 0.85)
    hot = mix(bright, white, 0.58)
    sec = hue_rgb(hi + 6, 1.0)
    dark2 = hue_rgb(hi + 6, 0.22)
    third = hue_rgb(hi + 11, 1.0, 0.9)
    segs = [(0, 1, K), (1, 4, deep), (4, 10, body), (10, 13, ring), (13, 24, bright), (24, 27, fr2),
            (27, 36, hot), (36, 40, white), (40, 48, sec), (48, 51, dark2), (51, 59, third), (59, 64, white)]
    t = [K] * 64
    for a, b, col in segs:
        for i in range(a, b):
            t[i] = col
    return t

def rgb_to_hw10(rgb):
    r, g, b = [c / 255.0 for c in rgb]
    y = 0.299 * r + 0.587 * g + 0.114 * b
    cb, cr = (b - y) / 1.772, (r - y) / 1.402
    return (round(64 + y * 876), round(512 + cr * 896), round(512 + cb * 896))

def prescale(yuv):
    y, u, v = yuv
    y2 = 64 + (y - 64) * 16.0 / 13.0
    y2 = int(round(min(940, max(64, y2))))
    return (y2, min(1000, max(24, int(u))), min(1000, max(24, int(v))))

def word(yuv):
    y, u, v = prescale(yuv)
    return (y << 22) | (u << 12) | (v << 2)

def pal_rom():
    out = []
    for h in range(16):
        out += [word(rgb_to_hw10(c)) for c in band_table(h)]
    return out

def env_rom():
    out = []
    for tails in (0, 1):
        tau = TAU_SHORT if tails else TAU_LONG
        peak = ENV_PEAK_SHORT if tails else ENV_PEAK_LONG
        for age in range(32):
            for fr in range(16):
                a = age + fr / 16.0
                e = int(round(peak * math.exp(-a / tau)))
                cw = min(31, int(round(e * 32 / 13.0)))
                ac = int(round(ACC_PEAK * math.exp(-a / TAU_LONG)))
                out.append(e | (cw << 7) | (ac << 12))
    return out

def vhd_table(name, typ, depth, width, vals):
    lines = ["    type %s is array (0 to %d) of %s(%d downto 0);" % ("t_" + name.lower(), depth - 1, typ, width - 1),
             "    constant %s : %s := (" % (name, "t_" + name.lower())]
    items = ['x"%0*X"' % (width // 4, v) for v in vals]
    for i in range(0, len(items), 16):
        lines.append("        " + ", ".join(items[i:i + 16]) + ("," if i + 16 < len(items) else ""))
    lines.append("    );")
    return "\n".join(lines)

def main():
    parts = ["-- Generated by euclid.py -- DO NOT EDIT.",
             "library ieee;", "use ieee.std_logic_1164.all;", "use ieee.numeric_std.all;", "",
             "package euclid_pkg is",
             vhd_table("C_EU_PAL", "std_logic_vector", 1024, 32, pal_rom()),
             vhd_table("C_EU_ENV", "std_logic_vector", 1024, 16, env_rom()),
             "end package euclid_pkg;", ""]
    with open(os.path.join(HERE, "euclid_pkg.vhd"), "w") as f:
        f.write("\n".join(parts))

if __name__ == "__main__":
    main()
