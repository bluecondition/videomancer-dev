"""
LIMELIGHT v0.1.0 - build hook.  Writes limelight_pkg.vhd next to this file (pure python: the builder runs
it with the system python3).  The integer model (.patchbay_work/rb_limelight/imodel.py) imports the same
tables and constants.

The patch (virtual 1920 x 1080 coordinates):
  four lamps on a rail 110 lines above the top edge, at x = 315, 745, 1175, 1605
  each beam = two rotated ramps (half-planes through its lamp, at theta - w and theta + w) into a soft
  window comparator: I = clamp(min(hA, hB)), a linear penumbra `soft` px wide centred on the geometric edge
  theta_i = Sweep sin(phi1 + i Spread) + 7 deg sin(phi2 + i/4) + fan_i        (two LFOs)
  the vertical ramp is folded at the floor line (the beams mirror in the floor); a level ramp (Reach) plus
  the haze texture and the camera caps each window; a pool = an ellipse on the floor line under each beam
  the four keys go through gels into an additive Y / U / V mixer (or a hard-priority keyer)

Tables:
  C_LL_EXP2  256 x 16   round(32768 * 2^(i/256))
  C_LL_SIN   2048 x 16  round(65536 * sin((j + 1/2) pi / 4096)), a quarter wave (8192 angle units per turn)
  C_LL_S1    256 x 16   round(256 * (1 - sqrt(1 - (u/256)^2))), 256 at u = 255: the pool's ellipse profile
  C_LL_GEL   8 x 32     gel sets, 8 bits per lamp: Y tap, U tap, V tap (see GELS)
"""
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))

# gels in the mixer's own terms: (Y tap, U tap, V tap).  Y tap 0 = J/4, 1 = J/2, 2 = J; chroma taps 0 or +-2 = 2J
# (U register = Cr, V register = Cb, in 10-bit chroma units; J = 255 is a full key)
RED, GREEN, AZURE, MAGENTA = (0, 2, -2), (1, -2, -2), (0, -2, 2), (1, 2, 2)
AMBER, ROSE, CYAN, VIOLET = (1, 2, -2), (0, 2, 0), (1, -2, 2), (0, 0, 2)
YELLOW, SEA, LIME, PINK = (2, 0, -2), (1, -2, 0), (2, -2, -2), (0, 2, 2)
ICE, LILAC, WHITE = (2, -2, 2), (2, 2, 2), (2, 0, 0)
# lamp 1's chroma taps are never negative (the mixer carries no sign for it)
GELS = [
    (MAGENTA, RED, GREEN, AZURE),     # 0 Primaries
    (ROSE, AMBER, CYAN, VIOLET),      # 1 Stage
    (ROSE, RED, AMBER, YELLOW),       # 2 Warm
    (VIOLET, AZURE, CYAN, SEA),       # 3 Cold
    (PINK, LIME, PINK, LIME),         # 4 Rack: hot pink / lime
    (MAGENTA, CYAN, YELLOW, CYAN),    # 5 CMY
    (ROSE, AZURE, ROSE, AZURE),       # 6 Police
    (WHITE, YELLOW, ICE, LILAC),      # 7 Limelight
]
GEL_NAMES = ["Primaries", "Stage", "Warm", "Cold", "Rack", "CMY", "Police", "Limelight"]

LAMP_X = [315, 745, 1175, 1605]     # lamp x (virtual px)
LAMP_Y = 110                        # the rail's height above the top edge (virtual lines)
FAN = [239, 80, -80, -239]          # static aim (angle units): 10.5, 3.5, -3.5, -10.5 degrees (converging)

def exp2_rom():
    return [int(round(32768 * 2 ** (i / 256.0))) for i in range(256)]

def sin_rom():
    return [min(65535, int(round(65536 * math.sin((j + 0.5) * math.pi / 4096)))) for j in range(2048)]

def s1_rom():
    out = [int(round(256 * (1 - math.sqrt(1 - (u / 256.0) ** 2)))) for u in range(256)]
    out[255] = 256
    return out

def gel_rom():
    """per lamp 8 bits: Y tap (1..0), U on (2), U negative (4), V on (5), V negative (7); lamp i at bits 8 i + 7 .. 8 i"""
    out = []
    for st in GELS:
        w = 0
        for i in range(4):
            y, u, v = st[i]
            assert u in (0, 2, -2) and v in (0, 2, -2) and (i > 0 or (u >= 0 and v >= 0))
            f = y | ((1 if u else 0) << 2) | ((1 if u < 0 else 0) << 4) | ((1 if v else 0) << 5) | ((1 if v < 0 else 0) << 7)
            w |= f << (8 * i)
        out.append(w)
    return out

def vhd_table(name, typ, depth, width, vals):
    lines = ["    type %s is array (0 to %d) of %s(%d downto 0);" % ("t_" + name.lower(), depth - 1, typ, width - 1),
             "    constant %s : %s := (" % (name, "t_" + name.lower())]
    items = ['x"%0*X"' % ((width + 3) // 4, v) for v in vals]
    for i in range(0, len(items), 16):
        lines.append("        " + ", ".join(items[i:i + 16]) + ("," if i + 16 < len(items) else ""))
    lines.append("    );")
    return "\n".join(lines)

def main():
    parts = ["-- Generated by limelight.py -- DO NOT EDIT.",
             "library ieee;", "use ieee.std_logic_1164.all;", "use ieee.numeric_std.all;", "",
             "package limelight_pkg is",
             vhd_table("C_LL_EXP2", "unsigned", 256, 16, exp2_rom()),
             vhd_table("C_LL_SIN", "unsigned", 2048, 16, sin_rom()),
             vhd_table("C_LL_S1", "unsigned", 256, 16, s1_rom()),
             vhd_table("C_LL_GEL", "std_logic_vector", 8, 32, gel_rom()),
             "end package limelight_pkg;", ""]
    with open(os.path.join(HERE, "limelight_pkg.vhd"), "w") as f:
        f.write("\n".join(parts))

if __name__ == "__main__":
    main()
