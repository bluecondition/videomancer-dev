"""
LISSAJOUS v0.1.0 - build hook.  Writes lissajous_pkg.vhd next to this file (pure python: the builder runs
it with the system python3).  The integer model (.patchbay_work/rb_lissajous/imodel.py) reads the same tables.

Package contents:
  C_LJ_ACOS  1024 x 16  the arcsine shaper: round(acos((i + 0.5) / 1024) / 2 pi * 16384), i = |x| * 1024
                        (a quarter cycle = 4096; the other half of the ramp is 8192 - table)
  C_LJ_COS   1024 x 16  the function generators: round(cos(2 pi (i + 0.5) / 4096) * 32752), a quarter wave
  C_LJ_PAL   512 x 32   the colouriser: {Y, U, V, 00}, index = tier * 64 + position (64 positions per cycle,
                        8 brightness tiers; tier 7 = black)
  C_LJ_K / C_LJ_L1 / C_LJ_L2   black, the figure's line colour, the twin's line colour ({Y, U, V, 00})
Colours are in the hardware convention (U register = Cr, V register = Cb); luma pre-scaled 16/13 for the shell's
13/16 output scale, capped at 940 (drawn whites ~777).
"""
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))

# one cycle of the colouriser, from the figure outward: wide saturated bands, thin fringes between them
STOPS = [  # (positions, rgb)
    (6, (255, 96, 0)),      # orange
    (5, (232, 14, 44)),     # red
    (2, (255, 160, 210)),   # fringe pink
    (6, (236, 16, 190)),    # magenta
    (6, (120, 30, 230)),    # violet
    (2, (120, 230, 255)),   # fringe cyan
    (6, (20, 70, 235)),     # blue
    (6, (0, 170, 190)),     # teal
    (2, (220, 255, 120)),   # fringe lime
    (6, (20, 190, 60)),     # green
    (5, (255, 236, 60)),    # yellow
    (2, (255, 255, 235)),   # fringe white
    (10, (8, 8, 20)),       # the gap (near black)
]
TIER = [1.0, 0.86, 0.70, 0.54, 0.38, 0.24, 0.12, 0.0]
BLACK = (6, 6, 12)
LINE1 = (255, 246, 200)     # the figure: warm white
LINE2 = (0, 232, 255)       # the twin: cyan

def cycle():
    out = []
    for w, c in STOPS:
        out += [c] * w
    assert len(out) == 64
    return out

def rgb_to_hw10(rgb):
    r, g, b = [c / 255.0 for c in rgb]
    y = 0.299 * r + 0.587 * g + 0.114 * b
    cb, cr = (b - y) / 1.772, (r - y) / 1.402
    return (round(64 + y * 876), round(512 + cr * 896), round(512 + cb * 896))

def prescale(yuv):
    y, u, v = yuv
    y2 = 64 + (y - 64) * 16.0 / 13.0
    y2 = int(round(min(940, max(64, y2))))
    return (y2, min(1000, max(24, int(u))), min(1000, max(24, int(v))))

def word(rgb):
    y, u, v = prescale(rgb_to_hw10(rgb))
    return (y << 22) | (u << 12) | (v << 2)

def pal_rom():
    cyc = cycle()
    out = []
    for t in range(8):
        for p in range(64):
            out.append(word(tuple(BLACK[i] + (cyc[p][i] - BLACK[i]) * TIER[t] for i in range(3))))
    return out

def acos_rom():
    return [int(round(math.acos((i + 0.5) / 1024.0) / (2 * math.pi) * 16384)) for i in range(1024)]

def cos_rom():
    return [int(round(math.cos(2 * math.pi * (i + 0.5) / 4096.0) * 32752)) for i in range(1024)]

def vhd_table(name, typ, depth, width, vals):
    lines = ["    type %s is array (0 to %d) of %s(%d downto 0);" % ("t_" + name.lower(), depth - 1, typ, width - 1),
             "    constant %s : %s := (" % (name, "t_" + name.lower())]
    items = ['x"%0*X"' % ((width + 3) // 4, v) for v in vals]
    for i in range(0, len(items), 16):
        lines.append("        " + ", ".join(items[i:i + 16]) + ("," if i + 16 < len(items) else ""))
    lines.append("    );")
    return "\n".join(lines)

def main():
    parts = ["-- Generated by lissajous.py -- DO NOT EDIT.",
             "library ieee;", "use ieee.std_logic_1164.all;", "use ieee.numeric_std.all;", "",
             "package lissajous_pkg is",
             vhd_table("C_LJ_ACOS", "unsigned", 1024, 16, acos_rom()),
             vhd_table("C_LJ_COS", "unsigned", 1024, 16, cos_rom()),
             vhd_table("C_LJ_PAL", "std_logic_vector", 512, 32, pal_rom()),
             '    constant C_LJ_K  : std_logic_vector(31 downto 0) := x"%08X";' % word(BLACK),
             '    constant C_LJ_L1 : std_logic_vector(31 downto 0) := x"%08X";' % word(LINE1),
             '    constant C_LJ_L2 : std_logic_vector(31 downto 0) := x"%08X";' % word(LINE2),
             "end package lissajous_pkg;", ""]
    with open(os.path.join(HERE, "lissajous_pkg.vhd"), "w") as f:
        f.write("\n".join(parts))

if __name__ == "__main__":
    main()
