"""
MUNCH v0.1.0 (Patchbay) - build hook.  Writes munch_pkg.vhd next to this file (pure python: the builder runs it
with the system python3).  The tables are also read by the integer model (.patchbay_work/rb_munch/imodel.py).

  C_MU_EXP2  256 x 16    round(32768 * 2^(i/256))                  the cell-clock divider's exponential
  C_MU_PAL   2048 x 16   {Y6, U5, V5}: index = mapping * 64 + code  the 3-channel DAC colouriser
             code = R level * 16 + G level * 4 + B level (2 bits per DAC channel); mapping 0..31 turns the three
             channel colours from red / green / blue through 270 degrees of hue.  Every non-black code is
             normalised to a bright saturated colour (the rack colouriser's bands).  Y6 is the luma pre-scaled
             16/13 for the shell's 13/16 output scale: Y10 = 64 + 14 * Y6; U10 = 32 * U5, V10 = 32 * V5
             (hardware convention: U = Cr, V = Cb; 16 is neutral).
"""
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))
NB = 0.72          # brightness floor of a lit code (level 1 of 3)
NPAL = 32
HUE_SPAN = 270.0

def exp2_rom():
    return [int(round(32768 * 2 ** (i / 256.0))) for i in range(256)]

def channel_vectors(theta_deg):
    th = math.radians(theta_deg)
    k = 1 / math.sqrt(3)
    c, s = math.cos(th), math.sin(th)
    # Rodrigues rotation about the grey axis
    R = [[c + k * k * (1 - c), k * k * (1 - c) - k * s, k * k * (1 - c) + k * s],
         [k * k * (1 - c) + k * s, c + k * k * (1 - c), k * k * (1 - c) - k * s],
         [k * k * (1 - c) - k * s, k * k * (1 - c) + k * s, c + k * k * (1 - c)]]
    vec = []
    for ch in range(3):
        v = [max(0.0, R[r][ch]) for r in range(3)]
        m = max(v)
        vec.append([x / m for x in v])
    return vec

def palette_rgb(p):
    """64 RGB triples (0..1) of mapping p."""
    vec = channel_vectors(p * HUE_SPAN / (NPAL - 1))
    out = []
    for code in range(64):
        lv = [((code >> 4) & 3) / 3.0, ((code >> 2) & 3) / 3.0, (code & 3) / 3.0]
        rgb = [sum(lv[ch] * vec[ch][i] for ch in range(3)) for i in range(3)]
        m = max(rgb)
        if m > 0:
            g = (NB + (1 - NB) * max(lv)) / m
            rgb = [min(1.0, x * g) for x in rgb]
        out.append(rgb)
    return out

def rgb_to_hw10(rgb):
    r, g, b = rgb
    y = 0.299 * r + 0.587 * g + 0.114 * b
    cb, cr = (b - y) / 1.772, (r - y) / 1.402
    return (64 + y * 876, 512 + cr * 896, 512 + cb * 896)

def pal_word(rgb):
    y, u, v = rgb_to_hw10(rgb)
    ypre = (y - 64) * 16.0 / 13.0
    y6 = max(0, min(62, int(round(ypre / 14.0))))
    u5 = max(1, min(31, int(round(u / 32.0))))
    v5 = max(1, min(31, int(round(v / 32.0))))
    return (y6 << 10) | (u5 << 5) | v5

def pal_rom():
    out = []
    for p in range(NPAL):
        out += [pal_word(c) for c in palette_rgb(p)]
    return out

def vhd_table(name, typ, depth, width, vals):
    lines = ["    type %s is array (0 to %d) of %s(%d downto 0);" % ("t_" + name.lower(), depth - 1, typ, width - 1),
             "    constant %s : %s := (" % (name, "t_" + name.lower())]
    items = ['x"%0*X"' % (width // 4, v) for v in vals]
    for i in range(0, len(items), 16):
        lines.append("        " + ", ".join(items[i:i + 16]) + ("," if i + 16 < len(items) else ""))
    lines.append("    );")
    return "\n".join(lines)

def main():
    parts = ["-- Generated by munch.py -- DO NOT EDIT.",
             "library ieee;", "use ieee.std_logic_1164.all;", "use ieee.numeric_std.all;", "",
             "package munch_pkg is",
             vhd_table("C_MU_EXP2", "unsigned", 256, 16, exp2_rom()),
             vhd_table("C_MU_PAL", "std_logic_vector", 2048, 16, pal_rom()),
             "end package munch_pkg;", ""]
    with open(os.path.join(HERE, "munch_pkg.vhd"), "w") as f:
        f.write("\n".join(parts))

if __name__ == "__main__":
    main()
