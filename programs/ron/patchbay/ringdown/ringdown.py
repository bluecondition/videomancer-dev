"""
RINGDOWN v0.1.0 - build hook.  Writes ringdown_pkg.vhd next to this file (pure python: the builder runs it with
the system python3).  imodel.py imports the same functions, so the RTL and the model share every table.

Package contents:
  C_RD_LOGCOS  256 x 16  round(4096 * -log2(cos(2 pi (i + 0.5) / 1024)))       first quadrant, Q12 octaves
  C_RD_EXP     256 x 16  T = round(2048 * 2^(i/256)) - 2048 (bits 10..0), s2 = round(2 * (2^((i+1)/256) - 2^(i/256))
                         * 2048) (bits 15..11): mantissa Q15 = ((T + 2048) << 4) + ((r * s2) >> 1), r = 4 more bits
                         (the fill engine interpolates; the sequencers use (T + 2048) << 4)
  C_RD_PAL     512 x 24  address s * 256 + j * 16 + f: the colouriser, the blend of wheel_s[j] and wheel_s[j + 1]
                         at count fraction (f + 1/2) / 16 with a pale fringe at the middle of the step; 8-bit
                         Y | U | V (10-bit >> 2; Y pre-scaled 16/13 for the shell's 13/16 output scale, cap 940),
                         hardware convention (U = Cr, V = Cb).  Band n of 8 uses j = (n + r) mod 16 (K5 rotation).
"""
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))

# 16-colour colouriser wheels (sRGB): band n (count n of 8) takes wheel[(n + r) mod 16], r = K5's step (0 .. 15).
# r = 0 is the designed look: crimson bottom field .. violet .. rainbow .. cyan .. deep-blue top field.
WHEEL_A = [(120, 0, 52), (128, 28, 200), (232, 30, 160), (240, 40, 40), (255, 140, 0), (250, 228, 30),
           (60, 210, 70), (0, 200, 230), (20, 70, 175), (0, 112, 120), (90, 220, 120), (215, 240, 60),
           (255, 170, 60), (255, 80, 140), (185, 40, 205), (60, 16, 110)]          # Spectrum
WHEEL_B = [(16, 14, 60), (0, 80, 150), (0, 170, 210), (110, 240, 240), (235, 250, 245), (255, 215, 110),
           (255, 140, 40), (255, 60, 110), (235, 20, 160), (120, 10, 120), (60, 0, 50), (150, 20, 40),
           (255, 90, 30), (255, 200, 0), (120, 230, 60), (0, 110, 90)]            # Neon
FRINGE = (255, 255, 255)
FR_STRENGTH = 0.55          # pale fringe at the middle of each band step
FR_HALF = 0.24              # fringe half-width (fraction of a band step)
BL_GAIN = 2.2               # blend slope across a band step (1 = linear over the whole step)


def rgb_to_hw10(rgb):
    r, g, b = [c / 255.0 for c in rgb]
    y = 0.299 * r + 0.587 * g + 0.114 * b
    cb, cr = (b - y) / 1.772, (r - y) / 1.402
    return (round(64 + y * 876), round(512 + cr * 896), round(512 + cb * 896))


def prescale(yuv):
    y, u, v = yuv
    y2 = 64 + (y - 64) * 16.0 / 13.0
    return (int(round(min(940, max(64, y2)))), int(u), int(v))


def logcos_rom():
    return [int(round(4096 * -math.log2(math.cos(2 * math.pi * (i + 0.5) / 1024)))) for i in range(256)]


def exp_rom():
    out = []
    for i in range(256):
        t = int(round(2048 * 2 ** (i / 256.0))) - 2048
        s2 = int(round(2 * (2 ** ((i + 1) / 256.0) - 2 ** (i / 256.0)) * 2048))
        assert 0 <= t < 2048 and 0 <= s2 < 32
        out.append(t | (s2 << 11))
    return out


def pal_rom():
    """512 x 24: address s * 256 + j * 16 + f -> the blend of wheel_s[j] and wheel_s[j + 1] at count fraction
    (f + 1/2) / 16 with a pale fringe at the middle; 8-bit Y | U | V (10-bit >> 2; Y pre-scaled 16/13)"""
    out = []
    for wheel in (WHEEL_A, WHEEL_B):
        for j in range(16):
            a = prescale(rgb_to_hw10(wheel[j])); b = prescale(rgb_to_hw10(wheel[(j + 1) % 16]))
            w = prescale(rgb_to_hw10(FRINGE))
            for f in range(16):
                x = (f + 0.5) / 16.0
                sb = min(1.0, max(0.0, (x - 0.5) * BL_GAIN + 0.5))
                fr = max(0.0, 1 - abs(x - 0.5) / FR_HALF) * FR_STRENGTH
                v = [(1 - fr) * ((1 - sb) * a[c] + sb * b[c]) + fr * w[c] for c in range(3)]
                y8 = int(round(min(940, max(64, v[0])) / 4.0))
                u8 = int(round(min(1008, max(16, v[1])) / 4.0))
                v8 = int(round(min(1008, max(16, v[2])) / 4.0))
                out.append((y8 << 16) | (u8 << 8) | v8)
    return out


def vhd_table(name, depth, width, vals):
    lines = ["    type %s is array (0 to %d) of unsigned(%d downto 0);" % ("t_" + name.lower(), depth - 1, width - 1),
             "    constant %s : %s := (" % (name, "t_" + name.lower())]
    items = ['x"%0*X"' % ((width + 3) // 4, v) for v in vals]
    for i in range(0, len(items), 16):
        lines.append("        " + ", ".join(items[i:i + 16]) + ("," if i + 16 < len(items) else ""))
    lines.append("    );")
    return "\n".join(lines)


def main():
    parts = ["-- Generated by ringdown.py -- DO NOT EDIT.",
             "library ieee;", "use ieee.std_logic_1164.all;", "use ieee.numeric_std.all;", "",
             "package ringdown_pkg is",
             vhd_table("C_RD_LOGCOS", 256, 16, logcos_rom()),
             vhd_table("C_RD_EXP", 256, 16, exp_rom()),
             vhd_table("C_RD_PAL", 512, 24, pal_rom()),
             "end package ringdown_pkg;", ""]
    with open(os.path.join(HERE, "ringdown_pkg.vhd"), "w") as f:
        f.write("\n".join(parts))


if __name__ == "__main__":
    main()
