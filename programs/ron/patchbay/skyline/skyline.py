"""
SKYLINE v0.1.0 - build hook.  Writes skyline_pkg.vhd next to this file (pure python: the builder runs it with
the system python3).  The same tables are read by the integer model (.patchbay_work/rb_skyline/imodel.py).

Package contents:
  C_SK_PAL   512 x 32   the colouriser: {Y - 64 (10), U - 512 (10, signed), V - 512 (10, signed), 00}
                        index = variant * 256 + wheel index; variant 0 = the ladder wheel, 1 = the cap / trail
                        wheel (the complement, 128 steps round the wheel, lifted toward white)
  C_SK_TAB   512 x 16   0..255: sine, round(128 + 127 sin(2 pi i / 256));  256 + N: round(65536 / N), N = 8..96
Colours are in the hardware convention (U register = Cr, V register = Cb); luma pre-scaled 16/13 for the
shell's 13/16 output scale, capped at 940 (drawn whites ~777).
"""
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))

# The wheel: (start index, colour at the band's start, colour at its end).  Wide flat bands with thin fringe
# bands between them, cyclic.  The VU ladder is indices 0 .. 104 (green, yellow, red); overdrive pushes on to
# hot pink and white (.. 148); the rest (violet, blue, cyan, teal) is reached by rotating the colouriser.
BANDS = [
    (0,   (0, 120, 40),    (10, 215, 30)),      # green
    (46,  (190, 255, 60),  (190, 255, 60)),     # lime fringe
    (50,  (255, 225, 0),   (255, 190, 0)),      # yellow -> amber
    (76,  (255, 250, 200), (255, 250, 200)),    # pale fringe
    (79,  (255, 60, 0),    (235, 0, 20)),       # orange-red -> red
    (104, (255, 170, 60),  (255, 170, 60)),     # amber fringe
    (107, (255, 0, 150),   (255, 40, 220)),     # hot pink -> magenta
    (134, (255, 235, 245), (255, 250, 235)),    # white hot
    (152, (160, 60, 255),  (95, 30, 235)),      # violet
    (178, (255, 120, 220), (255, 120, 220)),    # pink fringe
    (181, (20, 40, 235),   (0, 90, 255)),       # blue
    (210, (200, 255, 255), (200, 255, 255)),    # ice fringe
    (213, (0, 200, 230),   (0, 170, 150)),      # cyan -> teal
    (243, (0, 90, 60),     (0, 105, 45)),       # dark teal, into the green
]
IDX_HOT = 148        # the ladder index saturates here (white hot)
IDX_HZ = 160         # the horizon line's wheel index (violet)

def wheel_rgb():
    out = [(0, 0, 0)] * 256
    for bi, (s, c0, c1) in enumerate(BANDS):
        e = BANDS[bi + 1][0] if bi + 1 < len(BANDS) else 256
        for i in range(s, e):
            t = (i - s) / float(e - s - 1) if e - s > 1 else 0.0
            out[i] = tuple(c0[j] + (c1[j] - c0[j]) * t for j in range(3))
    return out

def cap_rgb():
    w = wheel_rgb()
    return [tuple(0.8 * w[(i + 128) & 255][j] + 0.2 * 255.0 for j in range(3)) for i in range(256)]

def rgb_to_hw10(rgb):
    r, g, b = [c / 255.0 for c in rgb]
    y = 0.299 * r + 0.587 * g + 0.114 * b
    cb, cr = (b - y) / 1.772, (r - y) / 1.402
    return (int(round(64 + y * 876)), int(round(512 + cr * 896)), int(round(512 + cb * 896)))

def word(rgb):
    y, u, v = rgb_to_hw10(rgb)
    y2 = int(round(min(940, max(64, 64 + (y - 64) * 16.0 / 13.0)))) - 64
    u2 = max(-488, min(488, u - 512)) & 1023
    v2 = max(-488, min(488, v - 512)) & 1023
    return (y2 << 22) | (u2 << 12) | (v2 << 2)

def pal_rom():
    return [word(c) for c in wheel_rgb()] + [word(c) for c in cap_rgb()]

def tab_rom():
    out = [int(round(128 + 127 * math.sin(2 * math.pi * i / 256.0))) for i in range(256)]
    out += [int(round(65536.0 / n)) if 8 <= n <= 96 else 0 for n in range(256)]
    return out

def vhd_table(name, typ, depth, width, vals):
    lines = ["    type %s is array (0 to %d) of %s(%d downto 0);" % ("t_" + name.lower(), depth - 1, typ, width - 1),
             "    constant %s : %s := (" % (name, "t_" + name.lower())]
    items = ['x"%0*X"' % (width // 4, v) for v in vals]
    for i in range(0, len(items), 16):
        lines.append("        " + ", ".join(items[i:i + 16]) + ("," if i + 16 < len(items) else ""))
    lines.append("    );")
    return "\n".join(lines)

def main():
    parts = ["-- Generated by skyline.py -- DO NOT EDIT.",
             "library ieee;", "use ieee.std_logic_1164.all;", "use ieee.numeric_std.all;", "",
             "package skyline_pkg is",
             vhd_table("C_SK_PAL", "std_logic_vector", 512, 32, pal_rom()),
             vhd_table("C_SK_TAB", "unsigned", 512, 16, tab_rom()),
             "end package skyline_pkg;", ""]
    with open(os.path.join(HERE, "skyline_pkg.vhd"), "w") as f:
        f.write("\n".join(parts))

if __name__ == "__main__":
    main()
