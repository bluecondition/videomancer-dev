"""Generate starwipe_pkg.vhd: the engine's sine ROM and the assembled
microcode (1024 x 32).  Edit the generators, never the package."""
import os
import sw_tables as T
import sw_ucode2 as uc

UCODE_DEPTH = 1280
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'starwipe_pkg.vhd')


def rom(name, typ, vals, width, depth):
    hexw = (width + 3) // 4
    vals = list(vals) + [0] * (depth - len(vals))
    items = [f'x"{v:0{hexw}X}"' for v in vals]
    rows = [', '.join(items[i:i + 8]) for i in range(0, depth, 8)]
    return f'    constant {name} : {typ} := (\n        ' + ',\n        '.join(rows) + ');\n'


def main():
    A = uc.build()
    words = A.words()
    assert len(words) <= UCODE_DEPTH, f'microcode is {len(words)} words, ROM is {UCODE_DEPTH}'
    s = []
    s.append('-- Copyright (C) 2026 czartroniks\n-- SPDX-License-Identifier: GPL-3.0-only\n--\n')
    s.append('-- starwipe_pkg.vhd -- GENERATED by tools/sw_gen2.py; edit the generators\n')
    s.append('-- (sw_tables.py, sw_ucode2.py), never this file.\n--\n')
    s.append(f'-- C_SIN quarter sine Q15 (256); C_UCODE {len(words)} of {UCODE_DEPTH} words.\n\n')
    s.append('library ieee;\nuse ieee.std_logic_1164.all;\n\npackage starwipe_pkg is\n')
    s.append('    type t_rom16_256 is array(0 to 255) of std_logic_vector(15 downto 0);\n')
    s.append(f'    type t_ucode is array(0 to {UCODE_DEPTH - 1}) of std_logic_vector(31 downto 0);\n')
    s.append(rom('C_SIN', 't_rom16_256', T.SIN, 16, 256))
    s.append(rom('C_UCODE', 't_ucode', words, 32, UCODE_DEPTH))
    s.append('end package starwipe_pkg;\n')
    open(OUT, 'w').write(''.join(s))
    print(f'wrote {OUT}: {len(words)} microcode words, {len(A.regs)} globals')


if __name__ == '__main__':
    main()
