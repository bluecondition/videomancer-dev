"""
HATCH v0.1.0 (Straightedge) - build hook.  Writes hatch_pkg.vhd next to this file (pure python: the builder runs
it with the system python3).  The integer model (.straightedge_work/rb_hatch/imodel.py) reads the same tables.

Families: 0 V (vertical lines), 1 H (horizontal lines), 2 D1 (lines x + y = k P, "/"), 3 D2 (x - y = k P, "\").

Package contents:
  C_HT_EXP    256 x 16   round(32768 * 2^(i/256))        (pitch, panel size and drift speed are exponential)
  C_HT_CMB     16 x 10   LeWitt's 15 combinations (entry 15 = entry 14): bits 2f+1..2f = the rank of family f in the
                         combination's order (the combination's own families first), bits 9..8 = its size - 1
  C_HT_TT      16 x 4    camera: 4-bit luma -> layer level 0 .. 8 (Grey; Ink uses 8 - t)
  C_HT_GV/GH/GD1/GD2  8 x 21   |geometric seed| per x step (index xs = 2, 3, 4), Q10 pixel widths: the line
                         phase of each family at pixel 0 of line 0 is minus this (lines pass through the centre)
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))

# LeWitt's order: V, H, D1, D2, VH, VD1, VD2, HD1, HD2, D1D2, VHD1, VHD2, VD1D2, HD1D2, VHD1D2.  Each as its
# priority order (first = the panel's single direction at Layers 0 %, balanced 4 / 4 / 4 / 3) and its size.
COMBO = [
    ([0, 1, 2, 3], 1), ([1, 2, 3, 0], 1), ([2, 3, 0, 1], 1), ([3, 0, 1, 2], 1),
    ([0, 1, 2, 3], 2), ([2, 0, 3, 1], 2), ([3, 0, 1, 2], 2), ([1, 2, 3, 0], 2), ([3, 1, 0, 2], 2), ([2, 3, 0, 1], 2),
    ([1, 0, 2, 3], 3), ([0, 1, 3, 2], 3), ([0, 2, 3, 1], 3), ([1, 2, 3, 0], 3),
    ([2, 0, 1, 3], 4),
]
TT = [0, 0, 0, 1, 1, 2, 3, 4, 4, 5, 6, 7, 7, 8, 8, 8]
R2 = 724                       # 1024 / sqrt(2): the diagonal families' step per pixel, Q10
XC = {2: 960, 3: 640, 4: 360}  # the screen centre, pixels from the left edge
YC = {2: 540, 3: 360, 4: 270}  # 540 virtual px in pixel widths


def exp2_rom():
    return [int(round(32768 * 2 ** (i / 256.0))) for i in range(256)]


def cmb_rom():
    out = []
    for c in range(16):
        order, n = COMBO[min(c, 14)]
        v = 0
        for f in range(4):
            v |= order.index(f) << (2 * f)
        out.append(v | ((n - 1) << 8))
    return out


def gseeds():
    g = {}
    for xs in (2, 3, 4):
        g[xs] = (XC[xs] * 1024, YC[xs] * 1024, (XC[xs] + YC[xs]) * R2, (XC[xs] - YC[xs]) * R2)
    return g


def vhd_table(name, typ, depth, width, vals):
    lines = ["    type %s is array (0 to %d) of %s(%d downto 0);" % ("t_" + name.lower(), depth - 1, typ, width - 1),
             "    constant %s : %s := (" % (name, "t_" + name.lower())]
    if width % 4 == 0:
        items = ['x"%0*X"' % (width // 4, v & ((1 << width) - 1)) for v in vals]
    else:
        items = ['"' + format(v & ((1 << width) - 1), "0%db" % width) + '"' for v in vals]
    for i in range(0, len(items), 16):
        lines.append("        " + ", ".join(items[i:i + 16]) + ("," if i + 16 < len(items) else ""))
    lines.append("    );")
    return "\n".join(lines)


def main():
    g = gseeds()
    gt = lambda k: [0, 0] + [g[xs][k] for xs in (2, 3, 4)] + [0, 0, 0]
    parts = ["-- Generated by hatch.py -- DO NOT EDIT.",
             "library ieee;", "use ieee.std_logic_1164.all;", "use ieee.numeric_std.all;", "",
             "package hatch_pkg is",
             vhd_table("C_HT_EXP", "unsigned", 256, 16, exp2_rom()),
             vhd_table("C_HT_CMB", "unsigned", 16, 10, cmb_rom()),
             vhd_table("C_HT_TT", "unsigned", 16, 4, TT),
             vhd_table("C_HT_GV", "unsigned", 8, 21, gt(0)),
             vhd_table("C_HT_GH", "unsigned", 8, 21, gt(1)),
             vhd_table("C_HT_GD1", "unsigned", 8, 21, gt(2)),
             vhd_table("C_HT_GD2", "unsigned", 8, 21, gt(3)),
             "end package hatch_pkg;", ""]
    with open(os.path.join(HERE, "hatch_pkg.vhd"), "w") as f:
        f.write("\n".join(parts))


if __name__ == "__main__":
    main()
