"""
HINGE v0.1.0 (Straightedge) - build hook.  Writes hinge_pkg.vhd next to this file (pure python: the builder
runs it with the system python3).  The integer model (.straightedge_work/rb_hinge/imodel.py) reads the same
table.

Package contents:
  C_HG_ROM   1024 x 16   0 .. 255     round(32768 * 2^(i/256))            (Scale and the Drift speed)
                         256 .. 511   round(32768 * sin(i * pi / 512))    (i = 0 .. 128 is 0 .. 45 degrees)
                         512 .. 767   round(32768 * cos(i * pi / 512))
                         768 .. 1023  round(32768 / cos(i * pi / 512))    (capped at 65535 past 45 degrees)
"""
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))


def rom():
    exp = [int(round(32768 * 2 ** (i / 256.0))) for i in range(256)]
    sn = [int(round(32768 * math.sin(i * math.pi / 512.0))) for i in range(256)]
    cs = [int(round(32768 * math.cos(i * math.pi / 512.0))) for i in range(256)]
    sec = [min(65535, int(round(32768 / math.cos(i * math.pi / 512.0)))) for i in range(256)]
    return exp + sn + cs + sec


def vhd_table(name, depth, width, vals):
    digits = (width + 3) // 4
    lines = ["    type %s is array (0 to %d) of unsigned(%d downto 0);" % ("t_" + name.lower(), depth - 1, width - 1),
             "    constant %s : %s := (" % (name, "t_" + name.lower())]
    items = ['x"%0*X"' % (digits, v) for v in vals]
    for i in range(0, len(items), 16):
        lines.append("        " + ", ".join(items[i:i + 16]) + ("," if i + 16 < len(items) else ""))
    lines.append("    );")
    return "\n".join(lines)


def main():
    parts = ["-- Generated by hinge.py -- DO NOT EDIT.",
             "library ieee;", "use ieee.std_logic_1164.all;", "use ieee.numeric_std.all;", "",
             "package hinge_pkg is",
             vhd_table("C_HG_ROM", 1024, 16, rom()),
             "end package hinge_pkg;", ""]
    with open(os.path.join(HERE, "hinge_pkg.vhd"), "w") as f:
        f.write("\n".join(parts))


if __name__ == "__main__":
    main()
