"""
MEANDER v0.1.0 (Straightedge) - build hook.  Writes meander_pkg.vhd next to this file (pure python: the builder
runs it with the system python3).  The integer model (.straightedge_work/rb_meander/imodel.py) builds the same
tables.

Package contents:
  C_MD_TAB   512 x 16   0 .. 255:   round(32768 * 2^(i/256))   (the key's pitch and the drift speed are exponential)
                        256 .. 319: the tone table, [odd-row * 32 + coverage (0 .. 16)] -> luma code: even rows
                                    black -> white, odd rows (Grey) dark grey 0.20 -> light grey 0.67; Y = 64 + 876 tone
                        (one block RAM, read by the sequencer in the vblank zone and by the pixel path outside it)
  C_MD_KEY   256 x 16   the Greek key: one node record per cell of the 16 x 8 unit, address = mirror & j & i
                        (j = 0 is the top node row; mirror = 1 holds the unit reflected left-right, for the odd
                        rows).  bit 14 wave (the square wave, always drawn) | 13..8 order along the spiral
                        (0 = the T node on the wave, 49 = the eye) | 7..6 heading out | 5..4 heading in |
                        3..0 arms (bit 0 N, 1 E, 2 S, 3 W).  Headings: 0 N, 1 E, 2 S, 3 W.

The unit: a square wave (wall up at x = 0, top y = 7 to x = 8, wall down at x = 8, bottom y = 0 to x = 16), and
in each of its two boxes a square spiral that leaves the wave at a T node (the foot of the merlon's right wall;
the same turned 180 degrees in the crenel) and winds inward through all 49 nodes of the box.
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))

N_, E_, S_, W_ = 0, 1, 2, 3
OPP = {N_: S_, S_: N_, E_: W_, W_: E_}
NEND = 49
TONES = ((0.0, 1.0), (0.20, 0.67))


def exp_rom():
    return [int(round(32768 * 2 ** (i / 256.0))) for i in range(256)]


def build_nodes():
    """(x, y) with y UP -> dict(mask, ord, inh, outh, wave)"""
    nd = {}

    def put(x, y, arms, ordn=0, inh=0, outh=0, wave=1):
        m = 0
        for a in arms:
            m |= 1 << a
        nd[(x % 16, y)] = dict(mask=m, ord=ordn, inh=inh, outh=outh, wave=wave)

    put(0, 0, [N_, W_])
    for y in range(1, 7):
        put(0, y, [N_, S_]); put(8, y, [N_, S_])
    for x in range(1, 8):
        put(x, 7, [E_, W_]); put(x + 8, 0, [E_, W_])
    put(8, 7, [W_, S_])
    put(8, 0, [N_, E_, W_], 0, W_, W_, 0)
    put(0, 7, [S_, E_, W_], 0, W_, W_, 0)

    def spiral(rot):
        segs = [(W_, 7), (N_, 6), (E_, 6), (S_, 5), (W_, 5), (N_, 4), (E_, 4), (S_, 3), (W_, 3), (N_, 2), (E_, 2), (S_, 1), (W_, 1)]
        d = {N_: (0, 1), S_: (0, -1), E_: (1, 0), W_: (-1, 0)}
        x, y = 8, 0
        path = []
        for h, n in segs:
            for _ in range(n):
                x += d[h][0]; y += d[h][1]
                path.append((x, y, h))
        assert len(path) == NEND
        for k, (px, py, h) in enumerate(path):
            last = k + 1 == len(path)
            outh = h if last else path[k + 1][2]
            arms = [OPP[h]] + ([] if last else [outh])
            if rot:
                put(16 - px, 7 - py, [OPP[a] for a in arms], k + 1, OPP[h], OPP[outh], 0)
            else:
                put(px, py, arms, k + 1, h, outh, 0)

    spiral(False)
    spiral(True)
    assert len(nd) == 128
    return nd


def key_rom():
    nd = build_nodes()
    sw = {N_: N_, S_: S_, E_: W_, W_: E_}
    rom = [0] * 256
    for (x, y), r in nd.items():
        j = 7 - y
        rom[j * 16 + x] = (r['wave'] << 14) | (r['ord'] << 8) | (r['outh'] << 6) | (r['inh'] << 4) | r['mask']
        m = 0
        for a in range(4):
            if r['mask'] >> a & 1:
                m |= 1 << sw[a]
        rom[128 + j * 16 + (15 - x)] = (r['wave'] << 14) | (r['ord'] << 8) | (sw[r['outh']] << 6) | (sw[r['inh']] << 4) | m
    return rom


def tone_rom():
    return [64 + int(round(876 * (g + (l - g) * min(c, 16) / 16.0))) for (g, l) in TONES for c in range(32)]


def vhd_table(name, typ, depth, width, vals):
    lines = ["    type %s is array (0 to %d) of %s(%d downto 0);" % ("t_" + name.lower(), depth - 1, typ, width - 1),
             "    constant %s : %s := (" % (name, "t_" + name.lower())]
    items = ['to_unsigned(%d, %d)' % (v, width) for v in vals]
    for i in range(0, len(items), 8):
        lines.append("        " + ", ".join(items[i:i + 8]) + ("," if i + 8 < len(items) else ""))
    lines.append("    );")
    return "\n".join(lines)


def main():
    parts = ["-- Generated by meander.py -- DO NOT EDIT.",
             "library ieee;", "use ieee.std_logic_1164.all;", "use ieee.numeric_std.all;", "",
             "package meander_pkg is",
             vhd_table("C_MD_TAB", "unsigned", 512, 16, exp_rom() + tone_rom() + [0] * 192),
             vhd_table("C_MD_KEY", "unsigned", 256, 16, key_rom()),
             "end package meander_pkg;", ""]
    with open(os.path.join(HERE, "meander_pkg.vhd"), "w") as f:
        f.write("\n".join(parts))


if __name__ == "__main__":
    main()
