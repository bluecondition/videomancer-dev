"""
PENTAGRID v0.1.0 (Straightedge) - build hook.  Writes pentagrid_pkg.vhd next to this file (pure python: the
builder runs it with the system python3).  The integer model (.straightedge_work/rb_pentagrid/imodel.py) reads
the same tables.

Package contents:
  C_PG_EXP    256 x 16   round(32768 * 2^(i/256))            (band period and drift speed are exponential)
  C_PG_SIN   1024 x 16   round(16384 * sin(i * pi / 2048))   (a quarter wave; the sequencer interpolates)
  C_PG_KN       8 x 16   round(2^17 / N): the fan step of a full turn / N in 2^-18 turns (index N)
  C_PG_DELT     8 x 4    the period spread of family k at Fan 0 (signed, 1/32)
  C_PG_RATE     8 x 7    the drift rate of family k (signed, 1/32): 1, -3/4, 2/3, -1/2, 5/4, -7/8, 9/8, -5/8
  C_PG_LO / C_PG_HI / C_PG_SL   16 x ..   Bold / Grey tone ramp, index = Stairs & (N - 3): first and last level
                         (in 16ths of a band: 16 per level) and the luma step per 16th (Q6)
"""
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))

DELT = [0, 3, -2, 5, -4, 1, -6, 7]
RATE = [32, -24, 21, -16, 40, -28, 36, -20]
# Bold / Grey: the count of gaps over a pixel runs 0 .. N (Stairs: 0 .. 3 N); white at <= lo, black at >= hi
FLAT_LOHI = {3: (0, 3), 4: (0, 4), 5: (0, 5), 6: (1, 5), 7: (1, 6), 8: (2, 6)}
STAIR_LOHI = {3: (1, 8), 4: (2, 10), 5: (3, 12), 6: (4, 14), 7: (5, 16), 8: (6, 18)}


def exp2_rom():
    return [int(round(32768 * 2 ** (i / 256.0))) for i in range(256)]


def sin_rom():
    return [int(round(16384 * math.sin(i * math.pi / 2048.0))) for i in range(1024)]


def kn_tab():
    return [0, 0, 0] + [int(round(131072.0 / n)) for n in range(3, 9)][:5] + [16384]


def ramp_tabs():
    lo, hi, sl = [], [], []
    for tab in (FLAT_LOHI, STAIR_LOHI):
        for n in range(3, 11):
            a, b = tab.get(n, tab[8])
            lo.append(a); hi.append(b); sl.append(int(round(3504.0 / (b - a))))
    return lo, hi, sl


def vhd_table(name, typ, depth, width, vals):
    lines = ["    type %s is array (0 to %d) of %s(%d downto 0);" % ("t_" + name.lower(), depth - 1, typ, width - 1),
             "    constant %s : %s := (" % (name, "t_" + name.lower())]
    if width % 4 == 0:
        items = ['x"%0*X"' % (width // 4, v & ((1 << width) - 1)) for v in vals]
    else:
        items = ['"' + format(v & ((1 << width) - 1), "0%db" % width) + '"' for v in vals]
    for i in range(0, len(items), 16):
        lines.append("        " + ", ".join(items[i:i + 16]) + ("," if i + 16 < len(items) else ""))
    lines.append("    );")
    return "\n".join(lines)


def main():
    lo, hi, sl = ramp_tabs()
    parts = ["-- Generated by pentagrid.py -- DO NOT EDIT.",
             "library ieee;", "use ieee.std_logic_1164.all;", "use ieee.numeric_std.all;", "",
             "package pentagrid_pkg is",
             vhd_table("C_PG_EXP", "unsigned", 256, 16, exp2_rom()),
             vhd_table("C_PG_SIN", "unsigned", 1024, 16, sin_rom()),
             vhd_table("C_PG_KN", "unsigned", 9, 16, kn_tab()),
             vhd_table("C_PG_DELT", "signed", 8, 4, DELT),
             vhd_table("C_PG_RATE", "signed", 8, 7, RATE),
             vhd_table("C_PG_LO", "unsigned", 16, 5, lo),
             vhd_table("C_PG_HI", "unsigned", 16, 5, hi),
             vhd_table("C_PG_SL", "unsigned", 16, 12, sl),
             "end package pentagrid_pkg;", ""]
    with open(os.path.join(HERE, "pentagrid_pkg.vhd"), "w") as f:
        f.write("\n".join(parts))


if __name__ == "__main__":
    main()
