"""
SLIVER v0.1.0 (Straightedge) - build hook.  Writes sliver_pkg.vhd next to this file (pure python: the builder
runs it with the system python3).  The integer model (.straightedge_work/rb_sliver/imodel.py) reads the same tables.

Package contents:
  C_SV_EXP    256 x 16   round(32768 * 2^(i/256))                 (opening angle and Drift speed are exponential)
  C_SV_SIN   1024 x 16   round(16384 * sin(i * pi / 2048))        (a quarter wave; the sequencer interpolates)
  C_SV_PSI      6 x 16   each sliver's apex direction from the gathering point (65536 per turn, y down)
  C_SV_DPHI     6 x 16   its axis direction minus its apex direction
  C_SV_DKQ      6 x 12   its apex distance at Spread 100 %: pixels (Q3) = (Sd * DKQ) >> 9, Sd = P12 (Q3) on the raster
  C_SV_RATE     6 x 6    its turn rate in sixteenths (signed)
  C_SV_OPF      6 x 2    its opening: 0 = x1, 1 = x3/4, 2 = x5/4, 3 = x1/2
"""
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))

# the six slivers (degrees, y down; virtual px)
PSI_DEG = [160.8, 329.0, 22.9, 222.7, 56.3, 244.2]
PHI_DEG = [332.0, 128.0, 188.0, 52.0, 256.0, 100.0]
DK = [911.0, 816.0, 977.0, 708.0, 721.0, 689.0]
RATE = [16, -12, 11, -8, 20, -5]
OPF = [0, 1, 2, 3, 0, 1]


def exp2_rom():
    return [int(round(32768 * 2 ** (i / 256.0))) for i in range(256)]


def sin_rom():
    return [int(round(16384 * math.sin(i * math.pi / 2048.0))) for i in range(1024)]


def psi_tab():
    return [int(round(d * 65536 / 360.0)) & 0xFFFF for d in PSI_DEG]


def dphi_tab():
    return [int(round((p - q) * 65536 / 360.0)) & 0xFFFF for p, q in zip(PHI_DEG, PSI_DEG)]


def dk_tab():
    return [int(round(d * 8 * 512 / 8184.0)) for d in DK]


def vhd_table(name, typ, depth, width, vals):
    lines = ["    type %s is array (0 to %d) of %s(%d downto 0);" % ("t_" + name.lower(), depth - 1, typ, width - 1),
             "    constant %s : %s := (" % (name, "t_" + name.lower())]
    if width % 4 == 0:
        items = ['x"%0*X"' % (width // 4, v & ((1 << width) - 1)) for v in vals]
    else:
        items = ['"%s"' % format(v & ((1 << width) - 1), "0%db" % width) for v in vals]
    for i in range(0, len(items), 16):
        lines.append("        " + ", ".join(items[i:i + 16]) + ("," if i + 16 < len(items) else ""))
    lines.append("    );")
    return "\n".join(lines)


def main():
    parts = ["-- Generated by sliver.py -- DO NOT EDIT.",
             "library ieee;", "use ieee.std_logic_1164.all;", "use ieee.numeric_std.all;", "",
             "package sliver_pkg is",
             vhd_table("C_SV_EXP", "unsigned", 256, 16, exp2_rom()),
             vhd_table("C_SV_SIN", "unsigned", 1024, 16, sin_rom()),
             vhd_table("C_SV_PSI", "unsigned", 6, 16, psi_tab()),
             vhd_table("C_SV_DPHI", "unsigned", 6, 16, dphi_tab()),
             vhd_table("C_SV_DKQ", "unsigned", 6, 12, dk_tab()),
             vhd_table("C_SV_RATE", "signed", 6, 6, RATE),
             vhd_table("C_SV_OPF", "unsigned", 6, 2, OPF),
             "end package sliver_pkg;", ""]
    with open(os.path.join(HERE, "sliver_pkg.vhd"), "w") as f:
        f.write("\n".join(parts))


if __name__ == "__main__":
    main()
