-- sugarcoat.vhd
--
-- SUGARCOAT -- video re-rendered as candy: a 1:1 COLOUR -> CANDY-TEXTURE map.
--
-- Each pixel is classified by its chroma (hue octant / saturation) or, when
-- neutral, by its luma; the class picks one of 8 flat screen-space candy
-- materials.  NO generated geometry -- no polar/radial patterns, the picture
-- alone decides where each candy appears.  SUGAR RUSH (P12) dips the raw
-- image into the confection.
--
-- Classes: neutral dark -> dark chocolate bar (quilted grooves), neutral dim
-- -> cookies & cream (cream dots on black), neutral light -> piped icing
-- (wavy scallop piping), neutral bright -> frosting + rainbow confetti;
-- red -> candy cane stripes, yellow -> choc-chip cookie, green -> mint
-- stripes (opposite diagonal), blue/cyan/magenta -> rainbow taffy stripes
-- (palette ramp, K4).
--
-- Pipeline (streaming, C_LATENCY = 16, 1 EBR = gloss line RAM):
--   Classify: E1 in -> E2 |du|,|dv|,sat,octant -> E3 class -> E4 (+K1 rotate)
--             -> txd SR to the texture stage.
--   Geometry: W1/W2 domain warp (drifting cross-axis triangle, shift-scaled)
--             -> three projections (dx+dy, dx-dy, wavy dy) -> pattern bits.
--   Gloss:    line RAM -> 2D luma-gradient emboss -> specular sheen g_add.
--   MP/PH1:   pattern bits + garnish decision + taffy palette read.
--   PH2/CO:   texture bank (constant-colour selects) -> gloss add -> clamp.
--   SUGAR RUSH inline dry/wet lerp (M1..M3), sync-aligned output.
-- Multiplies (HX4K has no DSP): only the mix x3.  Everything else is
-- shifts, compares and slices.
--------------------------------------------------------------------------------

