"""
CARTOUCHE v0.1.0 (Vellum) - build hook.  Writes cartouche_pkg.vhd next to this file (pure python: the builder
runs it with the system python3).  The integer model (.vellum_work/rb_cartouche/imodel.py) reads the same table.

Package contents:
  C_CT_EXP   256 x 16   round(32768 * 2^(i/256))   (the band period and the Drift speed are exponential)
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
C_SL = 18        # the pixel stage that adds the camera phase (the model aligns the luma stream with it)


def exp2_rom():
    return [int(round(32768 * 2 ** (i / 256.0))) for i in range(256)]


def vhd_table(name, depth, width, vals):
    digits = (width + 3) // 4
    lines = ["    type %s is array (0 to %d) of unsigned(%d downto 0);" % ("t_" + name.lower(), depth - 1, width - 1),
             "    constant %s : %s := (" % (name, "t_" + name.lower())]
    items = ['x"%0*X"' % (digits, v) for v in vals]
    for i in range(0, len(items), 16):
        lines.append("        " + ", ".join(items[i:i + 16]) + ("," if i + 16 < len(items) else ""))
    lines.append("    );")
    return "\n".join(lines)


def main():
    parts = ["-- Generated by cartouche.py -- DO NOT EDIT.",
             "library ieee;", "use ieee.std_logic_1164.all;", "use ieee.numeric_std.all;", "",
             "package cartouche_pkg is",
             vhd_table("C_CT_EXP", 256, 16, exp2_rom()),
             "end package cartouche_pkg;", ""]
    with open(os.path.join(HERE, "cartouche_pkg.vhd"), "w") as f:
        f.write("\n".join(parts))


if __name__ == "__main__":
    main()
