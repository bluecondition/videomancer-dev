"""
DECADE v0.1.0 (Vellum) - build hook.  Writes decade_pkg.vhd next to this file (pure python: the builder runs
it with the system python3).  The integer model (.vellum_work/rb_decade/imodel.py) reads the same tables.

Package contents:
  C_DC_SEQ   512 x 16   0 .. 255: round(32768 * 2^(i/256))             (exp2 mantissa, Q15)
                        256 .. 383: round(65536 * log2(1 + i/128))     (log2 mantissa, Q16; i = 128 is 65536,
                                                                       supplied by logic)
  C_DC_V     512 x 8    round(16 * 10^((i + 1/2) / 512))              (the value 1 .. 10 at a decade fraction, Q4)
  C_DC_LP    256 x 19   the two banks below as one ROM: address = bank & index (bank 1 = lin)
  C_DC_LPL / C_DC_LPN   21 x 19   line positions in a decade, Q18, by index in halves:
                        log  round(2^18 log10(idx / 2))  (idx 2 .. 20)      lin  round(2^18 idx / 20)
"""
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))


def exp2m():
    return [int(round(32768 * 2 ** (i / 256.0))) for i in range(256)]


def log2m():
    """129 entries, Q16; the last one (65536) does not fit the ROM and is supplied by logic"""
    return [int(round(65536 * math.log2(1 + i / 128.0))) for i in range(129)]


def seq_rom():
    return exp2m() + log2m()[:128] + [0] * 128


def vrom():
    return [int(round(16 * 10 ** ((i + 0.5) / 512.0))) for i in range(512)]


def lp_log():
    return [0, 0] + [int(round((1 << 18) * math.log10(i / 2.0))) for i in range(2, 21)]


def lp_lin():
    return [int(round((1 << 18) * i / 20.0)) for i in range(21)]


def lp_rom():
    """256 x 19: address = bank (bit 5) & index (4 .. 0): the line positions (log bank 0, lin bank 1)"""
    t = [0] * 256
    for i, v in enumerate(lp_log()):
        t[i] = v
    for i, v in enumerate(lp_lin()):
        t[32 + i] = v
    return t


def vhd_table(name, depth, width, vals):
    lines = ["    type %s is array (0 to %d) of unsigned(%d downto 0);" % ("t_" + name.lower(), depth - 1, width - 1),
             "    constant %s : %s := (" % (name, "t_" + name.lower())]
    items = ["to_unsigned(%d, %d)" % (v, width) for v in vals] if width % 4 else \
            ['x"%0*X"' % (width // 4, v) for v in vals]
    per = 8 if width % 4 else 16
    for i in range(0, len(items), per):
        lines.append("        " + ", ".join(items[i:i + per]) + ("," if i + per < len(items) else ""))
    lines.append("    );")
    return "\n".join(lines)


def main():
    parts = ["-- Generated by decade.py -- DO NOT EDIT.",
             "library ieee;", "use ieee.std_logic_1164.all;", "use ieee.numeric_std.all;", "",
             "package decade_pkg is",
             vhd_table("C_DC_SEQ", 512, 16, seq_rom()),
             vhd_table("C_DC_V", 512, 8, vrom()),
             vhd_table("C_DC_LPL", 21, 19, lp_log()),
             vhd_table("C_DC_LPN", 21, 19, lp_lin()),
             vhd_table("C_DC_LP", 256, 19, lp_rom()),
             "end package decade_pkg;", ""]
    with open(os.path.join(HERE, "decade_pkg.vhd"), "w") as f:
        f.write("\n".join(parts))


if __name__ == "__main__":
    main()
