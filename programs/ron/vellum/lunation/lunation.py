"""
LUNATION v0.1.0 (Vellum) - build hook.  Writes lunation_pkg.vhd next to this file (pure python: the builder runs
it with the system python3).  The integer model (.vellum_work/rb_lunation/imodel.py) imports these generators.

Package contents:
  C_LN_EXP   256 x 16    round(32768 * 2^(i/256))                        (pitch, span and drift are exponential)
  C_LN_SIN   1024 x 11   round(2047 * sin((i + 1/2) * pi / 2048))       (a quarter wave: the moon's cos(phase))
  C_LN_Y     512 x 10    the luma of a tone value x (0 .. 256): 64 + (876 x) >> 8
  C_LN_KT    1024 x 6    the terminator's slope factor kt = rho / sqrt(c^2 + (1 - c^2) rho^2), x 64, 4 .. 63,
                         at rho = (i / 32 + 1/2) / 32 (rho = w / R, per line) and |c| = (i mod 32 + 1/2) / 32
"""
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))


def exp_rom():
    return [int(round(32768 * 2 ** (i / 256.0))) for i in range(256)]


def sin_rom():
    return [int(round(2047 * math.sin((i + 0.5) * math.pi / 2048.0))) for i in range(1024)]


def kt_rom():
    out = []
    for i in range(1024):
        rho = ((i >> 5) + 0.5) / 32.0
        c = ((i & 31) + 0.5) / 32.0
        kt = rho / math.sqrt(c * c + (1.0 - c * c) * rho * rho)
        out.append(min(63, max(4, int(round(64 * kt)))))
    return out


def y_rom():
    return [64 + ((876 * min(x, 256)) >> 8) for x in range(512)]


def vhd_table(name, typ, depth, width, vals):
    lines = ["    type %s is array (0 to %d) of %s(%d downto 0);" % ("t_" + name.lower(), depth - 1, typ, width - 1),
             "    constant %s : %s := (" % (name, "t_" + name.lower())]
    items = ['to_unsigned(%d, %d)' % (v, width) for v in vals]
    for i in range(0, len(items), 8):
        lines.append("        " + ", ".join(items[i:i + 8]) + ("," if i + 8 < len(items) else ""))
    lines.append("    );")
    return "\n".join(lines)


def main():
    parts = ["-- Generated by lunation.py -- DO NOT EDIT.",
             "library ieee;", "use ieee.std_logic_1164.all;", "use ieee.numeric_std.all;", "",
             "package lunation_pkg is",
             vhd_table("C_LN_EXP", "unsigned", 256, 16, exp_rom()),
             vhd_table("C_LN_SIN", "unsigned", 1024, 11, sin_rom()),
             vhd_table("C_LN_KT", "unsigned", 1024, 6, kt_rom()),
             vhd_table("C_LN_Y", "unsigned", 512, 10, y_rom()),
             "end package lunation_pkg;", ""]
    with open(os.path.join(HERE, "lunation_pkg.vhd"), "w") as f:
        f.write("\n".join(parts))


if __name__ == "__main__":
    main()
