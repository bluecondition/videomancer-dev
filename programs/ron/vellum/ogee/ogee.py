"""
OGEE v0.1.0 (Vellum) - build hook.  Writes ogee_pkg.vhd next to this file (pure python: the builder runs it with
the system python3).  The integer model (.vellum_work/rb_ogee/imodel.py) reads the same tables.

Package contents:
  C_OG_EXP   256 x 16   round(32768 * 2^(i/256))            (Scale, Slender and the Drift speed are exponential)
  C_OG_SINB  256 x 16   round(16384 * sin(b_i))             b_i = 45 deg * (1 - i/255): the S's tangent angle,
  C_OG_COSB  256 x 16   round(16384 * cos(b_i))             i = Curve >> 5 (0 % = straight diamonds, b = 45 deg;
  C_OG_TANB  256 x 16   round(16384 * tan(b_i))             100 % = full round, b = 0)
  C_OG_QB    256 x 16   round(16384 * sqrt(cos b_i - sin b_i))   (the curvature k = 2 (cos b - sin b) = 2 q^2)
  C_OG_G    2048 x 12   round(2048 * g(t)), g(t) = 2 / (1 + sqrt(1 - 2t)) at the cell centre:
                        i >= 1024: t = (i - 1024 + 1/2) / 2048  (0 .. 1/2);  i < 1024: t = (i - 1024 + 1/2) / 256
                        (the true distance from the arc is f g(t), f = (r^2 - rho^2) / 2r, t = s k f)
  C_OG_SQ    128 x 16   i^2   (the pixel path's squarer: v^2 >> 14 = SQ[v >> 7] + ((v >> 7) (v & 127)) >> 6)
"""
import os
import math

HERE = os.path.dirname(os.path.abspath(__file__))


def exp2_rom():
    return [int(round(32768 * 2 ** (i / 256.0))) for i in range(256)]


def beta(i):
    return math.radians(45.0) * (1.0 - i / 255.0)


def sinb_rom():
    return [int(round(16384 * math.sin(beta(i)))) for i in range(256)]


def cosb_rom():
    return [int(round(16384 * math.cos(beta(i)))) for i in range(256)]


def tanb_rom():
    return [int(round(16384 * math.tan(beta(i)))) for i in range(256)]


def qb_rom():
    return [int(round(16384 * math.sqrt(max(math.cos(beta(i)) - math.sin(beta(i)), 0.0)))) for i in range(256)]


def sq_rom():
    return [i * i for i in range(128)]


def g_rom():
    out = []
    for i in range(2048):
        t = (i - 1024 + 0.5) / 2048.0 if i >= 1024 else (i - 1024 + 0.5) / 256.0
        g = 2.0 / (1.0 + math.sqrt(1.0 - 2.0 * t))
        out.append(min(int(round(2048 * g)), 4095))
    return out


def vhd_table(name, depth, width, vals):
    digits = (width + 3) // 4
    lines = ["    type %s is array (0 to %d) of unsigned(%d downto 0);" % ("t_" + name.lower(), depth - 1, width - 1),
             "    constant %s : %s := (" % (name, "t_" + name.lower())]
    items = ['x"%0*X"' % (digits, v) for v in vals]
    for i in range(0, len(items), 16):
        lines.append("        " + ", ".join(items[i:i + 16]) + ("," if i + 16 < len(items) else ""))
    lines.append("    );")
    return "\n".join(lines)


def main():
    parts = ["-- Generated by ogee.py -- DO NOT EDIT.",
             "library ieee;", "use ieee.std_logic_1164.all;", "use ieee.numeric_std.all;", "",
             "package ogee_pkg is",
             vhd_table("C_OG_EXP", 256, 16, exp2_rom()),
             vhd_table("C_OG_SINB", 256, 16, sinb_rom()),
             vhd_table("C_OG_COSB", 256, 16, cosb_rom()),
             vhd_table("C_OG_TANB", 256, 16, tanb_rom()),
             vhd_table("C_OG_QB", 256, 16, qb_rom()),
             vhd_table("C_OG_G", 2048, 12, g_rom()),
             vhd_table("C_OG_SQ", 128, 16, sq_rom()),
             "end package ogee_pkg;", ""]
    with open(os.path.join(HERE, "ogee_pkg.vhd"), "w") as f:
        f.write("\n".join(parts))


if __name__ == "__main__":
    main()
