            s_prev_vsync <= data_in.vsync_n;
            s_vs_pulse   <= '0';
            if data_in.avid = '1' then s_saw_avid <= '1'; end if;

            rf_we <= '0';
            v_op := to_integer(unsigned(u_q(31 downto 27)));
            v_x  := to_integer(unsigned(u_q(5 downto 0)));

            if u_en = '1' then
                u_q <= C_UCODE(to_integer(u_pc));
                if u_busy = '1' then
                    -- ---------------- the serial loop ----------------
                    -- the serial adder: x + y + c (SUB / MIN / MAX: a + not b + 1; NEG / ABS: 0 + not a + 1)
                    case v_op is
                        when 1       => v_xa := u_A(0); v_ya := u_B(0);
                        when 12 | 13 => v_xa := '0';    v_ya := not u_A(0);
                        when others  => v_xa := u_A(0); v_ya := not u_B(0);
                    end case;
                    v_s  := v_xa xor v_ya xor u_c;
                    v_cy := (v_xa and v_ya) or (u_c and (v_xa or v_ya));
                    u_c  <= v_cy;
                    -- the multiplier: m = a's next bit (its sign after 32), b in parallel
                    if u_t(5) = '0' then v_m := u_A(0); else v_m := u_as; end if;
                    v_xs(32) := '0';
                    for i in 0 to 31 loop
                        v_pp := v_m and u_B(i);
                        v_xs(i) := u_ms(i) xor u_mc(i) xor v_pp;
                    end loop;
                    v_p := v_xs(0);
                    -- the 2^32 a correction (b negative): a streams again from bit 0 at t = 32
                    v_k := u_B(31) and u_t(5) and u_A(0);
                    v_o := v_p xor v_k xor u_bw;
                    -- shift-in bit of r, per op
                    v_shr := v_op = 5 or v_op = 7;
                    if u_sx = '1' then              v_rin := u_aux(0);       -- IN, NORM result
                    elsif u_p2 = '1' then           v_rin := u_B(0);         -- MIN / MAX result b
                    elsif v_op = 8 then             v_rin := v_o;
                    elsif v_op >= 4 and v_op <= 7 then
                        if u_k /= 0 and not v_shr then v_rin := '0'; else v_rin := u_A(0); end if;
                    else                            v_rin := v_s;
                    end if;

                    v_done := false;
                    if v_op = 11 then
                        -- TAB: the table entry arrives two clocks after the address
                        if u_k /= 0 then u_k <= u_k - 1;
                        else
                            u_A <= rf_q; u_wsa <= '1'; v_done := true;
                        end if;
                    elsif v_op = 8 then
                        -- MUL: x + 32 clocks; a rotates, b holds
                        u_ms <= v_xs(32 downto 1);
                        for i in 0 to 31 loop
                            v_pp := v_m and u_B(i);
                            u_mc(i) <= (u_ms(i) and u_mc(i)) or (v_pp and (u_ms(i) or u_mc(i)));
                        end loop;
                        u_bw <= (not v_p and (v_k or u_bw)) or (v_k and u_bw);
                        u_t  <= u_t + 1;
                        u_A  <= u_A(0) & u_A(31 downto 1);
                        if u_k /= 0 then u_k <= u_k - 1;
                        else
                            u_R <= v_rin & u_R(31 downto 1);
                            u_n <= u_n + 1;
                            if u_n = 31 then v_done := true; end if;
                        end if;
                    elsif v_shr and u_k /= 0 then
                        -- SHR / SHRV: skip k bits (arithmetic)
                        u_k <= u_k - 1;
                        u_A <= u_A(31) & u_A(31 downto 1);
                    elsif v_op = 10 and u_sx = '0' then
                        -- NORM: scan a LSB first for its highest set bit (bit 31 not scanned)
                        if u_A(0) = '1' and u_n /= 31 then
                            u_lw <= u_hw; u_np <= u_n(4 downto 0); u_seen <= '1';
                        end if;
                        u_hw <= u_A(0) & u_hw(5 downto 1);
                        u_A  <= u_A(0) & u_A(31 downto 1);
                        u_n  <= u_n + 1;
                        if u_n = 31 then
                            -- then stream the result: msb * 64 + the 6 bits below it, or -2048
                            u_sx <= '1';
                            u_n  <= (others => '0');
                            if u_seen = '1' then u_aux <= "0" & std_logic_vector(u_np) & u_lw;
                            else                 u_aux <= "100000000000"; end if;
                        end if;
                    else
                        -- ADD SUB NEG ABS MIN MAX SHL SHLV, the SHR body, IN, the result streams
                        u_R <= v_rin & u_R(31 downto 1);
                        u_n <= u_n + 1;
                        if u_sx = '1' then u_aux <= u_aux(11) & u_aux(11 downto 1); end if;
                        if v_op >= 4 and v_op <= 7 then
                            if v_shr then        u_A <= u_A(31) & u_A(31 downto 1);
                            elsif u_k /= 0 then  u_k <= u_k - 1;
                            else                 u_A <= u_A(0) & u_A(31 downto 1);
                            end if;
                        else
                            u_A <= u_A(0) & u_A(31 downto 1);
                            u_B <= u_B(0) & u_B(31 downto 1);
                        end if;
                        if u_n = 31 then
                            if (v_op = 14 or v_op = 15) and u_p2 = '0' then
                                -- MIN / MAX: the sign of a - b (33 bits); a and b are back in place
                                if ((u_A(0) xor (not u_B(0)) xor v_cy) = '1') = (v_op = 14) then
                                    u_wsa <= '1'; v_done := true;               -- the result is a
                                else
                                    u_p2 <= '1';                                -- stream b into r
                                    u_n  <= (others => '0');
                                end if;
                            else
                                v_done := true;
                            end if;
                        end if;
                    end if;
                    if v_done then
                        u_busy <= '0';
                        u_wb   <= '1';
                    end if;
                elsif u_wb = '1' then
                    -- write back (r, or a), next instruction
                    u_wb  <= '0';
                    rf_we <= '1';
                    u_pc  <= u_pc + 1;
                    u_ph  <= (others => '0');
                else
                    u_ph <= u_ph + 1;
                    case to_integer(u_ph) is
                        when 0 => null;                                    -- ROM read of u_pc
                        when 1 => rf_ra <= '0' & unsigned(u_q(19 downto 13));
                        when 2 => rf_ra <= '0' & unsigned(u_q(12 downto 6));
                        when 3 => u_A <= rf_q;
                        when 4 => u_B <= rf_q;
                        when others =>
                            -- execute: set up the serial loop, or finish here
                            u_ph   <= (others => '0');
                            u_c    <= '0';
                            u_n    <= (others => '0');
                            u_t    <= (others => '0');
                            u_k    <= (others => '0');
                            u_ms   <= (others => '0');
                            u_mc   <= (others => '0');
                            u_bw   <= '0';
                            u_as   <= u_A(31);
                            u_wsa  <= '0';
                            u_sx   <= '0';
                            u_p2   <= '0';
                            u_seen <= '0';
                            u_hw   <= (others => '0');
                            case v_op is
                                when 1 =>                   u_busy <= '1';                         -- ADD
                                when 2 | 13 | 14 | 15 =>    u_busy <= '1'; u_c <= '1';             -- SUB NEG MIN MAX
                                when 3 =>                   u_wsa <= '1'; u_wb <= '1';             -- MOV
                                when 4 | 5 | 8 =>           u_busy <= '1'; u_k <= to_unsigned(v_x, 6);  -- SHL SHR MUL
                                when 6 | 7 =>               u_busy <= '1'; u_k <= unsigned(u_B(5 downto 0));
                                when 10 =>                  u_busy <= '1';                         -- NORM
                                when 11 =>                                                         -- TAB
                                    rf_ra  <= '1' & unsigned(u_A(6 downto 0));
                                    u_k    <= to_unsigned(1, 6);
                                    u_busy <= '1';
                                when 12 =>                                                         -- ABS
                                    if u_A(31) = '1' then u_busy <= '1'; u_c <= '1';
                                    else u_wsa <= '1'; u_wb <= '1'; end if;
                                when 17 | 18 | 19 | 20 =>                                          -- J JN JZ JP
                                    if v_op = 17 or (v_op = 18 and u_A(31) = '1') or (v_op = 19 and unsigned(u_A) = 0)
                                       or (v_op = 20 and u_A(31) = '0' and unsigned(u_A) /= 0) then
                                        u_pc <= unsigned(u_q(8 downto 0));
                                    else
                                        u_pc <= u_pc + 1;
                                    end if;
                                when 21 =>                                                         -- IN
                                    u_busy <= '1'; u_sx <= '1';
                                    case v_x is
                                        when 0      => u_aux <= "00" & registers_in(0);
                                        when 1      => u_aux <= "00" & registers_in(1);
                                        when 2      => u_aux <= "00" & registers_in(2);
                                        when 3      => u_aux <= "00" & registers_in(3);
                                        when 4      => u_aux <= "00" & registers_in(4);
                                        when 5      => u_aux <= "00" & registers_in(5);
                                        when 6      => u_aux <= "00" & registers_in(7);
                                        when 7      => u_aux <= std_logic_vector(s_W);
                                        when 8      => u_aux <= std_logic_vector(s_H);
                                        when 9      => u_aux <= std_logic_vector(resize(s_ls6m, 12));
                                        when 10     => u_aux <= (0 => s_lines, others => '0');
                                        when 11     => u_aux <= (0 => s_ink, others => '0');
                                        when 12     => u_aux <= (0 => s_fine, others => '0');
                                        when 13     => u_aux <= (0 => s_src, others => '0');
                                        when others => u_aux <= (0 => s_glide, others => '0');
                                    end case;
                                when 22 =>                                                         -- OUT
                                    case v_x is
                                        when 2  => w_mu1 <= signed(u_A(1 downto 0));
                                        when 3  => w_mu2 <= signed(u_A(1 downto 0));
                                        when 6  => w_g10 <= signed(u_A(9 downto 0));
                                        when 7  => w_hm <= unsigned(u_A(8 downto 0));
                                        when 8  => w_e <= unsigned(u_A(1 downto 0));
                                        when 9  => w_q1m <= unsigned(u_A(1 downto 0));
                                        when 10 => w_q2m <= unsigned(u_A(1 downto 0));
                                        when 11 => w_ro2 <= unsigned(u_A(16 downto 0));
                                        when 12 => w_hh4 <= unsigned(u_A(16 downto 0));
                                        when 13 => w_gs <= unsigned(u_A(11 downto 0));
                                        when 14 => w_t1 <= unsigned(u_A(9 downto 0));
                                        when 16 => w_ca <= signed(u_A(11 downto 0));
                                        when 18 => w_fa <= signed(u_A(11 downto 0));
                                        when 20 => w_ma <= unsigned(u_A(8 downto 0));
                                        when 22 => s_cxs <= signed(u_A(21 downto 0));
                                        when 23 => s_cys <= signed(u_A(21 downto 0));
                                        when 24 => w_dr2 <= unsigned(u_A(16 downto 0));
                                        when 25 => w_hk <= unsigned(u_A(2 downto 0));
                                        when others => null;
                                    end case;
                                    u_pc <= u_pc + 1;
                                when 23 =>                                                         -- STOP
                                    u_run <= '0';
                                when 24 =>                                                         -- CALL
                                    u_ret <= u_pc + 1;
                                    u_pc  <= unsigned(u_q(8 downto 0));
                                when 25 =>                                                         -- RET
                                    u_pc  <= u_ret;
                                when others =>                                                     -- NOP
                                    u_pc <= u_pc + 1;
                            end case;
                    end case;
                end if;
            end if;

            -- the field tick (after the engine: its restart wins)
            if data_in.vsync_n = '0' and s_prev_vsync = '1' and s_saw_avid = '1' then
                s_vs_pulse <= '1';
                s_saw_avid <= '0';
                s_glide <= registers_in(6)(0);            -- S7 Glide
                s_lines <= registers_in(6)(1);            -- S8 Form: Dots / Lines
                s_ink   <= registers_in(6)(2);            -- S9 Tone: Grey / Ink
                s_fine  <= registers_in(6)(3);            -- S10 Weight: Bold / Fine
                s_src   <= registers_in(6)(4);            -- S11 Source: Video / Osc
                s_Wl    <= s_W;
                u_run  <= '1';
                u_pc   <= (others => '0');
                u_ph   <= (others => '0');
                u_busy <= '0';
                u_wb   <= '0';
            end if;
        end if;
    end process p_frame;

    -- the register file (block RAM, one write, one registered read paused with the engine; the
    -- engine never reads the register it is writing in the same clock).  Write data: r, or a.
    rf_d <= u_A when u_wsa = '1' else u_R;
    p_rf : process(clk)
    begin
        if rising_edge(clk) then
            if u_en = '1' then rf_q <= rf(to_integer(rf_ra)); end if;
            if rf_we = '1' then rf(to_integer('0' & unsigned(u_q(26 downto 20)))) <= rf_d; end if;
        end if;
    end process p_rf;

    ------------------------------------------------------------------------
    -- coordinate accumulators on the GENERATED avid.  dx loads -cx at each
    -- line start and steps per pixel; dy seeds at the first line of the frame
    -- and steps per line by s_ystp (Q.8 x-pixel units, seeded +0.5).
    ------------------------------------------------------------------------
    p_acc : process(clk)
        variable v_dy0 : signed(22 downto 0);
    begin
        if rising_edge(clk) then
            s_gav_p <= g_avid;
            s_ls0 <= '0';
            lsp(1) <= s_ls0;
            if s_vs_pulse = '1' then
                s_newframe <= '1';
            elsif g_avid = '1' and s_gav_p = '0' then
                if s_newframe = '1' then
                    v_dy0 := shift_left(-resize(s_cys(21 downto 8), 23), 8);
                    v_dy0(7) := '1';                                   -- +0.5
                    s_dyc <= v_dy0(22 downto 8);
                    s_dyb <= v_dy0 + signed(resize(s_ystp, 23));
                    s_newframe <= '0';
                else
                    s_dyc <= s_dyb(22 downto 8);
                    s_dyb <= s_dyb + signed(resize(s_ystp, 23));
                end if;
                s_dx <= -resize(s_cxs(21 downto 8), 15);
                s_ls0 <= '1';
            else
                -- dx runs on past the line end (the last group's next lattice sample)
                s_dx <= s_dx + 1;
            end if;
        end if;
    end process p_acc;

    ------------------------------------------------------------------------
    -- EBR delay lines.  Write address = free-running counter; each read runs X behind it.
    ------------------------------------------------------------------------
    p_dl : process(clk)
    begin
        if rising_edge(clk) then
            s_wa <= s_wa + 1;
            dll(to_integer(s_wa)) <= "00000000" & std_logic_vector(s22_ls6) & std_logic_vector(s22_afa);
            dll_q  <= dll(to_integer(s_wa - C_XL));
            dly(to_integer(s_wa)) <= '0' & std_logic_vector(s26_lab) & std_logic_vector(s26_ya);
            dly_q  <= dly(to_integer(s_wa - 2));
            dls(to_integer(s_wa)) <= g_avid & data_in.hsync_n & data_in.vsync_n & data_in.field_n;
            dls_q  <= dls(to_integer(s_wa - C_XS));
        end if;
    end process p_dl;

    -- table ROMs (EBR): every address is a register, every read is registered
    p_csr : process(clk)
    begin
        if rising_edge(clk) then
            csr_q <= csr(to_integer("000000" & csr_ra));
            q_s   <= csr_q;
            if rf_we = '1' and u_q(26 downto 22) = "00000" then
                csr(to_integer("000000" & unsigned(u_q(21 downto 20)))) <= rf_d;
            end if;
        end if;
    end process p_csr;

    p_rom : process(clk)
    begin
        if rising_edge(clk) then
            lv_q  <= C_LOGV(to_integer(g4_i));
            ls_q  <= C_LOGS(to_integer(g4_i));
            ug_q  <= C_UG(to_integer(fu(17 downto 10)));
            ugs_q <= C_UGS(to_integer(fu(17 downto 10)));
            ua_q  <= C_UA(to_integer(fu(17 downto 10)));
            uas_q <= C_UAS(to_integer(fu(17 downto 10)));
            sqx_q  <= C_SQT(to_integer(s26_xa(12 downto 5)));
            sqy_q  <= C_SQT(to_integer(s26_ya(12 downto 5)));
        end if;
    end process p_rom;

    ------------------------------------------------------------------------
    -- THE FRONT, once per four pixels (only the lattice samples, pixel 0, 4, 8, ... of each line, need
    -- log2 r and theta): S1, S2 per pixel (|dx|, |dy| 13-bit, hi = max, lo = min); then ONE log2 unit
    -- takes hi and lo on two consecutive clocks (priority encode, normalise, 256-segment PWL from EBR,
    -- Q14), u = log2(hi / lo); ONE PWL lookup of g(u) = 0.5 log2(1 + 4^-u) and atan(2^-u) with one
    -- shared slope multiplier (two clocks); log2 r = log2 hi + g, theta from the octant.  (Hypnos)
    -- f2 = the sample phase at S2 (0: S2 holds a sample pixel); every hold register below is written at
    -- one phase and read within the next four clocks.  hL, hT, hls are written one clock before the
    -- lattice multiplier's phase 0 (the same timing as the per-pixel front's capture).
    ------------------------------------------------------------------------
    p_front : process(clk)
        variable va, vb : unsigned(14 downto 0);
        variable vx  : unsigned(12 downto 0);
        variable mh  : integer range 0 to 12;
        variable vu  : unsigned(17 downto 0);
        variable vmag, vth : unsigned(17 downto 0);
        variable vl  : signed(20 downto 0);
        variable vr  : unsigned(17 downto 0);
        variable q   : std_logic_vector(3 downto 0);
    begin
        if rising_edge(clk) then
            -- S1, S2 (per pixel)
            va := unsigned(abs(s_dx));
            vb := unsigned(abs(s_dyc));
            s1_a <= f_sat(va, 13);
            s1_b <= f_sat(vb, 13);
            s1_dxs <= s_dx(14);
            s1_dys <= s_dyc(14);
            if s1_a >= s1_b then s2_hi <= s1_a; s2_lo <= s1_b; s2_sw <= '0';
            else                 s2_hi <= s1_b; s2_lo <= s1_a; s2_sw <= '1'; end if;
            if s1_a = 0 or s1_b = 0 then s2_lz <= '1'; else s2_lz <= '0'; end if;
            s2_dxs <= s1_dxs;
            s2_dys <= s1_dys;
            if lsp(1) = '1' then f2 <= (others => '0'); else f2 <= f2 + 1; end if;
            -- G3: hi (f2 = 0), then the held lo
            if f2 = 0 then
                vx := s2_hi;
                lo_h <= s2_lo;
            else
                vx := lo_h;
            end if;
            if vx = 0 then vx := to_unsigned(1, 13); end if;
            mh := 0;
            for i in 0 to 12 loop
                if vx(i) = '1' then mh := i; end if;
            end loop;
            g3_v <= vx; g3_m <= to_unsigned(mh, 4);
            -- G4: normalise -> table index, 4-bit fraction
            vx := shift_left(g3_v, 12 - to_integer(g3_m));
            g4_i <= vx(11 downto 4); g4_t <= vx(3 downto 0); g4_m <= g3_m;
            -- G5: table read in flight ; G6: into fabric
            g5_t <= g4_t; g5_m <= g4_m;
            g6_lv <= lv_q; g6_ls <= ls_q; g6_t <= g5_t; g6_m <= g5_m;
            -- G7, G8: log2 = m + v + (s t) >> 4  (Q14)
            g7_lp <= resize(unsigned(g6_ls(6 downto 0)) * g6_t, 11);
            g7_lv <= unsigned(g6_lv(13 downto 0));
            g7_m  <= g6_m;
            g8_l  <= shift_left(resize(g7_m, 18), 14) + resize(g7_lv, 18) + resize(shift_right(g7_lp, 4), 18);
            -- the octant flags, held through the phases (written at f2 = 0)
            if f2 = 0 then
                fl_h <= s2_sw & s2_dxs & s2_dys & s2_lz;
                fl_1 <= fl_h; fl_2 <= fl_1; fl_3 <= fl_2;
            end if;
            -- log2 hi (f2 = 2), u = log2 hi - log2 lo (f2 = 3); the u table index addresses the EBR directly
            if f2 = 2 then
                lh9 <= g8_l;
                lhb <= lh9;
            end if;
            if f2 = 3 then
                vu := lh9 - g8_l;
                if fl_1(0) = '1' then vu := to_unsigned(16 * 16384 - 1, 18); end if;
                fu <= vu;
            end if;
            -- G12: table data into fabric (stable four clocks)
            g12_g <= ug_q; g12_gs <= ugs_q; g12_a <= ua_q; g12_as <= uas_q;
            g12_tu <= signed(resize(fu(9 downto 3), 8));
            -- the shared slope multiplier: g at f2 = 2, atan at f2 = 3
            if f2 = 2 then g13_p <= resize(bmul(signed(g12_gs(10 downto 0)), g12_tu), 22);
            else           g13_p <= resize(bmul(signed(g12_as(10 downto 0)), g12_tu), 22); end if;
            if f2 = 3 then
                g14_g <= resize(unsigned(signed(resize(unsigned(g12_g), 17)) + resize(shift_right(g13_p, 7), 17)), 14);
            end if;
            if f2 = 0 then
                g14_a <= resize(unsigned(signed(resize(unsigned(g12_a), 17)) + resize(shift_right(g13_p, 7), 17)), 16);
            end if;
            if f2 = 1 then
                -- the sample: log2 r (Q14) -> L (relative to the reference, Q13), the AA's log2 r, theta
                vr := lhb + resize(g14_g, 18);
                vl := signed(resize(vr, 21)) - resize(s_lref, 21);
                hL  <= vl(18 downto 1);
                hls <= vr(17 downto 8);
                q := fl_3;
                if q(3) = '1' then vmag := to_unsigned(65536, 18) - resize(g14_a, 18);
                else               vmag := resize(g14_a, 18); end if;
                if    q(2) = '0' and q(1) = '0' then vth := vmag;
                elsif q(2) = '1' and q(1) = '0' then vth := to_unsigned(131072, 18) - vmag;
                elsif q(2) = '1' and q(1) = '1' then vth := to_unsigned(131072, 18) + vmag;
                else                                 vth := to_unsigned(0, 18) - vmag; end if;
                hT <= signed('0' & vth);
            end if;
        end if;
    end process p_front;

    ------------------------------------------------------------------------
    -- S16..S29: the lattice forms, once per FOUR pixels (pixel index 0, 4, 8, ... of each line), on one
    -- shared multiplier, then interpolated per pixel.  a = lam1 L + mu1 T + oa, b = lam2 L + mu2 T + ob
    -- (Q18, mod 4; oa, ob carry the +1/2 of the rounding).  The four products of a sample run on four
    -- consecutive clocks (lam1 L, mu1 T, lam2 L, mu2 T).  Between two samples A, B the per-pixel value is
    -- A + m ((B - A) >> 2); where theta wrapped between them (|T_B - T_A| > 1/2 turn) the integer jump of
    -- mu T is taken out first, so the interpolation never crosses the seam (and the labels stay valid:
    -- a whole turn changes neither frac a, frac b nor k mod 4).  m15 = the pixel phase at S15.
    ------------------------------------------------------------------------
    p_samp : process(clk)
        variable vx  : signed(18 downto 0);
        variable vy  : signed(15 downto 0);
        variable vph : signed(26 downto 0);
        variable vpl : signed(27 downto 0);
        variable vp  : unsigned(19 downto 0);
        variable va2, vb2 : unsigned(1 downto 0);
        variable vda, vdb : signed(19 downto 0);
        variable vm  : unsigned(1 downto 0);
    begin
        if rising_edge(clk) then
            -- pixel phase at S15: the front's phase one clock later (13 clocks = 1 mod 4)
            m15 <= f2;
            -- (the sample hL / hT / hls is written by the front)
            -- M1 (phase k at S16 = m15 - 1): lam1 L, mu1 T, lam2 L, mu2 T
            vm := m15 - 1;
            case vm is
                when "00" | "10" => vx := resize(hL, 19);
                when others      => vx := hT;
            end case;
            vy := signed(q_s(31 downto 16));            -- lam1, mu1, lam2, mu2 (the word of this phase)
            csr_ra <= m15 + 2;
            vph := bmul(vx, vy(15 downto 8));
            vpl := bmul(vx, signed('0' & vy(7 downto 0)));
            m1_ph <= vph(23 downto 0);
            m1_pl <= vpl(23 downto 0);
            -- M2 (the product mod 2^24: L x lam (Q13 x Q9) -> Q18 at bit 4, T x mu -> Q18 at bit 0)
            m2_p <= shift_left(m1_ph, 8) + m1_pl;
            -- ACC (phase k at S18 = m15 - 3)
            vm := m15 - 3;
            if vm(0) = '0' then vp := unsigned(m2_p(23 downto 4)); else vp := unsigned(m2_p(19 downto 0)); end if;
            case vm is
                when "00"   => ac <= vp + shift_left(resize(unsigned(q_s(15 downto 0)), 20), 4);      -- oa (word lam2 | oa)
                when "01"   => an <= ac + vp; tn <= unsigned(hT(17 downto 16)); lsn <= hls;
                when "10"   => ac <= vp + shift_left(resize(unsigned(q_s(15 downto 0)), 20), 4);      -- ob (word lam1 | ob)
                when others =>
                    sa_a <= sb_a; sa_b <= sb_b; sa_t <= sb_t; sa_l <= sb_l;
                    sb_a <= an; sb_b <= ac + vp; sb_t <= tn; sb_l <= lsn;
            end case;
            -- S29: the per-pixel values (phase m at S29 = m15 - 14): a DDA from sample A in steps of
            -- (B - A) / 4, the seam taken out of the difference (theta wrapped between the two samples when
            -- its quadrant went 0 -> 3 or 3 -> 0: a whole turn = mu1, mu2 whole cells, mod 4)
            vm := m15 - 14;
            if vm = 0 then
                vda := signed(sb_a - sa_a);
                vdb := signed(sb_b - sa_b);
                va2 := unsigned(vda(19 downto 18)); vb2 := unsigned(vdb(19 downto 18));
                if sa_t = "00" and sb_t = "11" then
                    va2 := va2 - unsigned(w_mu1(1 downto 0)); vb2 := vb2 - unsigned(w_mu2(1 downto 0));
                elsif sa_t = "11" and sb_t = "00" then
                    va2 := va2 + unsigned(w_mu1(1 downto 0)); vb2 := vb2 + unsigned(w_mu2(1 downto 0));
                end if;
                vda(19 downto 18) := signed(va2);
                vdb(19 downto 18) := signed(vb2);
                s20_a  <= sa_a; s20_b <= sa_b; s20_ls <= sa_l;
                dd_a   <= shift_right(vda, 2); dd_b <= shift_right(vdb, 2);
                dd_l   <= shift_right(signed(resize(sb_l, 11)) - signed(resize(sa_l, 11)), 2);
            else
                s20_a  <= s20_a + unsigned(dd_a);
                s20_b  <= s20_b + unsigned(dd_b);
                s20_ls <= unsigned(signed(s20_ls) + resize(dd_l, 10));
            end if;
        end if;
    end process p_samp;

    ------------------------------------------------------------------------
    -- S22..S31: the nearest lattice point of row j: x = a + g fb (along w1), Y = h fb (across the
    -- rows), X = frac x; scaled by 2^-e (e: the dot size's octave pair), squared by a 256-entry table
    -- plus the cross term, d^2 = X^2 + Y^2; the label k mod 4 = i q1 + j q2.  The dot radius never
    -- exceeds half the row spacing (the engine and the camera swell are clamped to it), so the
    -- nearest dot that can cover a pixel is always in its own row.
    ------------------------------------------------------------------------
    p_near : process(clk)
        variable v12 : signed(11 downto 0);
        variable vfa, vfb : signed(17 downto 0);
        variable v17 : signed(16 downto 0);
        variable v19 : signed(18 downto 0);
        variable vX  : signed(17 downto 0);
        variable v2  : unsigned(3 downto 0);
        variable v18 : unsigned(17 downto 0);
    begin
        if rising_edge(clk) then
            -- S22: row j = round b, the fractions (bit 17 flipped: the +1/2 is in oa / ob);
            -- g fb (fb Q12, g Q9); fb >> (5 - k), saturated to 13 bits, for h fb
            vfb := signed((not s20_b(17)) & std_logic_vector(s20_b(16 downto 0)));
            vfa := signed((not s20_a(17)) & std_logic_vector(s20_a(16 downto 0)));
            v12 := vfb(17 downto 6);
            s22_gf <= bmul(v12, w_g10);
            v17 := shift_right(vfb(17 downto 1), 5 - to_integer(w_hk));
            if v17 > 4095 then s22_fbs <= to_signed(4095, 13);
            elsif v17 < -4095 then s22_fbs <= to_signed(-4095, 13);
            else s22_fbs <= resize(v17, 13); end if;
            v19 := abs(resize(vfa, 19));
            s22_afa <= unsigned(v19(17 downto 4));
            s22_ls6 <= s20_ls;
            s22_a <= s20_a; s22_jm <= s20_b(19 downto 18);
            -- S23: x = a + g fb (Q18) ; Y = (fb >> (5 - k)) hm (Q20 >> 8 = Q12 / 2^e)
            s23_x  <= s22_a + unsigned(resize(shift_right(s22_gf, 3), 20));
            s23_ys <= bmul(s22_fbs, signed('0' & w_hm));
            s23_jm <= s22_jm;
            -- S25 (no S24)
            vX := signed((not s23_x(17)) & std_logic_vector(s23_x(16 downto 0)));
            v19 := abs(resize(vX, 19));
            s25_ax <= unsigned(v19(17 downto 0));
            s25_ay <= unsigned(abs(resize(shift_right(s23_ys, 8), 15)));
            s25_im <= s23_x(19 downto 18);
            s25_jm <= s23_jm;
            -- S26
            s26_xa <= resize(shift_right(s25_ax, 6 + to_integer(w_e)), 13);
            s26_ya <= f_sat(s25_ay, 13);
            v2 := (s25_im * w_q1m) + (s25_jm * w_q2m);
            s26_lab <= v2(1 downto 0);
            -- S27 (table reads in flight): cross terms
            s27_cx <= f_cross(s26_xa); s27_cy <= f_cross(s26_ya);
            -- S28: table data into fabric
            s28_qx <= unsigned(sqx_q); s28_qy <= unsigned(sqy_q);
            s28_cx <= s27_cx; s28_cy <= s27_cy;
            -- S29: v^2 / 1024 = T(v >> 5) + ((v >> 5) (v & 31)) >> 4
            s29_sx <= resize(s28_qx, 17) + resize(shift_right(s28_cx, 4), 17);
            s29_sy <= resize(s28_qy, 17) + resize(shift_right(s28_cy, 4), 17);
            -- S30: d^2 ; the dot radius^2 (or the ring's mid radius^2) swollen by the camera, at most the
            -- half row spacing ; lines: the w2-family distance in w1 units, the half-width widened by it
            s30_dsq <= resize(s29_sx, 18) + resize(s29_sy, 18);
            v18 := resize(w_ro2, 18) + resize(s_cs, 18);
            if v18 > resize(w_hh4, 18) then s30_ro <= w_hh4; else s30_ro <= v18(16 downto 0); end if;
            s30_d2 <= resize(shift_right(shift_left(resize(unsigned(dll_q(13 downto 0)), 17), to_integer(w_e)), 2), 16);
            s30_ls6 <= unsigned(dll_q(23 downto 14));
            s30_ya <= unsigned(dly_q(12 downto 0));
            labsr(30) <= unsigned(dly_q(14 downto 13));
            for i in 31 to 35 loop labsr(i) <= labsr(i - 1); end loop;
            -- S31: dots: d^2 - R^2 ; lines: the nearer family's distance
            if s_lines = '1' then
                if s30_d2 < resize(s30_ya, 16) then s31_p <= signed(resize(s30_d2, 20)); famsr(31) <= '1';
                else s31_p <= signed(resize(s30_ya, 20)); famsr(31) <= '0'; end if;
            else
                s31_p <= signed(resize(s30_dsq, 20)) - signed(resize(s30_ro, 20));
                famsr(31) <= '0';
            end if;
            for i in 32 to 35 loop famsr(i) <= famsr(i - 1); end loop;
            s31_t1 <= resize(w_t1, 16) + resize(s_cs, 16);
            s31_ls6 <= s30_ls6;
        end if;
    end process p_near;

    ------------------------------------------------------------------------
    -- S32..S39: one one-pixel AA ramp, cov = clamp(1/2 - v * 2^sigma) (sigma = log2 r + C in half
    -- octaves; the half step is x 1.5), faded to its mean where the detail gets under ~2 px; tone.
    --   Dots:  v = d^2 - R^2 (Bold) or |d^2 - Rm^2| - band (Fine: an outline of constant area).
    --          Grey: x (k mod 4 + 1) / 4.  Ink: white.
    --   Lines: v = min(distance to the w1 lines, to the w2 lines) - half-width.
    --          Grey: the w2 family white over the w1 family at half grey.  Ink: white.
    ------------------------------------------------------------------------
    p_aa : process(clk)
        variable v_ls  : signed(11 downto 0);
        variable v_k2  : signed(6 downto 0);
        variable v_k   : signed(6 downto 0);
        variable v_rs  : signed(7 downto 0);
        variable v_f   : signed(11 downto 0);
        variable v28   : signed(27 downto 0);
        variable v_c   : unsigned(8 downto 0);
        variable v14   : unsigned(13 downto 0);
        variable v20   : signed(19 downto 0);
        variable v16   : signed(15 downto 0);
        variable v13   : signed(12 downto 0);
    begin
        if rising_edge(clk) then
            -- S32: v ; sigma ; the fade
            v_ls := signed(resize(s31_ls6, 12));
            if s_lines = '1' then
                s32_v <= s31_p - signed(resize(s31_t1, 20));
            elsif s_fine = '1' then
                v20 := abs(s31_p);
                s32_v <= v20 - signed(resize(w_dr2, 20));
            else
                s32_v <= s31_p;
            end if;
            s32_sg <= v_ls + w_ca;
            s32_fd <= v_ls + w_fa;
            -- S33: shift (7 - k) and the half-octave step; the fade
            v_k2 := resize(shift_right(s32_sg, 5), 7);
            if s32_sg > 30 * 32 + 31 then v_k2 := to_signed(30, 7);
            elsif s32_sg < -30 * 32 then v_k2 := to_signed(-30, 7); end if;
            v_k := shift_right(v_k2, 1);
            v_rs := to_signed(7, 8) - resize(v_k, 8);
            if v_rs < 0 then v_rs := (others => '0'); elsif v_rs > 27 then v_rs := to_signed(27, 8); end if;
            s33_rs <= unsigned(v_rs(4 downto 0));
            -- x 1.5 (|v| < 2^18: the sign is v's; the top bit is not added, no self-add LUT)
            if v_k2(0) = '1' then
                v20 := resize(s32_v(18 downto 0), 20) + resize(s32_v(19 downto 1), 20);
                v20(19) := s32_v(19);
                s33_vm <= v20;
            else
                s33_vm <= s32_v;
            end if;
            v_f := shift_right(s32_fd, 2);
            if v_f < 0 then s33_f <= (others => '0');
            elsif v_f > 16 then s33_f <= to_unsigned(16, 5);
            else s33_f <= unsigned(v_f(4 downto 0)); end if;
            -- S34: t = (vm << 7) >> rs in two steps: the coarse shift (4 rs(4:2)) saturated to 13 bits
            -- (the fine shift is <= 3, so |t| >= 128 is still decided), then the fine shift (rs(1:0))
            v28 := shift_left(resize(s33_vm, 28), 7);
            v28 := shift_right(v28, 4 * to_integer(s33_rs(4 downto 2)));
            if v28 > 4095 then s34_u <= to_signed(4095, 13);
            elsif v28 < -4095 then s34_u <= to_signed(-4095, 13);
            else s34_u <= v28(12 downto 0); end if;
            s34_fs <= s33_rs(1 downto 0);
            s34_f <= s33_f;
            -- S35: cov = clamp(128 - t, 0, 256)
            v13 := shift_right(s34_u, to_integer(s34_fs));
            if v13 >= 128 then s35_c <= (others => '0');
            elsif v13 <= -128 then s35_c <= to_unsigned(256, 9);
            else v13 := to_signed(128, 13) - v13; s35_c <= unsigned(v13(8 downto 0)); end if;
            s35_f <= s34_f;
            -- S36: Grey: the label's grey (dots: (k mod 4 + 1) / 4 ; lines: the w1 family at 1/2)
            v_c := s35_c;
            s36_c <= v_c;
            if s_ink = '0' then
                if s_lines = '1' then
                    if famsr(35) = '0' then s36_c <= shift_right(v_c, 1); end if;
                else
                    case labsr(35) is
                        when "00"   => s36_c <= shift_right(v_c, 2);
                        when "01"   => s36_c <= shift_right(v_c, 1);
                        when "10"   => v14 := resize(v_c, 14) + resize(shift_left(resize(v_c, 10), 1), 14);
                                       s36_c <= v14(10 downto 2);
                        when others => null;
                    end case;
                end if;
            end if;
            s36_f <= s35_f;
            -- S37..S39: fade to the mean, tone = m + ((c - m) * f) >> 4
            s37_d <= signed('0' & s36_c) - signed('0' & w_ma);
            s37_f <= s36_f;
            s38_p <= bmul(s37_d, signed('0' & s37_f));
            v16 := resize(signed('0' & w_ma), 16) + shift_right(s38_p, 4);
            s39_mix <= unsigned(v16(8 downto 0));           -- 0 .. 256 (a slice: resize would fold 256 to 0)
        end if;
    end process p_aa;

    ------------------------------------------------------------------------
    -- S40..S44: luma [1 2 1] / 4 with replicated picture edges, 13/16 toward black (white 776),
    -- blanking gate on the generated, aligned avid.  U = V = 512 always.
    ------------------------------------------------------------------------
    p_out : process(clk)
        variable vl, vr : unsigned(8 downto 0);
        variable vf  : unsigned(20 downto 0);
    begin
        if rising_edge(clk) then
            s40_m <= s39_mix; s41_m <= s40_m; s42_m <= s41_m;
            s_sy41 <= dls_q; s_sy42 <= s_sy41; s_sy43 <= s_sy42; s_sy44 <= s_sy43;
            if dls_q(3) = '1' then vr := s40_m; else vr := s41_m; end if;
            if s_sy42(3) = '1' then vl := s42_m; else vl := s41_m; end if;
            s42_f <= resize(vl, 11) + shift_left(resize(s41_m, 11), 1) + resize(vr, 11);
            -- S43: Y = 64 + f * 712 / 1024
            vf := shift_left(resize(s42_f, 21), 9) + shift_left(resize(s42_f, 21), 7)
                  + shift_left(resize(s42_f, 21), 6) + shift_left(resize(s42_f, 21), 3);
            s43_y <= to_unsigned(64, 10) + vf(19 downto 10);
            -- S44: blanking gate
            if s_sy43(3) = '1' then o_y <= s43_y; else o_y <= to_unsigned(64, 10); end if;
        end if;
    end process p_out;

    ------------------------------------------------------------------------
    -- SOURCE FIELD: camera luma, or the Osc lattice (640 x 540 virtual px triangles, only the peaks:
    -- islands, drifting) -> box means over blocks of 64 px (1080) / 32 px (otherwise) -> a vertical IIR
    -- per block (block RAM, q += (box - q) >> ksh, read at the block start, written at its end) ->
    -- linear interpolation between neighbouring blocks (a DDA, exact at every block start) -> * the
    -- per-field gain (K6 and the dot size): it swells the dots (their area) or widens the lines.
    -- Free-running, tapped shallow.  Black input = 0 = the clean figure.
    ------------------------------------------------------------------------
    p_irram : process(clk)
    begin
        if rising_edge(clk) then
            ir_q <= ir_ram(to_integer(ir_ra));
            if ir_we = '1' then ir_ram(to_integer(ir_wa)) <= ir_wd; end if;
        end if;
    end process p_irram;

    p_src : process(clk)
        variable v_l   : unsigned(7 downto 0);
        variable v_ox, v_oy : unsigned(7 downto 0);
        variable v_pos : unsigned(5 downto 0);
        variable v_blk : unsigned(5 downto 0);
        variable v_d   : signed(15 downto 0);
        variable v_st  : signed(15 downto 0);
        variable v_c   : unsigned(19 downto 0);
    begin
        if rising_edge(clk) then
            -- oscillator: two triangle waves (512 virtual px) from the pixel and line counters, drifting
            if s_vs_pulse = '1' then s_ot <= s_ot + 1; end if;
            if s_mcls = "10" then v_ox := s_xcnt(7 downto 0) + s_ot; v_oy := s_lacc(15 downto 8) + s_ot;
            else                  v_ox := s_xcnt(8 downto 1) + s_ot; v_oy := s_lacc(16 downto 9) + s_ot; end if;
            s_osum <= resize(f_tri7(v_ox), 8) + resize(f_tri7(v_oy), 8);

            -- the source sample: (luma >> 2) - 16, or the lattice's peaks ((sum - 127) * 2)
            v_l := unsigned(data_in.y(9 downto 2));
            if s_src = '1' then
                if s_osum(7) = '1' then s_sl <= shift_left(resize(s_osum(6 downto 0), 8) + 1, 1);
                else                    s_sl <= (others => '0'); end if;
            elsif v_l > 16 then s_sl <= v_l - 16;
            else s_sl <= (others => '0'); end if;
            s_sv <= data_in.avid;
            if s_sv = '1' then s_col <= s_col + 1; else s_col <= (others => '0'); end if;

            -- the block of this sample and the position in it
            if s_mcls = "00" then v_pos := s_col(5 downto 0);          v_blk := '0' & s_col(10 downto 6);
            else                  v_pos := '0' & s_col(4 downto 0);    v_blk := s_col(10 downto 5); end if;
            -- block start: read its IIR state; block end: the box sum
            ir_ra <= v_blk;
            b_st(0) <= s_sv and to_std(v_pos = 0);
            b_st(1) <= b_st(0); b_st(2) <= b_st(1); b_st(3) <= b_st(2);
            b_z(0)  <= to_std(v_blk = 0); b_z(1) <= b_z(0); b_z(2) <= b_z(1);
            if v_pos = 0 then s_bacc <= resize(s_sl, 14); else s_bacc <= s_bacc + resize(s_sl, 14); end if;
            if s_sv = '1' and ((s_mcls = "00" and v_pos = 63) or (s_mcls /= "00" and v_pos(4 downto 0) = 31)) then
                b_e(0) <= '1';
            else
                b_e(0) <= '0';
            end if;
            b_wa(0) <= v_blk;
            b_sum <= s_bacc + resize(s_sl, 14);
            b_e(1) <= b_e(0); b_e(2) <= b_e(1); b_wa(1) <= b_wa(0); b_wa(2) <= b_wa(1);
            -- the state into fabric (two clocks after the block start); the neighbours of the DDA
            ir_qr <= ir_q(12 downto 0);
            if b_st(2) = '1' then
                s_sb <= ir_qr;
                if b_z(2) = '1' then s_sa <= ir_qr; else s_sa <= s_sb; end if;
            end if;
            -- the IIR update (box Q4 * 2 vs the state Q5), written at the block end + 2
            if s_mcls = "00" then b_bx <= b_sum(13 downto 2); else b_bx <= b_sum(12 downto 1); end if;
            v_d := signed(resize(b_bx & '0', 16)) - signed(resize(s_sb, 16));
            case s_ksh is
                when "011"  => v_st := shift_right(v_d, 3);
                when "100"  => v_st := shift_right(v_d, 4);
                when others => v_st := shift_right(v_d, 5);
            end case;
            v_d := signed(resize(s_sb, 16)) + v_st;
            ir_wd <= "000" & unsigned(v_d(12 downto 0));
            ir_we <= b_e(1); ir_wa <= b_wa(1);
            -- the DDA from the left neighbour to this block (Q11; 64 steps at 1080, 32 otherwise)
            if b_st(3) = '1' then
                s_vacc <= shift_left(resize(s_sa, 19), 6);
                if s_mcls = "00" then s_vstp <= signed(resize(s_sb, 20)) - signed(resize(s_sa, 20));
                else s_vstp <= shift_left(signed(resize(s_sb, 20)) - signed(resize(s_sa, 20)), 1); end if;
            else
                s_vacc <= unsigned(signed(s_vacc) + resize(s_vstp, 19));
            end if;
            -- * K6 gain
            v_c := s_vacc(18 downto 11) * w_gs;
            s_cs <= resize(v_c(19 downto 5), 15);
        end if;
    end process p_src;

    data_out.y       <= std_logic_vector(o_y);
    data_out.u       <= std_logic_vector(C_MID);
    data_out.v       <= std_logic_vector(C_MID);
    data_out.avid    <= s_sy44(3);
    data_out.hsync_n <= s_sy44(2);
    data_out.vsync_n <= s_sy44(1);
    data_out.field_n <= s_sy44(0);

end architecture phyllo;
