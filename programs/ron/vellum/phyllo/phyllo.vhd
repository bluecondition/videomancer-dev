    -- registers in block RAM (constants, the persistent basis / drift / centre / glided knobs, the exp2
    -- table at 128 .. 255), 3-address code (op d a b x), a BIT-SERIAL datapath: a and b are shift
    -- registers loaded from the register file, the result is shifted into r LSB first and written back
    -- in one clock (MOV, TAB, ABS of a positive value write a back directly).  MUL is a serial-parallel
    -- multiplier (b in parallel, a streamed LSB first and sign-extended, the 2^32 a correction for a
    -- negative b), NORM scans for the msb, SHR skips k bits first.  It runs in blanking only (every
    -- engine register, the ROM and the register-file reads pause together while avid is high) and stops
    -- itself; its OUTs are the per-pixel constants.
    --   per field: the knob glides, alpha (P12), E (K3), the Gram matrix of the stored basis, the
