-- phyllo.vhd  (Vellum set, v0.1.0 -- phyllotaxis: dots on a log-polar Vogel lattice, a sunflower head)
--
-- Black, white and greys only (U = V = 512 on every pixel).  Polar chassis = Hypnos v1.1.0 (timing, generated
-- avid, centre glide, the log-domain polar engine) with a Kinetic / Hardline style source field.  In
-- (Lc, T) = (log2 r * ln2 / 2pi, theta / 2pi) the map is conformal and the Vogel lattice is generated by
-- (Ec, alpha) and (0, 1): point k sits at log2 r = k * E, theta = k * alpha turns.  Its dots are circles
-- whose size grows with r, arranged on two families of exponential spirals.
--
--   per field   a microcoded BIT-SERIAL engine (program + bit-exact model: ucode.py in the work folder):
--               the knob glides, alpha (P12), E (K3), the REDUCED basis w1 = (q1, p1), w2 = (q2, p2) of the
--               lattice (Lagrange-Gauss with Gram updates), the linear forms a = lam1 L + mu1 T + oa,
--               b = lam2 L + mu2 T + ob whose theta coefficients are the INTEGERS +-q (a seamless wrap),
--               g = w1.w2 / |w1|^2 and h = area / |w1|^2 (Newton reciprocal), the drift offsets (mod 4),
--               the dot radius, the AA / fade constants, the centre glide
--   front       log2 r, theta (Hypnos tables) once per FOUR pixels: one log2 unit (hi, lo on two clocks),
--               one slope multiplier (g, atan on two clocks)
--   samples     a, b, log2 r at pixels 0, 4, 8, ...: one shared multiplier (four products per sample, the
--               constants from a block-RAM copy of four engine registers)
--   per pixel   a DDA between the samples (the theta seam taken out of the step), j = round b, the
--               nearest point of row j: x = a + g fb, X = frac x, Y = h fb (fb shifted by h's exponent),
--               d^2 = X^2 + Y^2 (squares by table + cross term), the label k mod 4 = i q1 + j q2; one
--               one-pixel AA ramp (dots: d^2 - R^2, Fine: the ring; lines: the nearer lattice line), the
--               scale 2^(log2 r + C) in half octaves (two-step shift); Grey dots in four greys by k mod 4 /
--               Ink white; fade to the mean grey where the detail falls under ~2 px; the camera (box means
--               per block, a per-block vertical IIR, interpolated) swells R^2 / widens the lines
--   output      luma [1 2 1] / 4, 13/16 toward black (white 776), blanking gate
--
-- Author: czartroniks

