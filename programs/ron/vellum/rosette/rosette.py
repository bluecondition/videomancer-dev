"""
ROSETTE v0.1.0 (Vellum) - build hook.  Writes rosette_pkg.vhd next to this file (pure python: the builder runs
it with the system python3).  The integer model (.vellum_work/rb_rosette/imodel.py) builds the same tables.

Package contents:
  C_RS_TAB   512 x 16   0 .. 255:   round(32768 * 2^(i/256))          (pitch and drift speed are exponential)
                        256 .. 511: round(32768 * sin(i * pi / 512))  (a quarter wave for the screen angles; the
                                                                        sequencer interpolates it)
  C_RS_ISQ   64 x 6     round(4096 / sqrt((i + 1/2) * 256)), 32 .. 63  (1 / 2r from a normalised r^2)
  C_RS_TONE  256 x 10   [ink * 128 + two * 64 + S] -> luma code (S = summed dot coverage, 16 per screen):
                        Grey Three: 0 / 0.40 / 0.72 / 1 by screens covered, Grey Two: 0 / 0.55 / 1,
                        Ink: the triangle of S / 16 modulo 2 (anti-aliased XOR); Y = 64 + 876 tone
"""
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))

LV3 = (0.0, 0.40, 0.72, 1.0)
LV2 = (0.0, 0.55, 1.0)


def exp_rom():
    return [int(round(32768 * 2 ** (i / 256.0))) for i in range(256)]


def sin_rom():
    return [int(round(32768 * math.sin(i * math.pi / 512.0))) for i in range(256)]


def invsq_rom():
    out = []
    for i in range(64):
        if i < 16:
            out.append(63)
        else:
            out.append(min(63, max(32, int(round(4096.0 / math.sqrt((i + 0.5) * 256))))))
    return out


def tone_rom():
    out = []
    for ink in (0, 1):
        for two in (0, 1):
            for S in range(64):
                n = 2 if two else 3
                s = min(S, 16 * n) / 16.0
                if ink:
                    m = s % 2.0
                    t = m if m <= 1 else 2 - m
                else:
                    lv = LV2 if two else LV3
                    i = min(int(s), n - 1)
                    f = s - i
                    t = lv[i] + (lv[i + 1] - lv[i]) * f
                out.append(64 + int(round(t * 876)))
    return out


def vhd_table(name, typ, depth, width, vals):
    lines = ["    type %s is array (0 to %d) of %s(%d downto 0);" % ("t_" + name.lower(), depth - 1, typ, width - 1),
             "    constant %s : %s := (" % (name, "t_" + name.lower())]
    items = ['to_unsigned(%d, %d)' % (v, width) for v in vals]
    for i in range(0, len(items), 8):
        lines.append("        " + ", ".join(items[i:i + 8]) + ("," if i + 8 < len(items) else ""))
    lines.append("    );")
    return "\n".join(lines)


def main():
    parts = ["-- Generated by rosette.py -- DO NOT EDIT.",
             "library ieee;", "use ieee.std_logic_1164.all;", "use ieee.numeric_std.all;", "",
             "package rosette_pkg is",
             vhd_table("C_RS_TAB", "unsigned", 512, 16, exp_rom() + sin_rom()),
             vhd_table("C_RS_ISQ", "unsigned", 64, 6, invsq_rom()),
             vhd_table("C_RS_TONE", "unsigned", 256, 10, tone_rom()),
             "end package rosette_pkg;", ""]
    with open(os.path.join(HERE, "rosette_pkg.vhd"), "w") as f:
        f.write("\n".join(parts))


if __name__ == "__main__":
    main()
