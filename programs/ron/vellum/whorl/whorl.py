#!/usr/bin/env python3
"""whorl.py: build hook.  Writes whorl_pkg.vhd with the polygon table.

The polygon's log polar factor  P_N(v) = log2 cos(pi/N) - log2 cos(v pi/N)  (<= 0), v = |2u - 1| in [0, 1]
the folded position inside one of the N sectors (v = 0 mid-side, v = 1 corner).  Five N (3 4 5 6 8), 64
segments each, address = N index * 64 + segment (indices 5..7 repeat N = 8):
  C_PV : P at the segment start, Q14 (signed 16 bit)
  C_PS : slope (P at the segment end - P at its start, Q14, 10 bit) & tan(a) at the segment middle (Q5, 6 bit),
         a = v pi / N the angle from the side's middle (the anti-aliasing gradient)
  C_WH : half the filter width w / 2 (Q16) by (ri, rh): w = 2^-(ri + rh / 2) cycles per pixel (Hypnos's
         {64, 91} << (Iw + 10)); C_HF : the Fine line's half width clamp(w, 1/12, 1/4) (Q16)
  C_FX, C_FY : the tone with its fade folded in, by (case, fade c = 0 .. 15): tone = X + Y * coverage / 256,
         X = M + c/15 (Ta - M), Y = c/15 (Tb - Ta).  case 0..7 Grey Bold (k, up: the band's step Tb against
         the neighbour's Ta), 8..11 Grey Fine (k: the line's step over black), 12 Ink (white over black);
         M = the flat grey (128; Grey Fine 64)
"""
import math, os

NS = [3, 4, 5, 6, 8, 8, 8, 8]


def P(N, v):
    return math.log2(math.cos(math.pi / N)) - math.log2(math.cos(v * math.pi / N))


def tables():
    pv, ps = [], []
    for N in NS:
        for j in range(64):
            a = int(round(16384 * P(N, j / 64)))
            b = int(round(16384 * P(N, (j + 1) / 64)))
            s = b - a
            t = int(round(32 * math.tan((j + 0.5) / 64 * math.pi / N)))
            assert 0 <= s < 1024 and 0 <= t < 64 and -32768 <= a <= 0
            pv.append(a)
            ps.append((s << 6) | t)
    return pv, ps


def wh_tables():
    wh, hf = [], []
    for i in range(32):
        ri, rh = i >> 1, i & 1
        v = -(64 * ri + 32 * rh)                       # the quantised log2 w, Q6
        iw, h = v >> 6, (v >> 5) & 1
        vsh = iw + 10
        vm = 91 if h else 64
        w = (vm << vsh) & 0xFFFF if vsh >= 0 else vm >> -vsh
        w = max(w, 1)
        if i == 0: w = 65535                           # ri = rh = 0: w >= 1 cycle (saturated)
        wh.append(w >> 1)
        hf.append(min(max(w, 5461), 16384))
    return wh, hf


TG = [0, 85, 171, 256]


def tone_case(c):
    if c < 8:
        k, up = c >> 1, c & 1
        return TG[(k + 1) & 3] if up else TG[(k - 1) & 3], TG[k], 128
    if c < 12:
        return 0, TG[c - 8], 64
    return 0, 256, 128


def fade_tables():
    fx, fy = [], []
    for i in range(256):
        ta, tb, M = tone_case(i >> 4)
        f = (i & 15) / 15.0
        fx.append(int(round(M + f * (ta - M))))
        fy.append(int(round(f * (tb - ta))))
    return fx, fy


def main():
    pv, ps = tables()
    wh, hf = wh_tables()
    fx, fy = fade_tables()
    here = os.path.dirname(os.path.abspath(__file__))
    L = ["-- generated by whorl.py (do not edit): the polygon table of WHORL", "library ieee;",
         "use ieee.std_logic_1164.all;", "use ieee.numeric_std.all;", "", "package whorl_pkg is",
         "    type t_rom512 is array(0 to 511) of std_logic_vector(15 downto 0);"]
    for name, vals in (("C_PV", pv), ("C_PS", ps)):
        L.append("    constant %s : t_rom512 := (" % name)
        items = ['x"%04X"' % (v & 0xFFFF) for v in vals]
        for i in range(0, len(items), 8):
            L.append("        " + ", ".join(items[i:i + 8]) + ("," if i + 8 < len(items) else ");"))
    L.append("    type t_w32 is array(0 to 31) of unsigned(15 downto 0);")
    for name, vals in (("C_WH", wh), ("C_HF", hf)):
        L.append("    constant %s : t_w32 := (" % name)
        items = ['x"%04X"' % v for v in vals]
        for i in range(0, 32, 8):
            L.append("        " + ", ".join(items[i:i + 8]) + ("," if i + 8 < 32 else ");"))
    L.append("    type t_f256 is array(0 to 255) of std_logic_vector(15 downto 0);")
    for name, vals in (("C_FX", fx), ("C_FY", fy)):
        L.append("    constant %s : t_f256 := (" % name)
        items = ['x"%04X"' % (v & 0xFFFF) for v in vals]
        for i in range(0, 256, 8):
            L.append("        " + ", ".join(items[i:i + 8]) + ("," if i + 8 < 256 else ");"))
    L += ["end package whorl_pkg;", ""]
    open(os.path.join(here, "whorl_pkg.vhd"), "w").write("\n".join(L))


if __name__ == "__main__":
    main()
