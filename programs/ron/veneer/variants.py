#!/usr/bin/env python3
"""Stamp the two VENEER builds (VHDL + TOML) from the master in this directory.

    veneer      T: Ink / Texture fill (S7), eight texture sets, no line layers
    veneer_ink  I: flat ink fill with three independent line layers (Outline, Sketch, Contour)

Only the C_* build constants differ between the VHDL copies; both TOMLs are generated here.
Edit the master (veneer.vhd, tables.py, this file), never the stamped copy, then run:
    python3 tables.py && python3 variants.py
"""
import os, pathlib, re, sys

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import tables

VARIANTS = {
    "veneer":     dict(C_VARIANT='"T"', C_HAS_OUTLINE="false", C_HAS_SKETCH="false", C_HAS_CANNY="false", C_HAS_TEX="true"),
    "veneer_ink": dict(C_VARIANT='"I"', C_HAS_OUTLINE="true", C_HAS_SKETCH="true", C_HAS_CANNY="true", C_HAS_TEX="false"),
}
VERSION = "0.1.0"
SETS = tables.SET_NAMES
LEV = {2: 73, 3: 219, 4: 365, 5: 512, 6: 658, 7: 804, 8: 950}          # P12 zone centres
Z8 = lambda i: 64 + 128 * i                                             # 8-zone knob centres
Z4 = lambda i: 128 + 256 * i

def stepped(pid, name, labels, default):
    return (f'[[parameter]]\nparameter_id = "{pid}"\nname_label = "{name}"\n'
            f'value_labels = [{", ".join(chr(34) + l + chr(34) for l in labels)}]\ninitial_value_label = "{default}"\n')

def linear(pid, name, initial, lo=0, hi=100, suffix="%"):
    return (f'[[parameter]]\nparameter_id = "{pid}"\nname_label = "{name}"\ncontrol_mode = "linear"\n'
            f'display_min_value = {lo}\ndisplay_max_value = {hi}\ninitial_value = {initial}\ndisplay_float_digits = 0\n'
            f'suffix_label = "{suffix}"\n')

def preset(name, k, s, p12):
    assert len(name) <= 15, name
    lines = [f'[[preset]]\nname = "{name}"']
    lines += [f'rotary_potentiometer_{i + 1} = {v}' for i, v in enumerate(k)]
    lines += [f'toggle_switch_{i + 7} = {v}' for i, v in enumerate(s)]
    lines.append(f'linear_potentiometer_12 = {p12}\n')
    return "\n".join(lines)

def header(pid, name, cats, desc, note):
    assert len(desc.encode()) <= 127, len(desc.encode())
    return (f'{note}\n\n[program]\nprocessing_delay_clks = 84\nprogram_id = "com.czartroniks.{pid}"\n'
            f'program_name = "{name}"\nprogram_version = "{VERSION}"\nabi_version = ">=1.0,<2.0"\nauthor = "czartroniks"\n'
            f'license = "GPL-3.0"\ncategories = [{", ".join(chr(34) + c + chr(34) for c in cats)}]\nprogram_type = "processing"\n'
            f'description = "{desc}"\nhardware_compatibility = ["rev_b"]\ncore = "yuv444_30b"\n')

