def write_if_changed(path, text):
    if path.exists() and path.read_text() == text: return
    tmp = path.with_suffix(path.suffix + ".tmp"); tmp.write_text(text); os.replace(tmp, path)

def stamp_vhd(src, name, cfg):
    out = src
    for k, v in cfg.items():
        pat = re.compile(r"^(\s*constant\s+%s\s*:\s*\w+\s*:=\s*)[^;]+;" % k, re.M)
        out, n = pat.subn(lambda m: m.group(1) + v + ";", out)
        if n != 1: sys.exit(f"{name}: constant {k} matched {n} times")
    if name != "veneer":
        out = out.replace("-- VENEER -- re-renders video",
                          f"-- {name.upper()} -- STAMPED COPY of programs/ron/veneer/veneer.vhd (variants.py);\n-- edit the master, not this file.\n-- VENEER -- re-renders video", 1)
    return out

def main():
    vhd = (HERE / "veneer.vhd").read_text()
    for name, cfg in VARIANTS.items():
        d = HERE.parent / name; d.mkdir(exist_ok=True)
        write_if_changed(d / f"{name}.vhd", stamp_vhd(vhd, name, cfg))
        write_if_changed(d / f"{name}.toml", toml_veneer() if name == "veneer" else toml_ink())
        print("stamped", name)

if __name__ == "__main__":
    main()
