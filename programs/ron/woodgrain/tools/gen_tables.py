"""
WOODGRAIN - emits ../woodgrain_consts_pkg.vhd:
  C_WG_DECODE  256 x 32  6502 decode ROM for woodgrain_cpu.vhd (fields below)
  C_WG_PAL     128 x 30  NTSC TIA palette (Stella's measured RGB) as 10-bit Y/U/V,
                      hardware convention (u carries Cr, v carries Cb), Y = 64 + 876 y
Decode word: md[3:0] acc[5:4] aop[10:6] asel[12:11] bsel[15:13] dst[18:16]
             rop[21:19] wsel[23:22] spec[27:24] fl[30:28]
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from isa6502 import OPS, READ_OPS, WRITE_OPS, RMW_OPS  # noqa: E402

MD = {'imp': 0, 'acc': 1, 'imm': 2, 'zp': 3, 'zpx': 4, 'zpy': 5, 'abs': 6, 'abx': 7,
      'aby': 8, 'izx': 9, 'izy': 10, 'rel': 11}
AOP = {'NONE': 0, 'LD': 1, 'ORA': 2, 'AND': 3, 'EOR': 4, 'ADC': 5, 'SBC': 6, 'CMP': 7,
       'BIT': 8, 'INC': 9, 'DEC': 10, 'ASL': 11, 'LSR': 12, 'ROL': 13, 'ROR': 14,
       'ANC': 15, 'ALR': 16, 'ARR': 17, 'SBX': 18}
ASEL = {'A': 0, 'X': 1, 'Y': 2, 'AX': 3}
BSEL = {'DIN': 0, 'A': 1, 'X': 2, 'Y': 3, 'S': 4}
DST = {'-': 0, 'A': 1, 'X': 2, 'Y': 3, 'AX': 4}
ROP = {'ASL': 0, 'SLO': 0, 'ROL': 1, 'RLA': 1, 'LSR': 2, 'SRE': 2, 'ROR': 3, 'RRA': 3,
       'INC': 4, 'ISB': 4, 'DEC': 5, 'DCP': 5}
WSEL = {'STA': 0, 'STX': 1, 'STY': 2, 'SAX': 3}
SPEC = {'BRK': 1, 'JSR': 2, 'RTI': 3, 'RTS': 4, 'PHA': 5, 'PHP': 6, 'PLA': 7, 'PLP': 8,
        'JMPA': 9, 'JMPI': 10, 'TXS': 11}
FL = {'CLC': 1, 'SEC': 2, 'CLI': 3, 'SEI': 4, 'CLV': 5, 'CLD': 6, 'SED': 7}
COMBO = {'SLO': 'ORA', 'RLA': 'AND', 'SRE': 'EOR', 'RRA': 'ADC', 'DCP': 'CMP', 'ISB': 'SBC'}
IMPLIED = {  # mnemonic: (aop, bsel, dst)
    'TAX': ('LD', 'A', 'X'), 'TAY': ('LD', 'A', 'Y'), 'TXA': ('LD', 'X', 'A'),
    'TYA': ('LD', 'Y', 'A'), 'TSX': ('LD', 'S', 'X'), 'INX': ('INC', 'X', 'X'),
    'INY': ('INC', 'Y', 'Y'), 'DEX': ('DEC', 'X', 'X'), 'DEY': ('DEC', 'Y', 'Y')}


def decode(op):
    mn, mode, _, _ = OPS[op]
    md, acc, aop, asel, bsel, dst, rop, wsel, spec, fl = MD.get(mode, 6), 0, 'NONE', 'A', 'DIN', '-', 0, 0, 0, 0
    if mn in ('BRK', 'JSR', 'RTI', 'RTS', 'PHA', 'PHP', 'PLA', 'PLP'):
        md, spec = 12, SPEC[mn]
        if mn == 'PLA':
            dst = 'A'
    elif mn == 'JMP':
        md, spec = MD['abs'], SPEC['JMPA' if mode == 'abs' else 'JMPI']
    elif mode == 'rel':
        pass
    elif mn == 'TXS':
        spec = SPEC['TXS']
    elif mn in FL:
        fl = FL[mn]
    elif mn in IMPLIED:
        aop, bsel, dst = IMPLIED[mn]
    elif mode == 'acc':
        aop, bsel, dst = mn, 'A', 'A'
    elif mn in RMW_OPS:
        acc = 3
        rop = ROP[mn]
        if mn in COMBO:
            aop = COMBO[mn]
            dst = '-' if mn == 'DCP' else 'A'
    elif mn in WRITE_OPS:
        acc = 2
        wsel = WSEL[mn]
    else:
        # reads, immediates and the immediate-only illegals
        acc = 1 if mode not in ('imm', 'imp') else 0
        if mn in ('LDA',):
            aop, dst = 'LD', 'A'
        elif mn == 'LDX':
            aop, dst = 'LD', 'X'
        elif mn == 'LDY':
            aop, dst = 'LD', 'Y'
        elif mn in ('LAX', 'LXA'):
            aop, dst = 'LD', 'AX'
        elif mn in ('ORA', 'AND', 'EOR', 'ADC', 'SBC', 'ANC', 'ALR', 'ARR'):
            aop, dst = mn, 'A'
        elif mn == 'CMP':
            aop = 'CMP'
        elif mn == 'CPX':
            aop, asel = 'CMP', 'X'
        elif mn == 'CPY':
            aop, asel = 'CMP', 'Y'
        elif mn == 'BIT':
            aop = 'BIT'
        elif mn == 'SBX':
            aop, asel, dst = 'SBX', 'AX', 'X'
        elif mn == 'NOP':
            aop = 'NONE'
        else:
            raise ValueError('unhandled %s %s' % (mn, mode))
    w = (md | (acc << 4) | (AOP[aop] << 6) | (ASEL[asel] << 11) | (BSEL[bsel] << 13)
         | (DST[dst] << 16) | (rop << 19) | (wsel << 22) | (spec << 24) | (fl << 28))
    return w


def palette():
    with open(os.path.join(HERE, 'ntsc_palette.txt')) as f:
        vals = [int(t, 16) for t in f.read().split()]
    out = []
    for v in vals:
        r, g, b = ((v >> 16) & 255) / 255, ((v >> 8) & 255) / 255, (v & 255) / 255
        y = 0.299 * r + 0.587 * g + 0.114 * b
        cb = -0.168736 * r - 0.331264 * g + 0.5 * b
        cr = 0.5 * r - 0.418688 * g - 0.081312 * b
        Y = int(round(64 + 876 * y))
        U = int(round(512 + 896 * cr))      # hardware: u carries Cr
        V = int(round(512 + 896 * cb))      # hardware: v carries Cb
        out.append((min(max(Y, 64), 940), min(max(U, 64), 960), min(max(V, 64), 960)))
    return out


def main():
    dec = [decode(op) for op in range(256)]
    pal = palette()
    lines = []
    lines.append('-- Generated by tools/gen_tables.py - do not edit.')
    lines.append('-- Copyright (C) 2026 czartroniks')
    lines.append('-- SPDX-License-Identifier: GPL-3.0-only')
    lines.append('library ieee;')
    lines.append('use ieee.std_logic_1164.all;')
    lines.append('use ieee.numeric_std.all;')
    lines.append('')
    lines.append('package woodgrain_consts_pkg is')
    lines.append('    type t_dec_rom is array(0 to 255) of std_logic_vector(31 downto 0);')
    lines.append('    constant C_WG_DECODE : t_dec_rom := (')
    for i in range(0, 256, 4):
        lines.append('        ' + ', '.join('x"%08X"' % dec[j] for j in range(i, i + 4))
                     + (',' if i < 252 else ''))
    lines.append('    );')
    lines.append('    -- NTSC palette: Y(29:20) U(19:10) V(9:0); index = COLUxx(7 downto 1)')
    lines.append('    type t_pal_rom is array(0 to 127) of std_logic_vector(29 downto 0);')
    lines.append('    constant C_WG_PAL : t_pal_rom := (')
    for i in range(0, 128, 4):
        lines.append('        ' + ', '.join('"%s"' % format((y << 20) | (u << 10) | v, '030b')
                                            for y, u, v in pal[i:i + 4])
                     + (',' if i < 124 else ''))
    lines.append('    );')
    lines.append('end package woodgrain_consts_pkg;')
    path = os.path.join(HERE, '..', 'woodgrain_consts_pkg.vhd')
    with open(path, 'w') as f:
        f.write('\n'.join(lines) + '\n')
    print('wrote', os.path.normpath(path))


if __name__ == '__main__':
    main()
