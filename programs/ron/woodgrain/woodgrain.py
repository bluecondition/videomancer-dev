"""
WOODGRAIN - build hook.  Emits woodgrain_cart_pkg.vhd (the cartridge) and
woodgrain_consts_pkg.vhd (CPU decode ROM + NTSC palette).

Cartridge choice:
  cartridge.bin in this folder, if present (any 2K or 4K Atari 2600 ROM you
  have the right to use; 2K images are mirrored), else
  roms/rooms.bin, the bundled CC0 room explorer (8bitworkshop's procgen1.a,
  Steven Hugg, assembled by tools/asm6502.py from roms/rooms.a).
"""
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))


def main():
    cart = os.path.join(HERE, 'cartridge.bin')
    if not os.path.exists(cart):
        cart = os.path.join(HERE, 'roms', 'rooms.bin')
    data = open(cart, 'rb').read()
    if len(data) == 2048:
        data = data + data
    if len(data) != 4096:
        print('woodgrain: %s is %d bytes; only 2K / 4K cartridges are supported'
              % (cart, len(data)))
        return 1
    lines = ['-- Generated by woodgrain.py from %s - do not edit.' % os.path.basename(cart),
             'library ieee;',
             'use ieee.std_logic_1164.all;',
             '',
             'package woodgrain_cart_pkg is',
             '    type t_cart_rom is array(0 to 4095) of std_logic_vector(7 downto 0);',
             '    constant C_WG_CART : t_cart_rom := (']
    for i in range(0, 4096, 16):
        lines.append('        ' + ', '.join('x"%02X"' % b for b in data[i:i + 16])
                     + (',' if i < 4080 else ''))
    lines += ['    );', 'end package woodgrain_cart_pkg;']
    with open(os.path.join(HERE, 'woodgrain_cart_pkg.vhd'), 'w') as f:
        f.write('\n'.join(lines) + '\n')
    print('woodgrain: cartridge %s' % os.path.relpath(cart, HERE))
    return subprocess.call([sys.executable, os.path.join(HERE, 'tools', 'gen_tables.py')])


if __name__ == '__main__':
    sys.exit(main())
